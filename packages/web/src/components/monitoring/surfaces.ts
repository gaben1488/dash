// ────────────────────────────────────────────────────────────────
// Словарь поверхностей зоны «реестр + мониторинг» (канон п.129).
//
// Правило одно: в ТЁМНОЙ теме вложенные поверхности разделяет светлота, а не
// обводка. Плитка внутри карточки светлее самой карточки — рамка ей не нужна,
// и именно рамка на каждом атоме давала тот «частокол», которым владелец был
// недоволен. В СВЕТЛОЙ теме тонкая линия остаётся: на белом фоне разница
// светлот почти не читается.
//
// Что обводку СОХРАНЯЕТ:
//   • управление (кнопка, поле, флажок, чип) — без рамки перестаёт читаться
//     как нажимаемое;
//   • линейка таблицы — но тише текста (RULE_*);
//   • всплывающее окно — оно висит над произвольным фоном, и светлота там
//     не работает.
//
// Замер контраста в тёмной теме (страница zinc-950, карточка zinc-800/60
// поверх неё), порог различимости — 1,12 : 1:
//   карточка реестра к странице        — 1,158 : 1;
//   плитка white/[0.06] к карточке     — 1,179 : 1;
//   верхняя карточка реестра (zinc-900, сплошная) к странице — 1,123 : 1
//     (самый тесный случай зоны, но порог держит);
//   оговорка отказа чтения (amber-500/10) к карточке — 1,188 : 1
//     (прежняя заливка amber-950/20 давала 1,016 : 1 и потому держалась
//      на коричневой рамке amber-800 — той самой, на которую указывал
//      владелец; порог поднят светлотой, рамка снята).
// Почему светлота плитки поднята против канонического значения вкладки
// «Конкуренция»: white/[0.04] на этом фоне даёт 1,112 : 1 — ниже порога, а
// прежняя «плитка потемнее» (zinc-900/30) давала вовсе 1,009 : 1, то есть не
// читалась совсем — оттого ей и была нужна обводка. Порог держится светлотой,
// а не возвращённой рамкой.
// ────────────────────────────────────────────────────────────────

/**
 * Поверхность светлее страницы без заданного скругления: карточка, панель,
 * полоса. Скругление выбирает вызывающий код — иначе `rounded-lg` и
 * `rounded-xl` спорили бы в одном классе.
 */
export const SURFACE =
  'bg-white dark:bg-zinc-800/60 border border-zinc-200/70 dark:border-transparent';

/** Карточка — обычная поверхность продукта. Тень добавляет вызывающий код. */
export const CARD = `${SURFACE} rounded-xl`;

/** Вложенная плитка карточки (число с подписью, элемент списка, группа). */
export const TILE =
  'rounded-lg border border-zinc-200/70 dark:border-transparent bg-zinc-50/60 dark:bg-white/[0.06]';

/** Линейка под шапкой таблицы — тише текста, но различима в обеих темах. */
export const RULE_HEAD = 'border-b border-zinc-200/70 dark:border-white/[0.06]';

/** Линейка между строками таблицы — самая тихая линия зоны. */
export const RULE_ROW = 'border-b border-zinc-100 dark:border-white/[0.03]';

/** То же разделение строк, но линией сверху (таблицы без `tbody`-разметки). */
export const RULE_ROW_TOP = 'border-t border-zinc-100 dark:border-white/[0.03]';

/** Разделитель смысловых частей внутри одной карточки (итоги, примечания). */
export const RULE_SECTION = 'border-t border-zinc-200/70 dark:border-white/[0.06]';

/** Вертикальная линейка между группами колонок в шапке таблицы. */
export const RULE_COL_HEAD = 'border-l border-zinc-200/70 dark:border-white/[0.06]';

/** Та же вертикальная линейка в теле таблицы — тише шапочной. */
export const RULE_COL = 'border-l border-zinc-100 dark:border-white/[0.03]';

/**
 * Линейка над итоговой строкой таблицы — единственная линия зоны, которой
 * позволено быть громче соседних: строка «ВСЕГО» обязана отделяться от слагаемых
 * сразу, до чтения подписи.
 */
export const RULE_TOTAL = 'border-t-2 border-zinc-200 dark:border-white/[0.10]';

/** Линейки между строками, розданные телу таблицы разом (`divide-y`). */
export const RULE_DIVIDE = 'divide-y divide-zinc-100 dark:divide-white/[0.04]';

/**
 * Край управления — кнопки, поля, переключателя. Обводка живёт в ОБЕИХ темах:
 * снятая, она отняла бы у кнопки признак нажимаемости, и никакая светлота
 * этого не заменит. Скругление не задаётся: круглой кнопке нужен `rounded-full`.
 */
export const CONTROL_EDGE = 'border border-zinc-200 dark:border-zinc-700';

/** Обычное управление зоны: край плюс общее скругление продукта. */
export const CONTROL = `${CONTROL_EDGE} rounded-lg`;

/**
 * Флажок — управление размером в шрифт, и край ему нужен на ступень заметнее
 * кнопочного: на четырнадцати пикселях линия zinc-200 просто пропадает.
 */
export const CHECKBOX = 'rounded border-zinc-300 dark:border-zinc-600';

/** Всплывающая панель поверх страницы: обводка обязательна — фон под ней любой. */
export const OVERLAY = `${CONTROL} bg-white dark:bg-zinc-800 shadow-lg`;
