/** Число с русскими разрядами: 33 724. */
export function fmtCount(n: number | null): string {
  return n === null ? '—' : n.toLocaleString('ru-RU');
}

/** Отношение с одним знаком после запятой: 12,6. */
export function fmtRatio(n: number | null): string {
  return n === null ? '—' : n.toLocaleString('ru-RU', { maximumFractionDigits: 1 });
}

/** Момент чтения по-русски: «18 августа, 14:32». */
export function fmtMoment(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString('ru-RU', {
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
  });
}

