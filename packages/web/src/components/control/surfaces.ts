// ────────────────────────────────────────────────────────────────
// Словарь поверхностей зоны «контроль, дисциплина, аналитика» (канон п.129):
// сверка, оценки, гигиена текста, нагрузка, сроки, настройки.
//
// Правило одно: в ТЁМНОЙ теме вложенные поверхности разделяет СВЕТЛОТА, а не
// обводка. Карточка светлее страницы, плитка светлее карточки — рамка им не
// нужна, и именно рамка на каждом атоме давала тот «частокол обводок»,
// которым владелец был недоволен. В СВЕТЛОЙ теме тонкая линия остаётся: на
// белом фоне разница светлот почти не читается.
//
// Обводку сохраняют три рода:
//   • управление (кнопка, поле ввода, переключатель, чип) — без рамки
//     перестаёт читаться как нажимаемое;
//   • линейка таблицы (шапка, разделитель строк) — но самая тихая: RULE_HEAD
//     и RULE_ROW;
//   • всплывающее окно (подсказка, панель поверх страницы) — оно висит над
//     произвольным фоном, и светлота там не работает.
//
// Четвёртого рода — «смысловой рамки состояния» — больше нет, и это правка
// по существу, а не смена вкуса. Замер показал, что именно она и была теми
// «коричневыми прямоугольниками», на которые владелец жаловался: плита
// предупреждения `amber-950/20` отличалась от страницы на 1,033 : 1 (глазом
// не видно вовсе), а её обводка `amber-800` — на 2,716 : 1. Всю работу делала
// рамка, заливка не делала никакой. Сигнал теперь несут заливка нужной
// светлоты, значок и цвет текста — то есть плита целиком, а не бурый ободок
// вокруг пустоты. Словарь этих плит — `NOTE` ниже.
//
// Замеры светлот (тёмная тема, WCAG-контраст соседних поверхностей;
// порог читаемого разделения — 1,12 : 1):
//   страница zinc-950 → карточка CARD (zinc-800/60)   = 1,156 : 1
//   карточка CARD     → плитка TILE  (white/[0.05])   = 1,145 : 1
//   карточка CARD     → полоса шапки HEAD_STRIP       = 1,145 : 1
//   карточка CARD     → врезка кода (zinc-950, вниз)  = 1,162 : 1
//   плитка TILE       → страница zinc-950             = 1,324 : 1
//
// Почему плитка взята светлее канонического значения вкладки «Конкуренция»:
// над карточкой zinc-800/60 плитка white/[0.04] даёт 1,112 : 1 — ниже порога,
// её граница уже угадывается, а не видится. Прежние же поверхности зоны были
// вовсе ТЕМНЕЕ карточки (zinc-900/30 = 1,011 : 1, zinc-900/40 = 1,014 : 1,
// шапка таблицы zinc-900/50 = 1,018 : 1 — то есть не читались совсем) — оттого
// им и была нужна обводка. Недостающую светлоту здесь добирают фоном, а не
// возвращённой рамкой.
//
// Одно исключение из «светлее»: врезка с текстом файла уходит ВНИЗ по
// светлоте. Разделение читается ровно так же (1,162 : 1), а смысл при этом
// прямее: содержимое файла — не ещё одна карточка продукта.
// ────────────────────────────────────────────────────────────────

/**
 * Каркас карточки: белый лист в светлой теме, поверхность на ступень светлее
 * страницы — в тёмной. Скругление и тень объявляет место вызова: у сверки
 * карточки шире, чем у настроек.
 */
export const CARD =
  'bg-white dark:bg-zinc-800/60 border border-zinc-200/70 dark:border-transparent';

/**
 * Светлота и обводка плитки БЕЗ скругления — для мест, где радиус уже
 * объявлен рядом (`rounded-xl` у паспорта данных, у карточки источника).
 * Второго дома у этих значений нет: `TILE` собирается отсюда же.
 */
export const TILE_SKIN =
  'border-zinc-200/70 dark:border-transparent bg-zinc-50/60 dark:bg-white/[0.05]';

/**
 * Вложенная плитка карточки — число с подписью, элемент списка, группа,
 * врезка с пояснением. Светлее карточки ровно настолько, чтобы граница
 * читалась без линии.
 */
export const TILE = `rounded-lg border ${TILE_SKIN}`;

/**
 * Плита-оговорка, лежащая на САМОЙ странице, а не внутри карточки: пояснение
 * перед числами, врезка с методикой, серый блок примечания. Светлота у неё
 * карточная, а не плиточная, и это не прихоть: над почти чёрной страницей
 * плитка white/[0.05] даёт всего 1,096 : 1 — ниже порога, тогда как та же
 * ступень zinc-800/60 даёт 1,159 : 1. В светлой теме фон остаётся серым:
 * оговорка не должна выглядеть таким же чистым листом, как карточка данных.
 */
export const PLATE =
  'bg-zinc-50 dark:bg-zinc-800/60 border border-zinc-200/70 dark:border-transparent';

/**
 * Цвет линейки шапки таблицы и разделителя смысловых частей внутри карточки.
 * Сторону (`border-b`, `border-t`) объявляет место вызова.
 */
export const RULE_HEAD = 'border-zinc-200/70 dark:border-white/[0.06]';

/** Цвет линейки между строками таблицы — самая тихая линия зоны. */
export const RULE_ROW = 'border-zinc-100 dark:border-white/[0.03]';

/**
 * Те же линейки, розданные телу таблицы разом (`divide-y`). Прежнее
 * `dark:divide-zinc-700/50` давало на карточке линию светлее самой плитки —
 * это и был «частокол» на восьми таблицах зоны сразу. Линейка остаётся:
 * без неё строки слипаются, — но становится тише текста, а не громче него.
 */
export const RULE_DIVIDE = 'divide-y divide-zinc-100 dark:divide-white/[0.04]';

/**
 * Полоса шапки таблицы. В тёмной теме она СВЕТЛЕЕ карточки, а не темнее:
 * прежнее `dark:bg-zinc-900/50` давало 1,02 : 1 к карточке — шапка попросту
 * сливалась с телом таблицы, и держала её одна линейка. Теперь держит
 * светлота (1,139 : 1), а линейка ей только помогает.
 */
export const HEAD_STRIP = 'bg-zinc-50 dark:bg-white/[0.05]';

/**
 * Управление: кнопка, поле ввода, переключатель. Обводка живёт в обеих темах —
 * без неё поле перестаёт читаться как поле.
 */
export const CONTROL = 'border border-zinc-200 dark:border-zinc-700';

/**
 * Смысловые плиты состояния: предупреждение, сбой, успех, пояснение. Цвет
 * здесь — данные, а не хром, поэтому заливка остаётся окрашенной в обеих
 * темах; уходит только тёмная обводка, которая и давала «коричневый
 * прямоугольник».
 *
 * Доля заливки подобрана так, чтобы плита читалась И на странице (zinc-950),
 * И внутри карточки (zinc-800/60) — у плиты нет одного постоянного соседа.
 * Замеры к странице / к карточке при пороге 1,12 : 1:
 *   янтарь    amber-500/[0.12]    1,175 : 1  /  1,236 : 1
 *   сбой      red-500/[0.16]      1,151 : 1  /  1,184 : 1
 *   успех     emerald-500/[0.12]  1,150 : 1  /  1,200 : 1
 *   пояснение blue-500/[0.10]     1,127 : 1  /  1,178 : 1
 * Красному и «синему» дано больше доли не по прихоти: их собственная светлота
 * ниже янтарной, и на равной доле они бы просто не проявились. «Синий» здесь
 * в кавычках: `tailwind.config.ts` переводит всю палитру blue/sky/indigo в
 * крем, поэтому пояснительная плита выходит кремовой — как и весь хром.
 *
 * Доля пишется в скобках (`/[0.12]`), а не числом (`/12`): шкала прозрачности
 * Tailwind знает только 0, 5, 10, 20, 25, 30, 40, 50, 60, 70, 75, 80, 90, 95,
 * 100, и класс с долей вне шкалы не рождается вовсе — заливка молча исчезает,
 * а проверка типов об этом не скажет ни слова.
 *
 * Скругление, отступы и цвет текста объявляет место вызова — плита-оговорка
 * и плита-строка состояния делят цвет, но не размер.
 */
export const NOTE = {
  amber: 'border-amber-200 dark:border-transparent bg-amber-50/60 dark:bg-amber-500/[0.12]',
  red: 'border-red-200 dark:border-transparent bg-red-50/60 dark:bg-red-500/[0.16]',
  emerald: 'border-emerald-200 dark:border-transparent bg-emerald-50/60 dark:bg-emerald-500/[0.12]',
  blue: 'border-blue-200 dark:border-transparent bg-blue-50/60 dark:bg-blue-500/[0.10]',
} as const;
