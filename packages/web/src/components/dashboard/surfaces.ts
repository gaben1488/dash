// ────────────────────────────────────────────────────────────────
// Словарь поверхностей зоны «Пульт и Отчёт» (канон п.129).
//
// Правило одно: в ТЁМНОЙ теме вложенные поверхности разделяет СВЕТЛОТА, а не
// обводка. Карточка светлее страницы, плитка светлее карточки — рамка им не
// нужна, и именно рамка на каждом атоме давала тот «частокол обводок»,
// которым владелец был недоволен. В СВЕТЛОЙ теме тонкая линия остаётся: на
// белом фоне разница светлот почти не читается.
//
// Обводку сохраняют только три рода:
//   • управление (кнопка, поле, переключатель, чип) — без рамки перестаёт
//     читаться как нажимаемое;
//   • линейка таблицы (шапка, разделитель строк) — но самая тихая: RULE_HEAD
//     и RULE_ROW;
//   • всплывающее окно (подсказка, панель поверх страницы) — оно висит над
//     произвольным фоном, и светлота там не работает.
//
// Замеры светлот (тёмная тема, WCAG-контраст соседних поверхностей;
// порог читаемого разделения — 1,12:1):
//   страница zinc-950 → карточка CARD (zinc-800/60)   = 1,157:1
//   карточка CARD     → плитка TILE  (white/[0.05])   = 1,144:1
//   плитка TILE       → страница zinc-950             = 1,325:1
//   плитка TILE       → шапка внутри плитки (0,05)    = 1,161:1
//
// Почему 0,05, а не 0,04, как в словаре соседних вкладок: над карточкой
// zinc-800/60 плитка white/[0.04] даёт 1,112:1 — ниже порога, граница
// плитки уже угадывается, а не видится. Лишнюю светлоту здесь добирают
// фоном, а не возвращённой рамкой.
//
// Замеры не остаются на словах: их считает страж `surface-contrast.test.ts`
// прямо из строк этого файла. Уронить ступень ниже порога и не заметить
// больше нельзя — тест назовёт число.
// ────────────────────────────────────────────────────────────────

/**
 * Подложка карточки без края — белый лист в светлой теме, ступень светлее
 * страницы в тёмной. Отдельно от `CARD` она нужна карточкам, у которых край
 * несёт СИГНАЛ (тревога, предупреждение): там обводка своя, цветная, а фон
 * обязан остаться общим — иначе у одного фона появилось бы два дома.
 */
export const CARD_SURFACE = 'bg-white dark:bg-zinc-800/60';

/**
 * Каркас карточки: подложка плюс край. Радиус и тень объявляет место вызова:
 * у Пульта карточки крупнее, чем у Свода.
 */
export const CARD = `border border-zinc-200/60 dark:border-transparent ${CARD_SURFACE}`;

/**
 * Вложенная плитка карточки — число с подписью, элемент списка, группа.
 * Светлее карточки ровно настолько, чтобы граница читалась без линии.
 */
export const TILE =
  'rounded-lg border border-zinc-200/70 dark:border-transparent bg-zinc-50/60 dark:bg-white/[0.05]';

/**
 * Цвет линейки шапки таблицы и разделителя разделов внутри карточки. Сторону
 * (`border-b`, `border-t`, `border-l`) объявляет место вызова.
 */
export const RULE_HEAD = 'border-zinc-200/70 dark:border-white/[0.06]';

/** Цвет линейки между строками таблицы — самая тихая линия зоны. */
export const RULE_ROW = 'border-zinc-100 dark:border-white/[0.03]';
