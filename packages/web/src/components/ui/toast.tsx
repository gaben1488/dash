// ── Уведомление: короткое сообщение о том, что случилось после действия.
//
//    ЧТО ВЗЯТО ГОТОВЫМ (канон п.112). Библиотека `sonner` (MIT, без
//    зависимостей, React 19 объявлен явно). Она даёт то, что мы бы иначе
//    писали неделю и хуже: очередь сообщений, наложение карточек стопкой,
//    остановку отсчёта при наведении и при уходе вкладки в фон, область
//    живого объявления для диктора (`aria-live="polite"` — сообщение не
//    перебивает читателя на середине фразы) и горячую клавишу, которая
//    переводит фокус на стопку с клавиатуры.
//
//    ЧТО НАДСТРОЕНО (канон п.114). Библиотека знает про всплывающую
//    карточку и ничего не знает про наш продукт. Поверх неё положено
//    четыре правила:
//
//    1. КРАСКИ ИЗ СЛОВАРЯ РОЛЕЙ. У `sonner` своя палитра и светлая тема по
//       умолчанию. Здесь ей не разрешено ни одного собственного цвета:
//       всё задано переменными, которые библиотека читает
//       (`--normal-bg`, `--error-*` и прочие), и тема прокидывается из
//       нашего хранилища. Иначе на тёмной теме уведомление приезжало бы
//       белым прямоугольником поверх почти чёрного экрана.
//
//    2. У ОТКАЗА ОБЯЗАТЕЛЬНО ЕСТЬ «ЧТО ДЕЛАТЬ». Это канон п.53: сообщение
//       несёт механизм, адрес и действие. Тип `notifyProblem` не
//       собирается без поля `whatToDo` — забыть его нельзя.
//
//    3. УВЕДОМЛЕНИЕ НЕ ЕДИНСТВЕННЫЙ КАНАЛ. Оно исчезает через несколько
//       секунд, поэтому в нём не может жить то, что читателю понадобится
//       позже: число, адрес строки, подробность отказа. Уведомление
//       говорит «получилось» или «не получилось и вот что делать», а
//       подробность остаётся на экране — в карточке, в пустом состоянии,
//       в журнале. Отсюда обязательное поле `where` у отказа: куда пойти
//       за подробностью.
//
//    4. ПО-РУССКИ ВСЁ, ВКЛЮЧАЯ НЕВИДИМОЕ. Имя области для диктора и
//       подпись кнопки закрытия у библиотеки английские по умолчанию.

import { Toaster as SonnerToaster, toast } from 'sonner';
import { useTheme } from '../ThemeProvider';

/**
 * Стопка уведомлений. Ставится один раз в корне приложения.
 *
 * Положение — снизу справа: сверху живёт шапка с периодом и обновлением,
 * и уведомление, выезжающее сверху, закрывало бы ровно то управление,
 * которым его только что вызвали.
 */
export function Toaster() {
  const theme = useTheme((s) => s.theme);

  return (
    <SonnerToaster
      // Тему прокидываем явно: умолчание библиотеки — светлая, и на нашей
      // тёмной она давала белый прямоугольник поверх почти чёрного экрана.
      theme={theme}
      position="bottom-right"
      // Отсчёт по умолчанию у библиотеки короткий. Читатель этого продукта
      // смотрит в таблицу, а не в угол экрана, и обязан успеть прочитать.
      duration={6000}
      closeButton
      containerAriaLabel="Уведомления"
      toastOptions={{
        closeButtonAriaLabel: 'Закрыть уведомление',
        // Ни одной собственной краски у библиотеки: и заливка, и линия, и
        // чернила берутся из словаря ролей, поэтому обе темы правятся в
        // одном месте вместе со всем остальным продуктом.
        style: {
          background: 'var(--surface-overlay)',
          color: 'var(--ink)',
          border: '1px solid var(--line-strong)',
          borderRadius: 'var(--radius-card)',
          boxShadow: 'var(--elevation-3)',
          fontSize: 'var(--text-2xs)',
        },
        classNames: {
          title: 'ds-text-2xs',
          description: 'ds-text-3xs',
        },
      }}
    />
  );
}

export interface NotifyDoneOptions {
  /** Подробность одной строкой: «прочитано 318 строк, из них новых 4». */
  detail?: string;
}

/**
 * Получилось. Тон — благополучный, но без ликования: продукт сообщает
 * факт, а не поздравляет.
 */
export function notifyDone(what: string, options?: NotifyDoneOptions): void {
  toast.success(what, { description: options?.detail });
}

export interface NotifyProblemOptions {
  /** Отчего не вышло. Механизм, а не ярлык: «сервер не ответил за 30 секунд». */
  reason: string;
  /**
   * Что делать читателю. Обязательно (канон п.53): отказ без названного
   * действия читатель исполнить не может.
   */
  whatToDo: string;
  /**
   * Где смотреть подробность. Уведомление исчезает — подробность обязана
   * остаться на экране: «подробность отказа — на вкладке „Система“».
   */
  where?: string;
  /** Действие прямо из уведомления: «Повторить». */
  action?: { label: string; onClick: () => void };
}

/**
 * Не получилось.
 *
 * Три части сообщения — механизм, действие и адрес подробности — не
 * пожелание к автору вызова, а поля типа: без `reason` и `whatToDo`
 * вызов не компилируется.
 */
/**
 * Текст отказа: механизм, действие, адрес подробности (канон п.53).
 *
 * Вынесен отдельно и от вызова, и от замены, потому что дом у этого
 * правила должен быть один: два места сборки одной и той же фразы
 * разъезжаются на первой же правке формулировки.
 */
export function problemText(options: NotifyProblemOptions): string {
  return options.where
    ? `${options.reason}. ${options.whatToDo}. Подробность — ${options.where}.`
    : `${options.reason}. ${options.whatToDo}.`;
}

export function notifyProblem(what: string, options: NotifyProblemOptions): void {
  toast.error(what, {
    description: problemText(options),
    action: options.action,
    // Отказ не уезжает сам: читатель мог смотреть в другую часть экрана,
    // а потерянное сообщение об отказе — это потерянный отказ.
    duration: Infinity,
  });
}

/**
 * Идёт долгая работа. Возвращает опознаватель, которым сообщение потом
 * заменяется на итог, — чтобы на экране не копилась стопка из «идёт
 * чтение книги» и «книга прочитана».
 */
export function notifyWorking(what: string): string | number {
  return toast.loading(what);
}

/** Заменить сообщение о работе итогом. */
export function notifyReplaceDone(id: string | number, what: string, detail?: string): void {
  toast.success(what, { id, description: detail, duration: 6000 });
}

/** Заменить сообщение о работе отказом. */
export function notifyReplaceProblem(id: string | number, what: string, options: NotifyProblemOptions): void {
  toast.error(what, { id, description: problemText(options), action: options.action, duration: Infinity });
}

/** Убрать уведомление досрочно. */
export function dismissNotification(id?: string | number): void {
  toast.dismiss(id);
}
