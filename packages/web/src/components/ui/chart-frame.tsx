// ── Рама графика: то, чего библиотека рисования не знает.
//
//    ЧТО ВЗЯТО ГОТОВЫМ (канон п.112). Рисует Recharts, и менять его не на
//    что: сравнение по нашим осям (вес, доступность, тёмная тема, живость)
//    сделано в `2026-08-18-design-system.md` §1.5. Приём «переменная CSS
//    прямо в атрибуте SVG» взят у графиков shadcn/ui и живёт в
//    `chart-theme.ts` — благодаря ему график не знает про тему вовсе.
//
//    ЧТО НАДСТРОЕНО (канон п.114). Библиотека рисования умеет рисовать, но
//    про наш предмет не знает четырёх вещей, и каждая из них — источник
//    ошибки чтения ценой в три порядка:
//
//    1. ДВЕ ШКАЛЫ ДЕНЕГ. Книга мониторинга ведёт НМЦК в рублях, книги свода
//       и отчёта — в тысячах. Один и тот же столбик высотой «1 200» — это
//       либо тысяча двести рублей, либо миллион двести тысяч. Поэтому
//       единица здесь — обязательное поле рамы, а не подпись, которую
//       можно забыть: график без названной единицы не собирается.
//
//    2. ДОЛЯ БЫВАЕТ СЧЁТНОЙ И ДЕНЕЖНОЙ, и они расходятся вдвое: закупок у
//       единственного поставщика может быть 80 процентов по счёту и
//       12 процентов по деньгам. Показать одну без второй — значит дать
//       читателю сделать вывод, обратный правде. `SharePair` не даёт
//       назвать долю, не назвав, какую именно.
//
//    3. ПУСТОТА ОБЯЗАНА НАЗВАТЬ ПРИЧИНУ. Пустое полотно с осями выглядит
//       как «нулей на графике», хотя означает «строк не нашлось» или
//       «фильтр вычел всё». Рама не отдаёт полотно, пока в него нечего
//       рисовать, и вместо него ставит причину и следующий шаг.
//
//    4. ТЕКСТОВЫЙ ДУБЛЬ ВИЗУАЛЬНОГО (канон 01.08). То, что видно глазами,
//       обязано быть сказано словами: печать бывает чёрно-белой, один
//       читатель из двенадцати не различает красный и зелёный, а диктор
//       не читает SVG вовсе. Рама даёт для этого место (`summary`) и
//       прячет само полотно от диктора, чтобы он не читал координаты.
//
//    Высота полотна задаётся заранее и не зависит от того, приехали ли
//    данные: иначе карточка подпрыгивает в момент загрузки.

import type { ReactNode } from 'react';
import clsx from 'clsx';

/**
 * Шкала денег. Не оформление, а смысл: перепутанная шкала — это ошибка в
 * тысячу раз, самая дорогая из тех, что этот продукт может допустить.
 */
export type MoneyScale = 'руб' | 'тыс' | 'млн' | 'млрд';

/** Подпись шкалы для оси и подсказки. */
export const MONEY_SCALE_LABEL: Readonly<Record<MoneyScale, string>> = {
  'руб': '₽',
  'тыс': 'тыс ₽',
  'млн': 'млн ₽',
  'млрд': 'млрд ₽',
};

/** Фраза о шкале для читателя: что он увидит, переключив режим. */
export const MONEY_SCALE_HINT: Readonly<Record<MoneyScale, string>> = {
  'руб': 'суммы читаются в рублях — так их ведёт книга мониторинга',
  'тыс': 'суммы читаются в тысячах рублей — так их ведут свод и отчёт',
  'млн': 'суммы читаются в миллионах рублей',
  'млрд': 'суммы читаются в миллиардах рублей',
};

export interface ChartFrameProps {
  /**
   * В чём измерена вертикальная ось. Обязательно и для денег, и для
   * счёта: «тыс ₽», «закупок», «дней». Ось без единицы — число без смысла.
   */
  unit: string;
  /**
   * Причина, по которой рисовать нечего. Задана — полотно не строится
   * вовсе, на его месте стоит объяснение. Пустое полотно с осями врёт:
   * оно читается как «все значения нулевые».
   */
  emptyReason?: string;
  /**
   * Что здесь видно, словами. Обязательно: это единственное, что
   * останется на чёрно-белой печати и единственное, что услышит диктор.
   * «Доля единственного поставщика падает четвёртую неделю подряд».
   */
  summary: string;
  /** Высота полотна. Задана заранее, чтобы карточка не прыгала. */
  height?: number;
  /** Само полотно — узел Recharts. */
  children?: ReactNode;
  className?: string;
}

export function ChartFrame({
  unit,
  emptyReason,
  summary,
  height = 220,
  children,
  className,
}: ChartFrameProps) {
  const empty = emptyReason != null || children == null;

  return (
    <figure className={clsx('m-0 min-w-0', className)}>
      <div className="mb-1 flex items-baseline justify-between gap-[var(--space-2)]">
        <span className="ds-text-3xs text-[var(--ink-faint)]" data-unit>
          {unit}
        </span>
      </div>

      {/* Высота держится и в пустоте, и с данными: подмена содержимого не
          двигает то, что стоит под графиком. */}
      <div style={{ height }} className="relative">
        {empty ? (
          <div
            data-empty
            className="flex h-full flex-col items-center justify-center rounded-[var(--radius-card)] border border-dashed border-[var(--line-soft)] px-[var(--space-4)] text-center"
          >
            <p className="ds-text-2xs ds-prose text-[var(--ink-muted)]">
              {emptyReason ?? 'Рисовать нечего: ряд не передан'}
            </p>
          </div>
        ) : (
          // Полотно скрыто от диктора намеренно: он прочитал бы координаты
          // точек, а не смысл. Смысл — в подписи ниже.
          <div aria-hidden="true" className="h-full">
            {children}
          </div>
        )}
      </div>

      {/* Текстовый дубль визуального. Стоит под графиком и виден всем — не
          спрятан в `sr-only`: зрячий читатель тоже имеет право на вывод,
          а не только на картинку. */}
      <figcaption className="mt-[var(--space-2)] ds-text-2xs ds-prose text-[var(--ink-muted)]">
        {summary}
      </figcaption>
    </figure>
  );
}

export interface SharePairProps {
  /** Доля по счёту закупок, готовой строкой: «80,4 %». */
  byCount: string | null;
  /** Доля по деньгам, готовой строкой: «12,1 %». */
  byMoney: string | null;
  /** Чего доля: «закупки у единственного поставщика». */
  of: string;
  /** Отчего доли нет — когда база пуста. */
  emptyReason?: string;
  className?: string;
}

/**
 * Пара долей: счётная и денежная рядом, обе подписаны.
 *
 * Почему пара, а не одно число. Доля закупок у единственного поставщика по
 * счёту и по деньгам расходятся в разы, и каждая из них по отдельности
 * ведёт к противоположному выводу: «почти всё — ЕП» против «ЕП почти не
 * стоит денег». Показывать одну без второй продукт не имеет права.
 */
export function SharePair({ byCount, byMoney, of, emptyReason, className }: SharePairProps) {
  const empty = byCount === null && byMoney === null;

  if (empty) {
    return (
      <p className={clsx('ds-text-2xs text-[var(--ink-faint)]', className)} data-empty>
        {emptyReason ?? `Доля не считана: базы для «${of}» нет`}
      </p>
    );
  }

  return (
    <div className={clsx('flex flex-wrap items-baseline gap-x-[var(--space-4)] gap-y-1', className)}>
      <div>
        <div className="ds-text-3xs text-[var(--ink-faint)]">по счёту закупок</div>
        <div className="ds-text-lg font-[var(--weight-strong)] tabular-nums text-[var(--ink-strong)]" data-numeric>
          {byCount ?? '—'}
        </div>
      </div>
      <div>
        <div className="ds-text-3xs text-[var(--ink-faint)]">по деньгам</div>
        <div className="ds-text-lg font-[var(--weight-strong)] tabular-nums text-[var(--ink-strong)]" data-numeric>
          {byMoney ?? '—'}
        </div>
      </div>
      <p className="ds-text-3xs ds-prose basis-full text-[var(--ink-faint)]">
        Доля чего: {of}. Счётная и денежная доли расходятся — вывод делается по обеим.
      </p>
    </div>
  );
}
