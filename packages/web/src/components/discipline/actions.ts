/** Вклад одного управления в дело. */
export interface DeptShare {
  /** Ключ управления как в строках (латинский id DTO). */
  dept: string;
  rows: number;
  money: number;
}

/** Собранное дело: класс + счёт + деньги + разбивка по управлениям. */
export interface DisciplineAction {
  def: DisciplineActionDef;
  rows: number;
  /** Эффект дела, тыс. руб. (Σ plan либо fact по строкам класса). */
  money: number;
  /** Вклад управлений, по убыванию денег. */
  byDept: DeptShare[];
}

export interface DisciplineSummary {
  /** Дела с хотя бы одной строкой, по убыванию денег эффекта. */
  actions: DisciplineAction[];
  /** Число дел в списке. */
  totalActions: number;
  /** Уникальные строки, ждущие действия (строка в двух делах считается одной). */
  totalRows: number;
  /**
   * Деньги уникальных строк, тыс. руб.: строка входит один раз — планом, если
   * участвует в «плановом» деле, иначе фактом. Сумма НЕ равна сумме дел, если
   * одна строка попала в два дела, — и не должна: это деньги строк, а не дел.
   */
  totalMoney: number;
}

const num = (v: unknown): number => {
  const n = typeof v === 'number' ? v : parseFloat(String(v ?? ''));
  return Number.isFinite(n) && n > 0 ? n : 0;
};

/** Сборка списка дел из строк реестра. Чистая функция — см. actions.test.ts. */
export function buildDisciplineActions(rows: readonly DisciplineRow[]): DisciplineSummary {
  const perAction = new Map<string, { rows: number; money: number; byDept: Map<string, DeptShare> }>();
  let totalRows = 0;
  let totalMoney = 0;

  for (const row of rows) {
    const signals = row.signals ?? [];
    if (signals.length === 0) continue;
    let inPlanAction = false;
    let inFactAction = false;

    for (const def of DISCIPLINE_ACTIONS) {
      if (!signals.includes(def.signal)) continue;
      const money = def.money === 'plan' ? num(row.planSum) : num(row.factSum);
      let acc = perAction.get(def.signal);
      if (!acc) {
        acc = { rows: 0, money: 0, byDept: new Map() };
        perAction.set(def.signal, acc);
      }
      acc.rows += 1;
      acc.money += money;
      const deptKey = row.dept ?? '';
      let share = acc.byDept.get(deptKey);
      if (!share) {
        share = { dept: deptKey, rows: 0, money: 0 };
        acc.byDept.set(deptKey, share);
      }
      share.rows += 1;
      share.money += money;
      if (def.money === 'plan') inPlanAction = true;
      else inFactAction = true;
    }

    if (inPlanAction || inFactAction) {
      totalRows += 1;
      // Строка входит в итог один раз: планом, если хоть одно её дело плановое.
      totalMoney += inPlanAction ? num(row.planSum) : num(row.factSum);
    }
  }

  const actions: DisciplineAction[] = DISCIPLINE_ACTIONS.filter((d) => perAction.has(d.signal))
    .map((def) => {
      const acc = perAction.get(def.signal)!;
      return {
        def,
        rows: acc.rows,
        money: acc.money,
        byDept: [...acc.byDept.values()].sort((a, b) => b.money - a.money || b.rows - a.rows),
      };
    })
    .sort((a, b) => b.money - a.money || b.rows - a.rows);

  return { actions, totalActions: actions.length, totalRows, totalMoney };
}

/**
 * Тон денег эффекта — единственное место цвета в карточке дела (бриф: никаких
 * алых ярлыков, критичность цветом только у денег). Пороги в тыс. руб.
 */
export function moneyToneClass(money: number): string {
  if (money >= 50_000) return 'text-rose-600 dark:text-rose-400';
  if (money >= 5_000) return 'text-amber-600 dark:text-amber-400';
  return 'text-zinc-800 dark:text-zinc-100';
}
