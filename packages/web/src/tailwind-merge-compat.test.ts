import { describe, expect, it } from 'vitest';
import { cn } from './lib/utils';

/**
 * Страж совместимости слияния классов оформления (правка 18.08.2026).
 *
 * Библиотека слияния классов третьей ветки собрана под четвёртую ветку
 * Tailwind: она разрешает конфликты по чужой шкале имён, из-за чего
 * переопределение через свойство класса могло молча не срабатывать.
 * У нас Tailwind третьей ветки, поэтому закреплена вторая ветка библиотеки.
 * Тест проверяет, что последний аргумент по-прежнему побеждает.
 */
describe('слияние классов оформления', () => {
  it('последний цвет фона побеждает', () => {
    expect(cn('bg-red-500', 'bg-blue-500')).toBe('bg-blue-500');
  });

  it('переопределение отступа снаружи побеждает вариант компонента', () => {
    expect(cn('px-4 py-2', 'px-6')).toBe('py-2 px-6');
  });

  it('скругление третьей ветки разрешается верно', () => {
    expect(cn('rounded-sm', 'rounded-lg')).toBe('rounded-lg');
  });

  it('тень третьей ветки разрешается верно', () => {
    expect(cn('shadow-sm', 'shadow-md')).toBe('shadow-md');
  });

  it('несвязанные классы сохраняются оба', () => {
    expect(cn('text-zinc-800', 'bg-white')).toBe('text-zinc-800 bg-white');
  });

  it('условные значения не ломают слияние', () => {
    const off = false as boolean; // так условные классы пишутся в компонентах
    expect(cn('p-2', off && 'p-4', undefined, 'p-6')).toBe('p-6');
  });
});
