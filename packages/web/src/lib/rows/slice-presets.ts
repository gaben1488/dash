/** Срез по ключу; неизвестный ключ — null, а не молчаливый пропуск отбора. */
export function findSlicePreset(id: string | null): RegistrySlicePreset | null {
  if (id === null) return null;
  return REGISTRY_SLICE_PRESETS.find((p) => p.id === id) ?? null;
}

/**
 * Сколько загруженных строк проходит каждый срез. Счёт идёт по строкам ДО
 * фильтров экрана — иначе подпись кнопки зависела бы от неё самой.
 */
export function slicePresetCounts(rows: readonly SliceRow[]): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const preset of REGISTRY_SLICE_PRESETS) counts[preset.id] = 0;
  for (const row of rows) {
    for (const preset of REGISTRY_SLICE_PRESETS) {
      if (preset.predicate(row)) counts[preset.id] += 1;
    }
  }
  return counts;
}
