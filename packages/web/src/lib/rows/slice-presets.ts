/**
 * Пресеты срезов Реестра — именованные отборы строк в один щелчок.
 *
 * Зачем отдельный дом. Фильтр «Признаки строки» умеет выбрать один ключ
 * признака; читателю же нужны готовые вопросы («что требует разбора?»,
 * «где экономия есть, а отметка не проставлена?»), каждый из которых
 * собирается из нескольких признаков или из полей строки, признаком не
 * описанных. Раньше такие отборы дописывались прямо в страницу отдельными
 * переключателями — по одному на случай, каждый со своей подписью и своей
 * пустотой. Здесь они лежат списком: страница рисует их одинаково, а новый
 * срез — это ОДНА запись в массиве ниже, без правки разметки.
 *
 * Что обязана нести каждая запись (стандарт п.53 и п.119):
 *   • label — существительное или именная группа, не глагол-команда;
 *   • mechanism — какие строки отбираются и по каким полям книги, словами;
 *   • emptyReason — почему срез пуст ИМЕННО СЕЙЧАС и что делать читателю
 *     (честная пустота: «в классе никого» ≠ «фильтры всё срезали»);
 *   • predicate — ровно тот признак, которым считает движок, а не его
 *     пересказ: расхождение предиката и сигнала даёт два разных числа под
 *     одним словом.
 *
 * Срез НИЧЕГО не грузит и ни за чем не ходит: он работает по уже прочитанным
 * строкам, поэтому его счёт всегда сходится со счётом реестра над ним.
 *
 * ── Как добавить срез ────────────────────────────────────────────────────
 *   {
 *     id: 'economy_without_flag',
 *     label: 'Экономия без отметки',
 *     mechanism: 'В строке есть числовая экономия, а графа «Статус» (AD) пуста…',
 *     emptyReason: 'Среди загруженных строк такого сочетания нет…',
 *     predicate: (r) => hasSignal(r, 'economyFlagMissing'),
 *   }
 * Ключ сигнала и предикат обязаны прийти из движка проверок; выдумывать
 * условие здесь нельзя — тогда срез начнёт спорить с чипом на строке.
 */
import { ECONOMY_FLAG_CANON, ECONOMY_NOISE_THOUSAND } from '@aemr/shared';
import { rowHasPeriodDate, signalSeverity } from './registry-view';

/** Строка реестра глазами среза: только признаки и числа, ничего лишнего. */
export interface SliceRow {
  signals?: string[];
  planSum?: number;
  factSum?: number;
  economy?: number;
  [key: string]: unknown;
}

export interface RegistrySlicePreset {
  /** Служебный ключ; на экран не выходит. */
  id: string;
  /** Подпись кнопки — обывательский русский, без внутренних имён. */
  label: string;
  /** Механизм отбора простыми словами: какие строки и по каким полям. */
  mechanism: string;
  /** Честная причина пустоты среза при непустой загрузке. */
  emptyReason: string;
  /** Предикат отбора — тот же, которым считает движок проверок. */
  predicate: (row: SliceRow) => boolean;
  /**
   * Экономию в этом срезе читать по числам (план минус факт), а не по графам
   * экономии книги.
   *
   * Зачем оговорка. Графы Z/AA/AB заполняет формула листа ТОЛЬКО после
   * отметки «да» в графе «Статус» (AD). У класса «Экономия без отметки»
   * отметки как раз нет, поэтому столбец экономии у почти всех его строк пуст
   * — читатель видел бы срез «про экономию», в котором экономии не показано
   * ни на одной строке. Флаг велит показать разность плана и факта и назвать
   * её долю от плана, оговорив происхождение числа у самого числа (п.58).
   */
  economyByNumbers?: boolean;
}

/**
 * Экономия строки по числам: план минус факт и доля от плана.
 *
 * Порог шума и условия — те же, что у канона явления (@aemr/shared
 * economy-flag.ts): своих правил счёта здесь нет, иначе столбец начал бы
 * спорить с чипом на той же строке. Строка без плана, без факта или с
 * копеечной разностью числа не даёт — возвращается null, и ячейка говорит
 * то же, что говорила бы без среза.
 */
export function numericEconomyOf(row: SliceRow): { economy: number; sharePct: number } | null {
  const plan = Number(row.planSum);
  const fact = Number(row.factSum);
  if (!Number.isFinite(plan) || !Number.isFinite(fact)) return null;
  if (plan <= 0 || fact <= 0) return null;
  const economy = plan - fact;
  if (economy <= ECONOMY_NOISE_THOUSAND) return null;
  return { economy, sharePct: (economy / plan) * 100 };
}

/** Куда ведёт затравка перехода: в именованный срез или в фильтр признаков. */
export interface RegistrySeedRouting {
  /** Ключ среза, если затравка называет именно его. */
  slicePresetId: string | null;
  /** Ключи признаков для обычного фильтра — всё, что срезом не является. */
  signals: string[];
}

/**
 * Разбор затравки перехода в Реестр (`navigateTo('data', { signals })`).
 *
 * Кнопка-чип карточки «Пульта» или «Экономии» присылает ключ класса. Если у
 * класса есть именованный срез — читатель попадает не в безымянный отбор по
 * признаку, а в тот самый срез: с подписью, механизмом отбора и честной
 * причиной пустоты. Ключ среза и ключ признака у таких классов один и тот же
 * (см. `ECONOMY_FLAG_CANON.signal`), поэтому карточке не нужно знать про
 * устройство Реестра — достаточно назвать класс.
 *
 * Затравка из нескольких ключей срезом не считается: срез отвечает на один
 * вопрос, а несколько признаков — это обычный фильтр.
 */
export function splitRegistrySeed(seed: readonly string[]): RegistrySeedRouting {
  if (seed.length === 1 && findSlicePreset(seed[0]) !== null) {
    return { slicePresetId: seed[0], signals: [] };
  }
  return { slicePresetId: null, signals: [...seed] };
}

/** Признаки строки как массив: у части строк графы нет вовсе. */
export function rowSignals(row: SliceRow): string[] {
  return Array.isArray(row.signals) ? row.signals : [];
}

/** Есть ли у строки признак с такой тяжестью. */
function hasSeverity(row: SliceRow, severity: 'critical' | 'warning'): boolean {
  return rowSignals(row).some((s) => signalSeverity(s) === severity);
}

/** Несёт ли строка названный признак. */
function hasSignal(row: SliceRow, key: string): boolean {
  return rowSignals(row).includes(key);
}

