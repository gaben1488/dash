/**
 * outside-44fz.ts — класс строки «вне периметра 44-ФЗ» (закупка по 223-ФЗ).
 *
 * ОТКУДА КЛАСС. Разбор правил книги 30.08.2026
 * (`docs/superpowers/audits/2026-08-30-obmotka-plan.md`, §2 слепоты 6 и 7)
 * показал: условное форматирование книги красит «223» в графе обоснования (M)
 * и «223-ФЗ» в примечании ГРБС (AF), словарь причин ЕП кластер знает
 * (`EP_LAW_223`), а продукт классом его не считал — такие строки входили во
 * все счёты наравне с закупками по 44-ФЗ. Решение владельца §22 п.5: класс
 * ввести и строки МАРКИРОВАТЬ.
 *
 * ЧТО СДЕЛАНО ЗДЕСЬ, А ЧТО НЕТ. Здесь — метка и отбор Реестра: жетон на
 * строке и переключатель «вместе / отдельно». Исключения таких строк из
 * счётов исполнения здесь НЕ делается: счёты живут в ядре и на сервере, а
 * молчаливое расхождение экрана с расчётом хуже отсутствия метки. Поэтому
 * подпись Реестра говорит прямо: счёты исполнения эти строки пока включают.
 * Обещать читателю исключение, которого нет, запрещено.
 *
 * ЕДИНСТВЕННЫЙ ДОМ ПРИЗНАКА — словарь причин ЕП (@aemr/shared
 * dictionaries/ep-reason-clusters.ts, запись `EP_LAW_223`): и выражения, и
 * человеческая подпись берутся оттуда. Второй набор выражений на стороне
 * экрана завёл бы второй канон, и «223» на двух поверхностях считался бы
 * по-разному.
 *
 * ПОЧЕМУ ВЫРАЖЕНИЯ НАПРЯМУЮ, А НЕ `canonicalizeReasonEp`. Канонизация
 * возвращает ПЕРВЫЙ совпавший кластер из пятнадцати по фиксированному
 * порядку: причина «аукцион не состоялся, закупаем по положению о закупках»
 * ушла бы в кластер несостоявшегося аукциона, и метка периметра пропала бы.
 * Здесь вопрос другой — «относится ли строка к другому закону вообще», и
 * ответ на него не должен зависеть от того, чем ещё объяснена строка. Графа
 * примечания (AF) канонизацию причин ЕП не проходит вовсе — правило книги
 * читает её отдельно, и одним набором выражений обе графы судятся одинаково.
 */
import { EP_REASON_DICT } from '@aemr/shared';

/** Запись словаря — дом выражений и подписи класса. */
const CANON = EP_REASON_DICT.EP_LAW_223;

/** Подпись класса дословно из словаря: «Закупка по 223-ФЗ (вне периметра 44-ФЗ)». */
export const OUTSIDE_44FZ_LABEL: string = CANON.label_ru;

/** Короткая подпись жетона строки. Страж держит её внутри подписи словаря. */
export const OUTSIDE_44FZ_BADGE = 'вне периметра 44-ФЗ';

/**
 * Что жетон обещает и чего НЕ обещает. Формулировка честная по обеим
 * половинам: строка помечена, но из счётов исполнения не изъята.
 */
export const OUTSIDE_44FZ_HINT =
  `${OUTSIDE_44FZ_LABEL}. Признак поставлен по тексту графы обоснования (M) или примечания `
  + 'ГРБС (AF): в них назван 223-ФЗ либо положение о закупках. Строка живёт в книге 44-ФЗ, '
  + 'а закупка идёт по другому закону. Счёты исполнения такие строки пока включают — '
  + 'исключение из них решается отдельно. Жетон и замечание «вне периметра 44-ФЗ» '
  + 'намеренно расходятся в одном случае: у единственного поставщика 223-ФЗ в примечании '
  + 'ГРБС — это принадлежность (жетон есть), но не нарушение (замечания нет), потому что '
  + 'условный формат книги считает такое сочетание нормой и красит только конкурентные '
  + 'способы.';

/** Нормализация текста ячейки — та же, что в канонизации причин ЕП. */
function normalize(raw: unknown): string | null {
  if (raw === null || raw === undefined) return null;
  if (typeof raw !== 'string') return null;
  const cleaned = raw.trim();
  if (cleaned === '') return null;
  return cleaned.toLowerCase().replace(/\s+/g, ' ');
}

/** Названа ли в тексте ячейки закупка по другому закону. */
export function mentionsLaw223(raw: unknown): boolean {
  const text = normalize(raw);
  if (text === null) return false;
  return CANON.regex.some((re) => re.test(text));
}

/** Строка Реестра глазами этого класса: обоснование ЕП (M) и примечание ГРБС (AF). */
export interface Outside44fzRow {
  /** Графа M — обоснование выбора единственного поставщика. */
  epReason?: unknown;
  /** Графа AF — примечание ГРБС. */
  commentGRBS?: unknown;
}

/** Строка вне периметра 44-ФЗ? Хватает любой из двух граф. */
export function isOutside44fz(row: Outside44fzRow): boolean {
  return mentionsLaw223(row.epReason) || mentionsLaw223(row.commentGRBS);
}

/**
 * Режим показа таких строк.
 *   • `together` — по умолчанию: строки видны вместе со всеми и помечены;
 *   • `apart` — показаны только они, чтобы перечень можно было прочитать целиком.
 * Третьего режима («спрятать») нет намеренно: спрятанная строка исчезает из
 * счёта экрана молча, а метка ровно затем и заводилась, чтобы такие строки
 * было видно.
 */
export type Outside44fzMode = 'together' | 'apart';

export const OUTSIDE_44FZ_DEFAULT_MODE: Outside44fzMode = 'together';

/** Отбор строк по режиму. `together` не трогает перечень вовсе. */
export function applyOutside44fzMode<T extends Outside44fzRow>(
  rows: readonly T[],
  mode: Outside44fzMode,
): readonly T[] {
  if (mode === 'together') return rows;
  return rows.filter((row) => isOutside44fz(row));
}

/** Сколько загруженных строк несёт класс. */
export function countOutside44fz(rows: readonly Outside44fzRow[]): number {
  let n = 0;
  for (const row of rows) if (isOutside44fz(row)) n += 1;
  return n;
}

/**
 * Подпись переключателя под таблицей. Говорит три вещи и ни одной лишней:
 * сколько таких строк найдено, что сейчас показано, и что счёты исполнения их
 * пока включают. Последнее — не оговорка мелким шрифтом, а условие правды:
 * пока исключения нет, обещать его нельзя.
 */
export function outside44fzCaption(count: number, mode: Outside44fzMode): string {
  if (count === 0) {
    return 'Строк вне периметра 44-ФЗ среди загруженных нет:'
      + ' ни в обосновании, ни в примечании другой закон не назван.';
  }
  const word = count === 1 ? 'строка' : count < 5 ? 'строки' : 'строк';
  const shown = mode === 'together'
    ? 'Показаны вместе с остальными и помечены жетоном.'
    : 'Показаны отдельно: в таблице сейчас только они.';
  return `Вне периметра 44-ФЗ — ${count} ${word}. ${shown}`
    + ' Счёты исполнения эти строки пока включают: класс маркирует их, но из расчёта не изымает.';
}
