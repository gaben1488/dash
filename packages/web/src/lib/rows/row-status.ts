/**
 * row-status.ts — один дом «состояние строки → тон, значок, объяснение».
 *
 * Зачем отдельный дом. Карта состояний была написана дважды — в таблице
 * Реестра и в карточке строки — и разъехалась ровно так, как расходятся
 * рукописные копии: таблица знала восемь подписей, карточка пять, и «Скоро
 * срок», «Ошибка», «Открыт», «Срок не наступил», «Исполнение» в карточке
 * выходили серыми без значка. Обе копии молчали о том, ЧТО состояние значит:
 * читатель видел слово и цвет, а спросить о механизме было негде (канон п.53:
 * по каждому сигналу виден ответ).
 *
 * Ключ карты — русская подпись состояния, потому что до экрана доезжает
 * именно она: ось состояний считает @aemr/core (classifyRowState), а в
 * подпись её переводит DTO строки на сервере (services/rows-dto.ts,
 * STATE_STATUS_RU) — веб получает уже готовое слово. Подписи, у которых есть
 * сигнальный близнец, берутся здесь из общего словаря имён @aemr/shared, а не
 * переписываются строкой: разъехаться с DTO негде. Три подписи словаря не
 * имеют («Исполнение», «Открыт», «Ошибка») и заданы явно — их дом сегодня
 * тоже DTO, и страж-тест ниже держит список в поле зрения.
 *
 * Значок называется именем, а не компонентом: дом смысла не обязан тянуть за
 * собой библиотеку иконок, а каждая поверхность рисует своим набором.
 */
