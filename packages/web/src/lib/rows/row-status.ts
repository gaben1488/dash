/** Подписи, которые карта обязана знать, — для стража в тесте. */
export const KNOWN_ROW_STATUSES: readonly string[] = Object.keys(LOOKS);

/**
 * Оформление состояния строки. Пустое значение — не «неизвестное состояние», а
 * отсутствие расчёта: возвращается null, и каждая поверхность говорит об этом
 * своей честной пустотой. Незнакомая подпись не красится наугад: серый тон и
 * прямое признание, что объяснения для неё в продукте нет.
 */
export function rowStatusLook(status: unknown): RowStatusLook | null {
  const label = String(status ?? '').trim();
  if (label === '') return null;
  const look = LOOKS[label];
  if (look === undefined) {
    return {
      label,
      tone: NEUTRAL,
      icon: null,
      hint: `Состояние «${label}» продукту не описано: механизм присвоения назвать нечем.`,
    };
  }
  return { label, ...look };
}
