/**
 * disposal.ts — безопасная подсветка «распоряжения экономией» (канон п.85/12б
 * интервью 14.08.2026).
 *
 * Слова владельца: слой «заявки на перераспределение экономии» вводится в
 * безопасной версии — ПОДСВЕТКА автоматом, СЧЁТ только после подтверждения
 * человеком. Поэтому функция отвечает ровно на один вопрос: «похож ли текст
 * комментария на распоряжение сэкономленными деньгами?» — и ничего не
 * утверждает о статусе строки. Канон п.27 (свободный текст не источник
 * статусов) не нарушается: результат — приглашение человеку посмотреть,
 * а не машинный вывод.
 *
 * Словарь примет сознательно узкий: лучше пропустить спорную формулировку,
 * чем подсветить чужую. Расширяется только вместе с тестом.
 */

/** Приметы распоряжения экономией в свободном тексте комментария.
 *  `\w` в JavaScript — только латиница, поэтому окончания названы классом
 *  [а-яё] явно. */
const DISPOSAL_PATTERNS: readonly RegExp[] = [
  // «перераспределение экономии», «перераспределить экономию»
  /перераспредел[а-яё]*[^.;]{0,40}эконом/iu,
  // «экономию перераспределить / направить / использовать»
  /эконом[а-яё]*[^.;]{0,40}(?:перераспредел|направ|использова)/iu,
  // «за счёт экономии» (планируют потратить сэкономленное)
  /за\s+сч[её]т\s+эконом/iu,
  // «направить сэкономленные средства»
  /сэкономленн[а-яё]+\s+средств/iu,
];

/**
 * Похож ли текст на распоряжение экономией. Только подсветка — счёт и любые
 * итоги по таким строкам появляются исключительно после подтверждения
 * ответственным (безопасная версия п.85/12б).
 */
export function looksLikeEconomyDisposal(text: string | null | undefined): boolean {
  if (!text) return false;
  const t = text.trim();
  if (t.length < 8) return false;
  return DISPOSAL_PATTERNS.some((re) => re.test(t));
}
