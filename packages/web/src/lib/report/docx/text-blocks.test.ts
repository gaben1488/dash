  it('разбирает управления с процентом и остатком квартала', () => {
    const t = textOf(extra);
    expect(t).toContain('По остатку из 6 процедур по 1 кварталу:');
    expect(t).toContain('- УЭР – 40,00% (план на 1 квартал – 10, исполнено 4, план на год – 40)');
    expect(t).toContain(
      'В 1 квартале осталось заключиться по 6 аукционам на общую сумму 600,00 тыс. руб. ' +
      '(ФБ – 100,00 тыс. руб., КБ – 200,00 тыс. руб., МБ – 300,00 тыс. руб.), в том числе:',
    );
  });

  it('предлог квартала согласован: «Во 2 квартале», но «В 1 квартале»', () => {
    const q2 = additionalReportBlocks(
      { ...fixture, period: { ...fixture.period, quarter: 2 } },
      quarters,
      AS_OF,
    );
    expect(textOf(q2)).toContain('Во 2 квартале осталось заключиться');
    expect(textOf(extra)).toContain('В 1 квартале осталось заключиться');
  });

  it('перечень остатка: позиция листа с суммой и пояснением ГРБСа в скобках', () => {
    const t = textOf(extra);
    // Реверс эталона 26.06: пункт = предмет + сумма + «Комментарий ГРБСа».
    expect(t).toContain('- Поставка учебной мебели на сумму 610,00 тыс. руб. ' +
      '(Ожидаем доведения лимитов, контракт будет подписан до 30.09.2026.);');
  });

  it('блока рекомендаций нет: колонка УЭР переведена под идентификатор закупки (07.08)', () => {
    expect(textOf(extra)).not.toContain('В ходе анализа рекомендовано');
  });

