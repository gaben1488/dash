/**
 * Состав .docx-выгрузок: проверяется словами, без рендера документа.
 *
 * Калибровка — два ручных эталона: «Отчет по закупкам на 26.06.2026» и
 * «Дополнительно к отчету по закупкам» (12.07.2026), структура сверена с
 * третьей неделей (08.05.2026) — она постоянна, а не разовая.
 */
import { describe, it, expect } from 'vitest';
import {
  mainReportBlocks,
  additionalReportBlocks,
  type QuarterReports,
  type ReportForExport,
} from './text-blocks';
import { makeReportFixture } from '../fixture';

const AS_OF = '20.03.2026';

/**
 * Фикстура с официальным ярусом листа: «Расч. экономия» и «Остаток к заключ.»
 * лист СВОД считает сам, и без них главные денежные строки уходят в плашку.
 */
const fixture: ReportForExport = {
  ...makeReportFixture(),
  official: {
    remainderToConclude: { fb: 100, kb: 200, mb: 300, total: 600, row: 2 },
    calcEconomy: { fb: 10, kb: 20, mb: 30, total: 60, row: 32 },
  },
  svodOnlineUrl: 'https://docs.google.com/spreadsheets/d/svod',
};

// Один и тот же срез по четырём кварталам: для состава важны подписи
// кварталов и то, что каждая из четырёх строк действительно печатается.
const quarters: QuarterReports = { 1: fixture, 2: fixture, 3: fixture, 4: fixture };

const main = mainReportBlocks(fixture, quarters, AS_OF);
const extra = additionalReportBlocks(fixture, quarters, AS_OF);
// toLocaleString('ru-RU') разделяет разряды неразрывным пробелом — в
// сравнениях он невидим и путает; нормализуем его к обычному.
const textOf = (blocks: { text: string }[]): string =>
  blocks.map((b) => b.text).join('\n').replace(/\u00A0/g, ' ');
const headingsOf = (blocks: { kind: string; text: string }[]): string[] =>
  blocks.filter((b) => b.kind === 'heading').map((b) => b.text);

/** Строки вида «(ФБ – 10,00 тыс. руб., КБ – 20,00 тыс. руб., МБ – 30,00 тыс. руб.)». */
function budgetTriples(text: string): Array<{ fb: number; kb: number; mb: number }> {
  const re = /\(ФБ – ([\d\s\u00A0]+,\d{2}) тыс\. руб\., КБ – ([\d\s\u00A0]+,\d{2}) тыс\. руб\., МБ – ([\d\s\u00A0]+,\d{2}) тыс\. руб\.\)/g;
  const parse = (s: string): number => Number(s.replace(/[\s\u00A0]/g, '').replace(',', '.'));
  return [...text.matchAll(re)].map((m) => ({ fb: parse(m[1]), kb: parse(m[2]), mb: parse(m[3]) }));
}

describe('основной отчёт — структура ручного эталона', () => {
  it('открывается шапкой: название, срез, ссылка на СВОД и курсивная оговорка', () => {
    expect(main[0].text).toBe('ОТЧЕТ ПО ЗАКУПКАМ');
    expect(main[1].text).toBe(`срез на ${AS_OF}`);
    expect(main[2].text).toContain('Ссылка на СВОД онлайн');
    const notes = main.filter((b) => b.kind === 'note').map((b) => b.text);
    expect(notes[0]).toContain('могут незначительно отличаться');
  });

  it('районный блок идёт до секций и несёт оба способа', () => {
    expect(main.find((b) => b.text === 'ВСЕ ГРБС')).toBeDefined();
    const headings = headingsOf(main);
    expect(headings[1]).toBe('ПО КОНКУРЕНТНЫМ ПРОЦЕДУРАМ:');
    expect(headings).toContain('ЕДИНСТВЕННЫЙ ПОСТАВЩИК:');
  });

  it('печатает ВСЕ ЧЕТЫРЕ квартала района — и по КП, и по ЕП', () => {
    const t = textOf(main);
    for (const q of [1, 2, 3, 4]) {
      expect(t).toContain(`Всего на ${q} квартал 2026 года запланировано 10 конкурентных процедур.`);
      expect(t).toContain(
        `Всего на ${q} квартал 2026 года запланировано заключить договоров/контрактов по 5 наименованиям.`,
      );
    }
  });

  it('кварталы названы словом «квартал», латинской Q в тексте нет', () => {
    expect(textOf(main)).toContain('1 квартал');
    expect(textOf(main)).not.toContain('1 кв ');
    expect(textOf(main)).not.toMatch(/\bQ[1-4]\b/);
  });

  it('исполнение по кварталу названо отклонением, когда план не закрыт', () => {
    // Фикстура: КП квартала план 10, факт 4 → отклонение 6 процедур, 40,00%.
    expect(textOf(main)).toContain(
      'Отклонение от плана 1 квартала – 6 процедур (общее исполнение плана 1 квартала – 40,00%)',
    );
  });

  it('список ГРБС отсортирован по проценту по возрастанию и стоит под датой среза', () => {
    const t = textOf(main);
    expect(t).toContain(`По состоянию на ${AS_OF} фактическое исполнение плана 1 квартала по ГРБС:`);
    // «План на год» — сумма четырёх кварталов (10 × 4), а не годовой счётчик
    // блока (30): в план года входят только строки с плановым кварталом (§2).
    expect(t).toContain('- УЭР – 40,00% (план на 1 квартал – 10, исполнено 4, план на год – 40)');
    // УО без плана на квартал (planCount = 0) в список не попадает: исполнять нечего.
    expect(t).not.toContain('- УО – ');
  });

  it('остаток года по конкурентным = сумма квартальных остатков КП', () => {
    // Фикстура: 6 незаключённых КП в квартале × 4 квартала = 24.
    expect(textOf(main)).toContain(
      'Остаток незаключенных договоров по конкурентным процедурам до конца года – 24.',
    );
  });

  it('расчётная экономия берётся из официального яруса листа, с бюджетами', () => {
    expect(textOf(main)).toContain(
      'Расчетная экономия по оставшимся незаключенным 24 конкурентным процедурам составляет ' +
      '60,00 тыс. руб., из них – 30,00 тыс. руб. – местный бюджет ' +
      '(ФБ – 10,00 тыс. руб., КБ – 20,00 тыс. руб., МБ – 30,00 тыс. руб.).',
    );
  });

  it('каждое управление получает секцию с обоими способами и экономией МБ', () => {
    const headings = headingsOf(main);
    for (const block of fixture.grbsBlocks) {
      expect(headings).toContain(`${block.dept} — ${block.deptLabel}`);
    }
    expect(headings.filter((h) => h === 'КОНКУРЕНТНЫЕ ПРОЦЕДУРЫ:'))
      .toHaveLength(fixture.grbsBlocks.length);
    expect(textOf(main)).toContain('Экономия местного бюджета 0,00 тыс. руб.');
  });

  it('год — сумма четырёх кварталов, а не годовой ярус проекции (§2)', () => {
    // Годовые счётчики проекции квартала не требуют и тянут строки без него.
    // На живых книгах 26.06.2026 это давало 475 конкурентных процедур вместо
    // эталонных 396, 2 684 ЕП вместо 2 333 и 225 против 150 у УО, а вслед за
    // знаменателем врало «исполнение годового плана» (38,22 % против 57,33 %).
    // Фикстура ловит подмену: годовой ярус даёт 50/30 КП и 30/24 ЕП, сумма
    // кварталов — 40/16 и 20/8; у блока УЭР 30/21 против 40/16.
    const t = textOf(main);
    expect(t).toContain('Всего на год запланировано 40 процедур.');
    expect(t).toContain('Фактически обязательства заключены по 16 конкурентным процедурам.');
    expect(t).not.toContain('Всего на год запланировано 50 процедур.');
    expect(t).toContain('Заключено 8 договоров/контрактов.');
    expect(t).toContain('Всего на год: 40');
    expect(t).not.toContain('Всего на год: 30');
    // Исполнение годового плана считается по тому же сложению: 16 / 40.
    expect(t).toContain('Исполнение годового плана – 40,00%');
  });

  it('квартал без плана и без факта в секции не печатается', () => {
    // УО: план и факт квартала нулевые — «запланировано 0 … исполнение – —»
    // это пустота, выданная за строку; эталон таких строк не знает.
    expect(textOf(main)).not.toContain('запланировано 0 конкурентных процедур');
    expect(textOf(main)).not.toContain('Исполнение плана 1 квартала – —');
  });

  it('место под адресные рекомендации есть, но текст пишет человек', () => {
    expect(textOf(main)).toContain(
      'В ходе ведения аналитики адресные рекомендации ГРБС и их итоги — не заполнено.',
    );
  });

  it('склонения по числу: аукционы, договоры, процедуры', () => {
    const t = textOf(main);
    expect(t).toContain('Проведено 4 аукциона.');
    expect(t).toContain('Заключено 2 договора/контракта.');
  });

  it('секция управления называет остаток квартала — по КП и по ЕП', () => {
    // Эталон 26.06 держит эту строку у пяти ГРБС из восьми (119/149/237/267/
    // 421/449/491/593), 08.05 — у семи: часть структуры, а не приписка.
    // Фикстура УЭР: КП 6 незаключённых на 600,00, ЕП 3 на 60,00.
    const t = textOf(main);
    expect(t).toContain(
      'В 1 квартале осталось отыграть 6 аукционов на общую сумму 600,00 тыс. руб. ' +
      '(ФБ – 100,00 тыс. руб., КБ – 200,00 тыс. руб., МБ – 300,00 тыс. руб.), в том числе:',
    );
    expect(t).toContain(
      'В 1 квартале осталось заключить 3 договора/контракта на общую сумму 60,00 тыс. руб. ' +
      '(ФБ – 10,00 тыс. руб., КБ – 20,00 тыс. руб., МБ – 30,00 тыс. руб.), в том числе:',
    );
    // Нулевой остаток строки не рождает: «осталось 0» — та же пустота.
    expect(t).not.toContain('осталось отыграть 0 ');
    expect(t).not.toContain('осталось заключить 0 ');
  });

  it('честные плашки на месте: что пишет человек, продукт не сочиняет', () => {
    const t = textOf(main);
    expect(t).toContain('не заполнено');
    expect(t).toContain('перечень по стадиям ведёт специалист отдела');
    // Суммы по способу закупки продукт не считает — сказано один раз, оговоркой.
    expect(textOf(main.filter((b) => b.kind === 'note')))
      .toContain('в разрезе способа закупки');
  });

  it('без официального яруса экономия уходит в плашку, а не в ноль', () => {
    const bare = mainReportBlocks({ ...fixture, official: undefined }, quarters, AS_OF);
    expect(textOf(bare)).toContain('Расчетная экономия по оставшимся незаключенным 24 конкурентным');
    expect(textOf(bare)).toContain('не рассчитано: ярус «Расч. экономия» листа СВОД не передан');
  });

  it('бюджетные тройки сходятся с итогом строки', () => {
    // Три тройки: экономия остатка (60,00) и два остатка квартала УЭР —
    // КП 600,00 и ЕП 60,00. Каждая обязана сойтись с итогом СВОЕЙ строки,
    // иначе тройка — украшение, а не разбивка суммы.
    const t = textOf(main);
    const triples = budgetTriples(t);
    expect(triples).toHaveLength(3);
    for (const tri of triples) expect(tri.fb + tri.kb + tri.mb).toBeGreaterThan(0);
    const n = (s: string): number => Number(s.replace(/\s/g, '').replace(',', '.'));
    const withTotal = [...t.matchAll(
      /(?:составляет|на общую сумму) ([\d\s]+,\d{2}) тыс\. руб\.[^(]*\(ФБ – ([\d\s]+,\d{2}) тыс\. руб\., КБ – ([\d\s]+,\d{2}) тыс\. руб\., МБ – ([\d\s]+,\d{2}) тыс\. руб\.\)/g,
    )];
    // Сверка должна что-то сверить: пустой список дал бы зелёный тест ни о чём.
    expect(withTotal).toHaveLength(3);
    for (const [, total, fb, kb, mb] of withTotal) {
      expect(n(fb) + n(kb) + n(mb)).toBeCloseTo(n(total), 2);
    }
  });
});

describe('дополнительный отчёт — записка руководителю', () => {
  it('открывается обращением эталона', () => {
    expect(headingsOf(extra)[0]).toBe('ДОПОЛНИТЕЛЬНО К ОТЧЕТУ ПО ЗАКУПКАМ');
    expect(textOf(extra)).toContain(
      'Уважаемые коллеги, буду краток, исключительно по основным показателям и проблематике',
    );
  });

  it('несёт год, факт и исполнение по кварталам', () => {
    const t = textOf(extra);
    // Год = сумма кварталов: 10 × 4 плана и 4 × 4 факта (§2), а не 50/30
    // из годового яруса проекции — тот считает и строки без квартала.
    expect(t).toContain('Всего на год запланировано 40 процедур.');
    expect(t).toContain('Фактически обязательства заключены по 16 конкурентным процедурам.');
    expect(t).toContain('Отклонение от плана 1 квартала – 6 процедур');
  });

  it('остаток года напечатан с суммой и бюджетами, тройка сходится', () => {
    const t = textOf(extra);
    // Остаток КП за год: 4 квартала × (100 ФБ + 200 КБ + 300 МБ) = 2 400,00.
    expect(t).toContain(
      'Остаток незаключенных договоров по конкурентным процедурам до конца года – 24 ' +
      'на общую сумму 2 400,00 тыс. руб. ' +
      '(ФБ – 400,00 тыс. руб., КБ – 800,00 тыс. руб., МБ – 1 200,00 тыс. руб.)',
    );
    for (const tri of budgetTriples(t)) {
      expect(tri.fb + tri.kb + tri.mb).toBeGreaterThan(0);
    }
  });

  it('разбирает управления с процентом и остатком квартала', () => {
    const t = textOf(extra);
    expect(t).toContain('По остатку из 6 процедур по 1 кварталу:');
    expect(t).toContain('- УЭР – 40,00% (план на 1 квартал – 10, исполнено 4, план на год – 40)');
    expect(t).toContain(
      'В 1 квартале осталось заключиться по 6 аукционам на общую сумму 600,00 тыс. руб. ' +
      '(ФБ – 100,00 тыс. руб., КБ – 200,00 тыс. руб., МБ – 300,00 тыс. руб.), в том числе:',
    );
  });

  it('предлог квартала согласован: «Во 2 квартале», но «В 1 квартале»', () => {
    const q2 = additionalReportBlocks(
      { ...fixture, period: { ...fixture.period, quarter: 2 } },
      quarters,
      AS_OF,
    );
    expect(textOf(q2)).toContain('Во 2 квартале осталось заключиться');
    expect(textOf(extra)).toContain('В 1 квартале осталось заключиться');
  });

  it('пояснения по позициям и проблематика — честные плашки', () => {
    const t = textOf(extra);
    expect(t).toContain('пояснение по каждой незаключённой позиции пишет специалист');
    expect(t).toContain('Из критичной проблематики — не заполнено.');
    expect(t).toContain('Адресные рекомендации ГРБС и их итоги — не заполнено.');
  });

  it('режим просмотра назван в конце', () => {
    const live = additionalReportBlocks(
      { ...fixture, period: { ...fixture.period, live: true } },
      quarters,
      AS_OF,
    );
    expect(textOf(live)).toContain('в режиме прямого эфира');
    expect(textOf(extra)).toContain('по снимку недели');
  });

  it('латинской Q в тексте нет', () => {
    expect(textOf(extra)).not.toMatch(/\bQ[1-4]\b/);
  });
});
