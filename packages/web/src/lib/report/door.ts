/**
 * Дверь к строкам-основаниям для карточек «Отчёта».
 *
 * ДОСЛОВНОЕ ТРЕБОВАНИЕ ВЛАДЕЛЬЦА, ради которого модуль существует: по каждому
 * числу должно быть видно, КАКИЕ строки за ним стоят. Полоса этапности и
 * кластеры оснований — единственные карточки «Отчёта», где число до сих пор
 * кончалось словами: попап объяснял признак колонки листа, а показать сами
 * строки было нечем (работы 4.11 и 4.12 плана переплавки, P2 карты вкладки).
 *
 * ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ. Сводит два готовых дома в одну готовую к нажатию
 * дверь и НЕ заводит третьего:
 *
 *   • `lib/kb/rows-door.ts` знает, КУДА ведёт ключ показателя (страница,
 *     признаки строк Реестра, чего дверь не переносит). До 21.08 у этого
 *     реестра не было ни одного потребителя — дверь была описана и закрыта;
 *   • `lib/drill.ts` (механизм М14) знает, КАК доехать: какие оси периметра
 *     цель принимает, какие теряет и как назвать потерю словами.
 *
 * Своей навигации и своих формулировок здесь нет намеренно (канон п.112:
 * один смысл — один дом). Модуль возвращает описание перехода; открывает его
 * страница тем же `navigateTo`, которым живёт всё приложение.
 *
 * ЧЕСТНОСТЬ. Ключа нет в реестре дверей — возвращается `null`, и экран не
 * рисует ссылку вовсе. Ложная дверь хуже отсутствующей: читатель не узнает,
 * что открылись ДРУГИЕ строки. По той же причине подсказка двери всегда
 * называет потери периметра (`warning` перехода) и оговорку самой двери
 * (`dropped` реестра) — обе, а не ту, что короче.
 */
import type { Page } from '../../store';
import { buildDrill, type DrillFilters, type DrillPoint, type DrillPage } from '../drill';
import { rowsDoorFor, noDoorReason } from '../kb/rows-door';

/** Готовый к нажатию переход: куда, с чем, под какой подписью. */
export interface ReportDoor {
  /** Страница назначения — как её понимает `navigateTo`. */
  readonly page: Page;
  /** Отбор шапки — второй довод `navigateTo`, собран механизмом М14. */
  readonly filters: DrillFilters;
  /** Подпись двери на экране («Открыть просроченные строки»). */
  readonly label: string;
  /**
   * Что откроется и чего в цели не будет — одной строкой для подсказки.
   * Собрана из трёх частей, каждая со своим домом: перечень доехавших осей и
   * фраза о потерянных приходят из `buildDrill`, оговорка о самой двери — из
   * реестра дверей.
   */
  readonly hint: string;
}

/**
 * Корзины Реестра — это Реестр с зафиксированным классом строк, а не
 * отдельные вкладки со своим отбором: `unfunded` и `yearlong` рендерятся тем
 * же `DataBrowser`. Поэтому оси периметра доезжают до них ровно так же, и
 * применимость осей считается по Реестру.
 */
const REGISTRY_BUCKETS: readonly Page[] = ['unfunded', 'yearlong'];

/** Страница, по которой считается применимость осей перехода. */
function carrierPage(page: Page): DrillPage {
  return REGISTRY_BUCKETS.includes(page) ? 'data' : (page as DrillPage);
}

/**
 * Дверь к строкам-основаниям показателя. `null` — двери у ключа нет; причину
 * отсутствия, если она разобрана, отдельно называет `doorAbsence`.
 *
 * `point` — периметр карточки, с которого щёлкнули: управление секции, год
 * отчёта, признак строк. Что из него доедет до цели, а что нет, решает не
 * этот модуль, а таблица применимости осей механизма М14.
 */
export function reportDoor(metricKey: string, point: DrillPoint): ReportDoor | null {
  const door = rowsDoorFor(metricKey);
  if (door === null) return null;
  const target = buildDrill(
    { ...point, ...(door.signals ? { signals: door.signals } : {}) },
    carrierPage(door.page),
  );
  const parts = [target.summary, target.warning, door.dropped ?? ''].filter((s) => s !== '');
  return {
    page: door.page,
    filters: target.filters,
    label: door.label,
    hint: parts.join(' '),
  };
}

/**
 * Почему у показателя двери нет. Пустой ответ означает, что вопрос никем не
 * разбирался, — это повод завести либо дверь, либо причину, а не молчать на
 * экране. Реэкспорт вместо второго словаря: причины живут в реестре дверей.
 */
export function doorAbsence(metricKey: string): string | null {
  return noDoorReason(metricKey);
}
