/**
 * Какая секция «Отчёта» сейчас перед глазами — для подсветки в липкой
 * навигации ГРБС (работа 4.14 плана переплавки).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Наблюдатель пересечений даёт СОБЫТИЯ («секция УО
 * вошла в окно на 40 %»), а колонке нужен ОТВЕТ («сейчас читают УО»). Между
 * ними лежит правило выбора, и именно оно ошибается молча: при прокрутке в
 * окне почти всегда видны две секции сразу, и наивное «последняя вошедшая»
 * даёт скачки подсветки назад. Правило вынесено сюда, чтобы его проверял
 * тест, а не глаз на живой странице.
 *
 * ПРАВИЛО. Активна секция, чей верх ВЫШЕ линии чтения и при этом ближе всех
 * к ней снизу — то есть та, в тело которой читатель уже вошёл. Если ни одна
 * секция ещё не пересекла линию (страница в самом начале), активна первая
 * видимая: пустая подсветка на длинном документе хуже, чем подсветка первой.
 */

/** Секция в окне: ключ ГРБС и координата её верха относительно окна. */
export interface SectionOffset {
  readonly dept: string;
  /** `getBoundingClientRect().top` секции — пиксели от верха окна. */
  readonly top: number;
}

/**
 * Активная секция из положений всех секций. `null` — секций нет вовсе
 * (одна-единственная секция навигации не получает, и колонка не рисуется).
 *
 * `readingLine` — та высота окна, на которой читатель держит взгляд: не сам
 * верх (тогда подсветка переключалась бы на секцию, от которой видна одна
 * строка), а полоса чуть ниже шапки.
 */
export function activeSectionOf(
  sections: readonly SectionOffset[],
  readingLine: number,
): string | null {
  if (sections.length === 0) return null;
  let best: SectionOffset | null = null;
  for (const s of sections) {
    if (s.top > readingLine) continue;
    if (best === null || s.top > best.top) best = s;
  }
  if (best !== null) return best.dept;
  // Ни одна секция линию не перешла — страница в самом верху. Активна та,
  // что ближе всех к линии сверху вниз: её читатель и увидит первой.
  let first = sections[0]!;
  for (const s of sections) if (s.top < first.top) first = s;
  return first.dept;
}
