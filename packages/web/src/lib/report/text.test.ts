/**
 * Юниты generateReportText — плоский текст для письма: разделы, проценты,
 * «тыс. руб.», честная сверка со СВОД, примечания. Детерминизм: дата среза —
 * параметром, Date.now в генераторе не участвует.
 */
import { describe, it, expect } from 'vitest';
import { generateReportText } from './text';
import { makeReportFixture } from './fixture';

const norm = (s: string) => s.replace(/[\u00A0\u202F]/g, ' ');
const text = norm(generateReportText(makeReportFixture(), '20.03.2026'));
const lines = text.split('\n');

describe('generateReportText — плоский отчёт для письма', () => {
  it('шапка: дата среза и период', () => {
    expect(lines[0]).toBe('Отчёт по закупкам на 20.03.2026');
    expect(lines[1]).toBe('Период: 2026 год, 1 квартал');
  });

  it('интегральная сводка: год и квартал с КП/ЕП', () => {
    expect(text).toContain('ИТОГО ПО УПРАВЛЕНИЯМ');
    expect(text).toContain('Год: план 80, заключено 54 (67,5%). КП 60,0%, ЕП 80,0%.');
    expect(text).toContain('1 квартал: план 15, заключено 6 (40,0%). КП 40,0%, ЕП 40,0%.');
    expect(text).toContain(
      'Деньги за год: лимит 4 500 тыс. руб., факт 3 450 тыс. руб., экономия 150 тыс. руб.',
    );
  });

  it('блок УЭР: калибровка эталоном 20.03 (6 из 15 = 40,0%)', () => {
    expect(text).toContain('УЭР — Управление экономического развития');
    expect(text).toContain('1 квартал: заключено 6 из 15 (40,0%). Не заключено: 9.');
    expect(text).toContain('КП: 4 из 10 (40,0%), ЕП: 2 из 5 (40,0%).');
    expect(text).toContain('За год: заключено 20 из 50 (40,0%), не заключено 30.');
    expect(text).toContain('Лимит 3 500 тыс. руб., факт 2 500 тыс. руб. Экономия: 150 тыс. руб.');
  });

  it('сверка со СВОД: сходится (сравниваются живые числа) и объясняет разрыв со срезом', () => {
    expect(text).toContain('Сверка со СВОД (1 квартал): расхождений нет.');
    expect(text).toContain('После даты среза заключено 1');
  });

  it('сигналы человеческими словами', () => {
    expect(text).toContain('Сигналы: Просрочен план размещения по 3 процедурам.');
  });

  it('блок УО: «нет плана» вместо нуля, без сверки и сигналов', () => {
    expect(text).toContain('УО — Управление образования');
    expect(text).toContain('1 квартал: заключено 0 из 0 (нет плана). План на квартал отсутствует.');
    expect(text).not.toContain('УО — Управление образования\nСверка');
  });

  it('примечания в конце', () => {
    expect(text).toContain('Примечания:\n— Лист СВОД за 1 квартал не передан для УД');
  });

  it('без markdown — плоский текст письма', () => {
    expect(text).not.toMatch(/[#*|`]/);
  });
});
