/**
 * ISO-момент из базы → время, которое можно прочитать вслух.
 *
 * Сервер везде хранит и отдаёт моменты в ISO-UTC (`new Date().toISOString()`):
 * время события в журнале, `createdAt` снимка, `detectedAt` замечания. Строка
 * `2026-08-07T09:15:00.000Z` — технический формат, и на экране ей не место.
 * Печатаем в поясе пользователя: вопрос «когда это случилось» он задаёт про
 * своё время, а не про UTC.
 *
 * Общий дом для всех страниц, где показывается момент события: иначе формат
 * расходится по вкладкам, и одно и то же время выглядит по-разному.
 */
export function formatEventTime(iso: string | null | undefined): string {
  if (!iso) return 'время не записано';
  const parsed = new Date(iso);
  // Непарсимое значение не выдумываем и не прячем: отдаём как есть, чтобы
  // поломка источника была видна, а не заметена под «—».
  if (Number.isNaN(parsed.getTime())) return iso;
  return parsed.toLocaleString('ru-RU', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}
