/** Дверь к строкам-основаниям для ключа карточки; null — двери нет. */
export function rowsDoorFor(metricKey: string): RowsDoor | null {
  return DOORS[metricKey] ?? null;
}

/**
 * Почему у ключа нет двери. Пустой ответ означает, что вопрос не разбирался,
 * — и это повод завести либо дверь, либо причину, а не молчать.
 */
export function noDoorReason(metricKey: string): string | null {
  return NO_DOOR[metricKey] ?? null;
}

/** Все ключи, у которых дверь описана, — для стража покрытия. */
export function doorKeys(): readonly string[] {
  return Object.keys(DOORS);
}

/** Все ключи с честно названной причиной отсутствия двери. */
export function noDoorKeys(): readonly string[] {
  return Object.keys(NO_DOOR);
}
