/**
 * Дверь к строкам-основаниям — девятое поле карточки базы знаний 2.0.
 *
 * ЗАЧЕМ. Объяснение, которое кончается словами, оставляет читателя с верой на
 * слово. Карточка 2.0 обязана уметь показать ТЕ САМЫЕ строки, из которых
 * сложилось число: «96 строк без даты заключения», «строки без года плана»,
 * «процедуры, на которых посчитано среднее снижение». Сегодня такая дверь есть
 * у двенадцати ключей и ведёт только в ячейку официального листа
 * (`lib/provenance-registry.ts`); этот модуль добавляет вторую дверь — в
 * строки Реестра и в разбор соответствующей вкладки.
 *
 * ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Он ЗНАЕТ, куда ведёт число, и
 * НЕ ХОДИТ сам: возвращает описание двери в тех же понятиях, которые принимает
 * переход хранилища (`navigateTo(page, filters)`), — страница дополняет его
 * текущим отбором шапки и открывает. Второй схемы навигации здесь нет
 * намеренно (канон п.112 «брать готовое»).
 *
 * ЧЕСТНОСТЬ ДВЕРИ. Дверь заводится только там, где строки-основания
 * действительно достижимы. Показатель, у которого своих строк нет (сводная
 * оценка сервера, коэффициент из книги мониторинга), получает честное
 * отсутствие двери с названной причиной — `noDoorReason`, — а не ссылку
 * «куда-нибудь», которая открыла бы ДРУГИЕ строки. Ложная дверь хуже её
 * отсутствия: читатель не знает, что смотрит не на то.
 */

/** Куда ведёт дверь. Значения — страницы навигации хранилища (`Page`). */
export type DoorPage =
  | 'data'
  | 'unfunded'
  | 'yearlong'
  | 'monitoring'
  | 'economy'
  | 'competition'
  | 'discipline'
  | 'quality'
  | 'report';

/** Подвкладка Контроля — та же, что принимает переход хранилища. */
export type DoorQualityTab = 'trust' | 'recon' | 'issues' | 'recs' | 'journal' | 'scorecard';

export interface RowsDoor {
  /** Подпись двери в карточке. Без числа: число подставит экран. */
  readonly label: string;
  /** Страница назначения. */
  readonly page: DoorPage;
  /**
   * Ключи признаков строк для фильтра Реестра — та самая затравка
   * `registrySignalSeed`, которой пользуется вкладка «Дисциплина».
   */
  readonly signals?: readonly string[];
  /** Подвкладка Контроля, если дверь ведёт туда. */
  readonly qualityTab?: DoorQualityTab;
  /**
   * Чего дверь НЕ переносит. Пишется там, где периметр карточки и периметр
   * страницы назначения расходятся: читатель должен знать это ДО перехода.
   */
  readonly dropped?: string;
}

