/**
 * Запись базы знаний по ключу метрики. Неизвестный ключ даёт null: карточка с
 * пустыми разделами вреднее, чем её отсутствие, — она обещает объяснение и не
 * даёт его (тот же контракт, что у kbFor в metric-kb.ts).
 */
export function economicKbFor(metricKey: string): EconomicKbEntry | null {
  return ECONOMIC_METRIC_KB[metricKey as EconomicMetricKey] ?? null;
}
