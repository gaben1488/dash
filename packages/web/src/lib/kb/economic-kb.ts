/**
 * База знаний экономических метрик первого эшелона (план запуска §2).
 *
 * Продолжение линии metric-kb.ts: у каждого видимого числа обязана быть
 * карточка «что это, как считается, как читать порог, откуда метод». Разница
 * в том, что записи METRIC_KB описывают счётчики движка, а здесь — четыре
 * метрики, у которых порог взят не из практики района, а из внешней
 * методики, и назвать её обязательно: порог без источника — это мнение,
 * выданное за норму.
 *
 * Записи держатся отдельным файлом, а не вливаются в METRIC_KB, ровно по
 * этой причине: у них есть раздел «откуда метод», которого у счётчиков нет,
 * и терять его при сплющивании в общий формат нельзя.
 *
 * Ключи записей совпадают с ключами метрик в ответе /api/analytics/economic —
 * по ним интерфейс находит объяснение рядом с числом. Менять ключ здесь, не
 * поправив роут, значит оставить число без карточки.
 *
 * Правило подписей соблюдается и здесь: наружу не выходят ни внутренние
 * ключи, ни буквы колонок листа — колонки названы так, как они подписаны в
 * книгах ГРБС.
 */

/** Ключи метрик — контракт с ответом /api/analytics/economic. */
export type EconomicMetricKey =
  | 'december_overhang'
  | 'planning_accuracy'
  | 'source_execution_gap'
  | 'quarter_compliance';

/** Внешняя методика, из которой взят порог. */
export interface KbMethodSource {
  /** Полная подпись работы — так, как её процитируют в отчёте. */
  title: string;
  /** Ссылка на публикацию; всегда защищённый протокол. */
  url: string;
}

/** Запись базы знаний: семь разделов, ни один из которых не пустует. */
export interface EconomicKbEntry {
  /** Название метрики — подпись плитки и заголовок карточки. */
  title: string;
  /** Что показывает число простыми словами. */
  whatIs: string;
  /** Как считается: числитель, знаменатель и запреты счёта. */
  howCalc: string;
  /** Как читать порог: границы зон и что они означают. */
  thresholds: string;
  /** Откуда числа: какие колонки книг ГРБС участвуют в счёте. */
  dataSource: string;
  /** Чьё это решение — кому и зачем метрика нужна. */
  decision: string;
  /** Подводные камни: чего число не говорит и где ошибётся читатель. */
  pitfalls: string;
  /** Откуда метод: внешняя методика, задавшая порог. */
  method: KbMethodSource;
}

