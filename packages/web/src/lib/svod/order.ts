/**
 * Порядок блоков управлений в таблице «Свода».
 *
 * ЗАЧЕМ. Восемь блоков всегда стояли в порядке реестра — том же, в каком
 * управления перечислены в справочнике. Порядок удобен, когда ищешь СВОЁ
 * управление, и бесполезен, когда спрашиваешь «у кого хуже всего». Вопрос
 * «у кого хуже» — рабочий: с него начинается разбор недели, и до сих пор
 * читатель отвечал на него глазами, сравнивая восемь процентов по столбцу
 * (работа 5.3 карты вкладки «Отчёт+Свод»).
 *
 * ПОЧЕМУ ЧИСТОЙ ФУНКЦИЕЙ. Порядок — это правило, а правило ошибается тихо:
 * пустое значение, севшее не на тот край, выдаёт управление без плана за
 * отличника. Здесь оно проверяется тестом, а не глазом на живой таблице.
 *
 * ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не трогает ни одного числа: блоки те же,
 * меняется только их последовательность. Строка «Итог по всем управлениям»
 * порядку не подчиняется вовсе — она стоит первой всегда, потому что это не
 * управление, а сумма.
 */
import type { SvodBlock } from '@aemr/shared';

/** Чем упорядочены блоки. Значения — то, что стоит на кнопках вкладки. */
export type SvodOrder = 'registry' | 'execution' | 'plan' | 'economy';

/** Подписи порядков — единственный дом этих слов. */
export const SVOD_ORDER_LABEL: Readonly<Record<SvodOrder, string>> = {
  registry: 'как в реестре',
  execution: 'по исполнению',
  plan: 'по лимиту',
  economy: 'по экономии',
};

/**
 * Что означает каждый порядок — для подсказки кнопки. Направление названо
 * словами: «по исполнению» само по себе не говорит, сверху отстающие или
 * передовые, а от этого зависит, как читатель поймёт первую строку.
 */
export const SVOD_ORDER_HINT: Readonly<Record<SvodOrder, string>> = {
  registry: 'Порядок справочника управлений — тот же, что в официальном листе.',
  execution: 'Сверху отстающие: наименьший процент исполнения (столбец G) первым.',
  plan: 'Сверху крупные: наибольший плановый лимит (столбец K) первым.',
  economy: 'Сверху наибольшая экономия по итогу управления.',
};

/** Блок управления в том виде, в каком его держит срез вкладки. */
export interface SvodDeptEntry {
  readonly id: string;
  readonly block: SvodBlock;
}

/** Экономия итоговой строки: план минус факт по строкам с датой заключения. */
function economyOf(block: SvodBlock): number | null {
  const row = block.total.year;
  if (row.planTotal === null || row.factTotal === null) return null;
  return row.planTotal - row.factTotal;
}

/** Ключ сортировки блока; `null` — числа нет вовсе. */
function keyOf(entry: SvodDeptEntry, order: SvodOrder): number | null {
  const row = entry.block.total.year;
  switch (order) {
    case 'execution': return row.executionPct;
    case 'plan': return row.planTotal;
    case 'economy': return economyOf(entry.block);
    case 'registry': return null;
  }
}

/**
 * Блоки в выбранном порядке. Исходный массив не трогается.
 *
 * Правила, из-за которых функция и существует:
 *
 *   • управление БЕЗ числа (плана нет — исполнения нет) уходит в самый низ
 *     при ЛЮБОМ направлении. Пустота — не «ноль процентов»: поставить её
 *     первой в порядке отстающих значило бы обвинить управление, которому
 *     просто нечего исполнять;
 *   • при равных числах сохраняется порядок реестра — сортировка устойчива,
 *     и два одинаковых процента не переставляются местами от перерисовки;
 *   • «как в реестре» возвращает исходный порядок, а не пересобранный:
 *     реестровый порядок задаёт источник, и воспроизводить его сортировкой
 *     значило бы завести ему второй дом.
 */
export function orderDeptBlocks<T extends SvodDeptEntry>(
  entries: readonly T[],
  order: SvodOrder,
): T[] {
  if (order === 'registry') return [...entries];
  // Убывание для лимита и экономии (сверху крупные), возрастание для
  // исполнения (сверху отстающие — с них начинается разбор).
  const descending = order !== 'execution';
  return entries
    .map((entry, index) => ({ entry, index, key: keyOf(entry, order) }))
    .sort((a, b) => {
      if (a.key === null && b.key === null) return a.index - b.index;
      if (a.key === null) return 1;
      if (b.key === null) return -1;
      if (a.key !== b.key) return descending ? b.key - a.key : a.key - b.key;
      return a.index - b.index;
    })
    .map((x) => x.entry);
}
