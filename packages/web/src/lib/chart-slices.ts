// ── Правила круга долей, отделённые от отрисовки.
//
// Живут здесь по двум причинам. Первая — их надо проверять тестом, а
// импорт компонента тянет за собой тему и localStorage. Вторая — правило
// «итог равен сумме частей» одно на все круговые представления, а не
// собственность одного экрана.

/** Минимум, который знает о срезе правило отбора: величина. */
export interface SliceValue {
  value: number;
}

export interface DrawableSplit<T extends SliceValue> {
  /** Срезы, которые круг может изобразить, от крупного к мелкому. */
  drawable: T[];
  /** Что круг изобразить не смог: сколько срезов и на какую сумму. */
  hidden: { count: number; sum: number };
}

/**
 * Круг рисует только положительные величины: сектора отрицательной площади
 * не существует. Отрицательные срезы (например превышение факта над планом
 * в экономии) не исчезают молча — их считают и называют под кругом, иначе
 * сумма показанного тихо разойдётся с итогом.
 *
 * Ровный ноль спрятанным не считается: рисовать нечего и терять нечего.
 */
export function splitDrawable<T extends SliceValue>(slices: T[]): DrawableSplit<T> {
  const drawable: T[] = [];
  let count = 0;
  let sum = 0;
  for (const s of slices) {
    if (s.value > 0) drawable.push(s);
    else if (s.value !== 0) { count += 1; sum += s.value; }
  }
  drawable.sort((a, b) => b.value - a.value);
  return { drawable, hidden: { count, sum } };
}

/**
 * Значимо ли расхождение суммы частей с итогом.
 *
 * Порог не может быть только абсолютным: на миллиардах разница в копейку —
 * это округление источника, а на сотне тысяч та же копейка уже ничего не
 * значит, зато тысяча значит потерянную строку. Поэтому берётся большее из
 * половины единицы и одной тысячной итога.
 */
export function isMeaningfulGap(diff: number, reference: number): boolean {
  return Math.abs(diff) > Math.max(0.5, Math.abs(reference) * 0.001);
}
