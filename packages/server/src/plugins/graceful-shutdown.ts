/**
 * Остановка по сигналу — без оборванных ответов и без бесконечного ожидания.
 *
 * ЗАЧЕМ. `docker compose down`, перезапуск связки и выкатка новой версии шлют
 * SIGTERM. Без обработчика процесс умирает прямо посреди запроса: читатель
 * получает оборванное соединение, а база остаётся с открытым дескриптором.
 * Закрываться, однако, надо не бесконечно: если что-то держит закрытие
 * (открытая лента событий, зависшее чтение книги), через названный срок
 * выходим всё равно — иначе оркестратор добьёт процесс SIGKILL, и разница
 * между штатным выходом и убийством исчезнет.
 *
 * ЧТО ДОБАВЛЕНО К ПРОСТОМУ `app.close()`. Пока закрытие идёт, новые обращения
 * получают честный отказ 503 с `Retry-After`, а не молчание сокета. Это важно
 * ровно в те несколько секунд, когда балансировщик ещё шлёт сюда трафик, а
 * сервер уже прощается: 503 с названным сроком повтора клиент переживает, а
 * оборванное соединение выглядит как поломка.
 *
 * ЧЕСТНО О ГОТОВОМ. Своё здесь не всё: у Fastify есть встроенный
 * `return503OnClosing` (по умолчанию включён), и он тоже отвечает 503 на новые
 * обращения. Заслон ниже его не подменяет, а дополняет двумя вещами, которых у
 * встроенного нет:
 *   • он включается с ПОЛУЧЕНИЯ СИГНАЛА, а встроенный — только с началом
 *     `close()`, то есть на несколько десятков миллисекунд позже; в эту щель и
 *     попадали обращения, приходившие сразу за сигналом;
 *   • отказ идёт в общей форме сервера (plugins/error-shape.ts) и с
 *     `Retry-After`, тогда как встроенный отвечает своей четвёркой полей без
 *     срока повтора — то есть заводит вторую форму отказа в продукте, где она
 *     одна.
 * Проверка живости при этом продолжает отвечать: оркестратору нужно отличать
 * «прощается» от «завис».
 */
import type { FastifyInstance } from 'fastify';
import { codeForStatus } from './error-shape.js';

/** Через сколько закрытие считается затянувшимся и процесс выходит сам. */
export const SHUTDOWN_DEADLINE_MS = 10_000;

/** Через сколько секунд клиенту предлагается повторить обращение. */
const RETRY_AFTER_SECONDS = 5;

export interface ShutdownGuard {
  /** Идёт ли прощание: с этого момента новые обращения получают 503. */
  isClosing(): boolean;
  /** Объявить прощание. Возвращает false, если оно уже объявлено. */
  begin(): boolean;
}

/**
 * Ставит заслон на входе. Регистрируется в `createApp` ПЕРВЫМ хуком запроса:
 * прощающийся сервер не должен ни проверять ключ, ни тратить окно частоты.
 */
export function registerShutdownGuard(app: FastifyInstance): ShutdownGuard {
  let closing = false;

  const guard: ShutdownGuard = {
    isClosing: () => closing,
    begin: () => {
      if (closing) return false;
      closing = true;
      return true;
    },
  };

  app.addHook('onRequest', async (request, reply) => {
    if (!closing) return;
    // Проверка живости — исключение: оркестратору полезно видеть, что процесс
    // ещё отвечает и именно прощается, а не завис.
    if (request.url.split('?')[0] === '/health/live') return;
    return reply
      .status(503)
      .header('connection', 'close')
      .header('retry-after', String(RETRY_AFTER_SECONDS))
      .send({
        error: 'ServiceUnavailable',
        message: `Сервер останавливается и новые обращения не принимает. Повторите через ${RETRY_AFTER_SECONDS} секунд.`,
        statusCode: 503,
        code: codeForStatus(503),
        requestId: String(request.id),
      });
  });

  return guard;
}

/**
 * Подписывается на сигналы остановки. Отдельно от заслона: заслон живёт вместе
 * с приложением (и нужен в прогонах), подписка на сигналы процесса — только у
 * настоящего запуска.
 */
export function installGracefulShutdown(
  app: FastifyInstance,
  guard: ShutdownGuard,
  deadlineMs: number = SHUTDOWN_DEADLINE_MS,
): void {
  for (const signal of ['SIGTERM', 'SIGINT'] as const) {
    process.once(signal, () => {
      if (!guard.begin()) return;
      app.log.info(`Получен сигнал ${signal}: закрываем сервер`);

      const forceExit = setTimeout(() => {
        app.log.warn('Закрытие затянулось — выходим принудительно');
        process.exit(1);
      }, deadlineMs);
      // unref: сам по себе этот таймер держать процесс живым не должен —
      // если закрытие успело, выходим сразу, не досиживая десять секунд.
      forceExit.unref();

      void app
        .close()
        .then(() => {
          clearTimeout(forceExit);
          process.exit(0);
        })
        .catch((err: unknown) => {
          clearTimeout(forceExit);
          // Код выхода 1: закрытие не удалось. Оркестратор вправе отличать
          // штатное прощание от неудавшегося — прежний нулевой код выдавал
          // второе за первое.
          app.log.error({ err }, 'Ошибка при закрытии сервера');
          process.exit(1);
        });
    });
  }
}
