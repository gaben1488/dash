/**
 * Признак «данные показательные, а не настоящие» — во всех ответах сразу.
 *
 * Реестр багов 09.07.2026, п.8 («демо-данные неотличимы клиентом»). Когда
 * учётные данные Google не настроены, продукту неоткуда взять книги управлений,
 * и снимок собирается генератором-образцом. Раньше об этом можно было
 * догадаться единственным способом: на пульте посмотреть, начинается ли
 * идентификатор снимка со слова demo. Любой другой ответ — «Контроль», реестр
 * строк, аналитика, выгрузка — отдавал сочинённые числа тем же видом, что и
 * настоящие: отличить было НЕЧЕМ. Показанное про реальные управления число,
 * которого никто не считал, — худший вид неправды в этом продукте.
 *
 * Механизм. Показательные данные возможны ровно в одном состоянии — учётные
 * данные Google не заданы (config.isDemoMode); при настроенных ключах отказ
 * источника отдаётся честно (последний сохранённый снимок либо 503), а
 * генератор-образец не зовётся никогда (services/snapshot.ts). Поэтому признак
 * ставится не по каждому ответу отдельно, а один раз на весь сервер, и он не
 * может разойтись с тем, что на самом деле показано.
 *
 * Адрес признака — заголовок ответа, а не поле в теле. Причина: тела ответов
 * этого сервера бывают трёх разных родов — карточка (объект с полями), СПИСОК
 * (массив) и СПРАВОЧНИК ПО УПРАВЛЕНИЯМ (объект, каждый ключ которого —
 * идентификатор ГРБС: /analytics/scorecard, /analytics/anticorruption,
 * /rows/subordinates). Дописанное в такой справочник поле стало бы девятым
 * «управлением» с выдуманным именем, то есть новой неправдой вместо снятой.
 * Заголовок одинаково доступен всем трём родам, и выгрузкам (CSV) тоже.
 */
import type { FastifyInstance } from 'fastify';
import { isDemoMode } from '../config.js';

/** Заголовок-признак: «данные показательные». Один на сервер и на страницы. */
export const DEMO_HEADER = 'x-aemr-demo-data';

export function registerDemoMarker(app: FastifyInstance, demo: boolean = isDemoMode): void {
  if (!demo) return;

  app.addHook('onSend', async (request, reply, payload) => {
    if (request.url.startsWith('/api/')) {
      reply.header(DEMO_HEADER, '1');
    }
    return payload;
  });
}
