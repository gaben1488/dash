/**
 * Влить доводку в основной реестр карточек.
 *
 * Заплатка кладётся ПОВЕРХ существующей записи: у ключа, который в реестре
 * уже есть, сохраняются все его прежние поля, а перечисленные здесь —
 * заменяются. Так дописываются пороги и действия к неполным карточкам ядра,
 * не переписывая их целиком.
 */
export function applyKbUplift(base: Record<string, KBEntryData>): void {
  for (const [key, patch] of Object.entries(KB_UPLIFT)) {
    const prev = base[key];
    base[key] = { ...(prev ?? {}), ...patch } as KBEntryData;
  }
}
