/** Текст ячейки или null (не строка / пусто). */
function textOf(cells: Record<string, unknown>, col: string): string | null {
  const v = cells[col];
  if (typeof v !== 'string') return null;
  const t = v.trim();
  return t.length > 0 ? t : null;
}

/** Фрагмент текста вокруг [start, end) с многоточиями по краям. */
function excerptAround(text: string, start: number, end: number): string {
  const from = Math.max(0, start - EXCERPT_RADIUS);
  const to = Math.min(text.length, end + EXCERPT_RADIUS);
  const prefix = from > 0 ? '…' : '';
  const suffix = to < text.length ? '…' : '';
  return prefix + text.slice(from, to).replace(/\s+/gu, ' ').trim() + suffix;
}

/** Номер календарных суток снимка — из ЛОКАЛЬНЫХ компонент (как в signals.ts). */
function snapshotDayOf(snapshotDate: Date): number {
  return Date.UTC(snapshotDate.getFullYear(), snapshotDate.getMonth(), snapshotDate.getDate()) / 86400000;
}

/** «дд.мм.гггг» из номера суток — для текста карточек. */
function ruDateOfDay(day: number): string {
  const [y, m, d] = isoOfDayNumber(day).split('-');
  return `${d}.${m}.${y}`;
}

