/**
 * Маркеры стадий размещения — правило (а). Набор задан директивой волны
 * 14.08.2026. ВНИМАНИЕ: `\w` в JS не матчит кириллицу — окончания слов
 * покрываются классом [а-яё] с флагом iu.
 */
const STAGE_MARKERS: ReadonlyArray<{ re: RegExp; label: string }> = [
  { re: /подач[а-яё]*\s+заявок/iu, label: 'подача заявок' },
  { re: /будет\s+размещ/iu, label: 'будет размещена' },
  { re: /протокол/iu, label: 'протокол' },
  { re: /на\s+подписании/iu, label: 'на подписании' },
  { re: /планируется\s+размещение/iu, label: 'планируется размещение' },
];

/**
 * Обещание с датой — правило (б): «будет заключен/подписан/размещён [до]
 * ДД.ММ[.ГГГГ]». Живые формы из дампа 14.08.2026: «договор будет заключен
 * 01.06.2026» (УО, строка листа 331, AF), «контракт будет заключен 2.09.2026»
 * (УКСиМП, строка 88, AF); форма с «до» — эталон владельца std-dop-infa.txt
 * строка 10: «Контракт будет подписан до 31.07.2026».
 */
const PROMISE_RE =
  /будет\s+(?:заключ|подписан|размещ)[а-яё]*\s*(?:до\s+)?(\d{1,2})\.(\d{1,2})(?:\.(\d{4}))?/iu;

/** Колонки, сканируемые правилом (а) — по формулировке директивы: AF и AE. */
const STAGE_SCAN_COLUMNS: ReadonlyArray<CommentColumn> = ['AF', 'AE'];

/** Колонки, сканируемые правилом (б): все комментарные текстовые колонки. */
const PROMISE_SCAN_COLUMNS: ReadonlyArray<CommentColumn> = ['U', 'AE', 'AF', 'AG', 'AH'];

/**
 * Отложенный срок в тексте: «отложено/перенесено/переносится … до ДД.ММ[.ГГГГ]»,
 * «планируется на ДД.ММ», «срок сдвинут на ДД.ММ». Ловит дату ОБЕЩАНИЯ, а не
 * дату факта: факт берётся исключительно из структурной Q (канон п.27).
 */
const POSTPONE_RE =
  /(?:отложен[а-яё]*|перенесен[а-яё]*|переносится|сдвинут[а-яё]*|планируется)[^.;)]{0,40}?(?:до|на)\s+(\d{1,2})\.(\d{1,2})(?:\.(\d{4}))?/iu;

/**
 * Даты ЧУЖИХ документов, которые нельзя принимать за срок закупки: у них свой
 * маркер прямо перед датой. Именно из-за смешения таких дат с датой контракта
 * владелец в августе отключил чтение текста (канон п.110) — теперь они
 * распознаются и ИСКЛЮЧАЮТСЯ, а не толкуются.
 */
const FOREIGN_DATE_RE =
  /(?:распоряжени[ея]|постановлени[ея]|приказ|протокол|письм[оа]|решени[ея]|заявк[аи]|служебн\w*)[^.;)]{0,30}?(?:от\s+)?(\d{1,2})\.(\d{1,2})(?:\.(\d{4}))?/giu;

/**
 * Отрицание ЗАКЛЮЧЕНИЯ КОНТРАКТА — при заполненной Q это прямое противоречие.
 *
 * Осторожно с предметом отрицания: «аукцион не состоялся» относится к
 * ПРОЦЕДУРЕ и является законным основанием закупки у единственного поставщика
 * (п. 25 ч. 1 ст. 93). Такие фразы противоречием НЕ являются и отсеиваются
 * ниже (PROCEDURE_SUBJECT_RE). Отрицание считается противоречием, только когда
 * речь о самом договоре.
 */
const DENIAL_MARKERS: ReadonlyArray<{ re: RegExp; label: string; procedureOk?: true }> = [
  { re: /не\s+заключ[её]н/iu, label: 'не заключён' },
  // Ход процедуры: «аукцион не состоялся / не размещён» — законный сюжет,
  // если рядом названа процедура. Проверяется отдельно (procedureOk).
  { re: /не\s+состоял[аи]?с[ья]/iu, label: 'не состоялась', procedureOk: true },
  { re: /не\s+размещ[её]н/iu, label: 'не размещён', procedureOk: true },
  // Отмена ПРОЦЕДУРЫ при заключённом контракте — законный сюжет: процедуру
  // сняли, разместили повторно, договор заключили (живой пример: УЭР r41).
  // Противоречие — только когда отменена сама ЗАКУПКА.
  { re: /отменен[а-яё]*|отмен[её]н[а-яё]*/iu, label: 'отменена', procedureOk: true },
  // Расторжение из списка снято (живой прогон 18.08): договор сначала
  // заключают, потом расторгают — «контракт исполнен на 46 844,74, расторгнут
  // досрочно» противоречием не является, это нормальный ход событий.
];

/**
 * Речь идёт о процедуре, а не о договоре: аукцион, конкурс, запрос котировок,
 * номер процедуры рядом. «Аукцион не состоялся» при заключённом контракте —
 * норма (закупка у единственного поставщика после несостоявшихся торгов),
 * а не устаревший комментарий.
 */
const PROCEDURE_SUBJECT_RE =
  /(?:аукцион|электронн\w+\s+процедур\w*|конкурс|котировк\w*|торг[аи]?|процедур\w*|извещени|заявк\w*|(?<![А-Яа-яЁё])Э(?:АС|ЗК|А|К)(?![а-яё]))/iu;

/** Отрицание относится к процедуре, если её упоминание стоит рядом с маркером. */
function denialAboutProcedure(text: string, at: number): boolean {
  const from = Math.max(0, at - 60);
  const to = Math.min(text.length, at + 60);
  return PROCEDURE_SUBJECT_RE.test(text.slice(from, to));
}

/**
 * Утверждение об исполнении ЗАКУПКИ — при отсутствии фактических сумм это
 * противоречие.
 *
 * Живой прогон 18.08 по 1 199 строкам показал: слово «исполнение» в книгах чаще
 * значит совсем другое — «качество исполнения швов», «с целью исполнения
 * санитарных норм», «во исполнение предписания». Поэтому корень «исполнен»
 * засчитывается ТОЛЬКО рядом с договором или обязательством, а обороты
 * «качество исполнения», «с целью исполнения», «во исполнение» исключаются.
 */
const EXECUTION_MARKERS: ReadonlyArray<{ re: RegExp; label: string }> = [
  { re: /оплачен[а-яё]*|оплата\s+произведена/iu, label: 'оплачено' },
  { re: /(?:контракт|договор|обязательств[а-яё]*)\s+(?:полностью\s+)?исполнен[а-яё]*/iu, label: 'договор исполнен' },
  { re: /исполнен[а-яё]*\s+(?:контракт|договор)/iu, label: 'договор исполнен' },
  { re: /работы\s+выполнен[ыаио]/iu, label: 'работы выполнены' },
  { re: /товар\s+поставлен/iu, label: 'товар поставлен' },
  { re: /услуг[аи]\s+оказан[ыаио]/iu, label: 'услуги оказаны' },
];

/** Обороты со словом «исполнение», не относящиеся к оплате закупки. */
const EXECUTION_FALSE_FRIENDS =
  /(?:качеств\w*|цель[юя]?|целях|во\s+исполнение|порядк\w*|сроки?)\s+исполнени/iu;

/** Колонки правил (д)-(ж): те же текстовые поля, что у правила (б). */
const CLAIM_SCAN_COLUMNS: ReadonlyArray<CommentColumn> = ['U', 'AE', 'AF', 'AG', 'AH'];

/** Диапазоны дат чужих документов в тексте — чтобы не спутать их со сроком. */
function foreignDateSpans(text: string): Array<[number, number]> {
  const spans: Array<[number, number]> = [];
  FOREIGN_DATE_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = FOREIGN_DATE_RE.exec(text)) !== null) {
    spans.push([m.index, m.index + m[0].length]);
  }
  return spans;
}

/** Попадает ли найденная дата внутрь ссылки на чужой документ. */
function insideForeignDate(spans: ReadonlyArray<[number, number]>, at: number): boolean {
  return spans.some(([from, to]) => at >= from && at < to);
}

/** Есть ли в строке хоть какие-то фактические деньги (V/W/X/Y). */
function hasFactMoney(cells: Record<string, unknown>): boolean {
  for (const col of ['V', 'W', 'X', 'Y']) {
    const raw = cells[col];
    if (raw === null || raw === undefined) continue;
    const n = Number(String(raw).replace(/\s/gu, '').replace(',', '.'));
    if (Number.isFinite(n) && n > 0) return true;
  }
  return false;
}

/** Радиус контекста вокруг совпадения в excerpt, символов. */
const EXCERPT_RADIUS = 60;

