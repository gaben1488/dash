/** Текстовые колонки комментариев книг ГРБС (директива п.72). */
export type CommentColumn = 'M' | 'U' | 'AE' | 'AF' | 'AG' | 'AH';

/**
 * Вид несогласованности комментария со структурными колонками.
 *
 * - `stage_marker_when_signed` — правило (а): текст описывает стадию
 *   размещения (подача заявок / будет размещена / протокол / на подписании /
 *   планируется размещение), а контракт уже заключён (Q — валидная дата).
 * - `past_promise_no_fact` — правило (б): текст обещает «будет
 *   заключен/подписан/размещён [до] ДД.ММ[.ГГГГ]», дата обещания прошла
 *   относительно даты снимка, а дата заключения (Q) — заглушка.
 * - `stage_vs_monitoring` — правило (в), ЗАГЛУШКА ИНТЕРФЕЙСА: устаревшая
 *   стадия против книги «Ежедневный мониторинг». Тип объявлен, карточки этого
 *   вида НЕ эмитятся — реализация после связки строк книг ГРБС со строками
 *   мониторинга (отдельная волна, п.72(в)).
 * - `foreign_text_in_ag` — правило (г), канон п.74(б): в колонке AG (структурный
 *   ключ «номер процедуры», п.74(а)) посторонний текст — либо приписка рядом с
 *   валидным номером, либо содержимое вовсе без распознаваемого номера
 *   (в т.ч. искажённый код, который парсер честно не признал). Не трётся молча —
 *   карточка «перенести в примечание». Чтение структурное (detectForeignText):
 *   свободный текст машинно не интерпретируется (п.27 в силе).
 * - `promise_after_fact` — правило (д), канон п.110 (уточнение владельца
 *   18.08.2026): комментарий откладывает закупку на дату ПОЗЖЕ той, когда
 *   контракт уже заключён («отложено до 01.09», а в Q стоит 15.08). Текст
 *   пережил событие и вводит читателя в заблуждение.
 * - `denial_when_signed` — правило (е): текст ОТРИЦАЕТ заключение («не
 *   заключён», «не состоялась», «отменена», «расторгнут»), а структурная Q
 *   несёт дату. Ровно тот случай, из-за которого в августе «не заключен»
 *   читался как «подписан»: теперь текст не меняет статус, а получает
 *   карточку противоречия.
 * - `execution_claim_no_fact` — правило (ж): текст утверждает исполнение или
 *   оплату («оплачено», «исполнен», «работы выполнены»), а фактических сумм
 *   в строке нет (V/W/X/Y пусты либо нули). Либо деньги не внесены в книгу,
 *   либо комментарий опережает события.
 * - `missing_procedure_ref` — правило (и), поручение владельца 19.08:
 *   у КОНКУРЕНТНОЙ строки (способ ЭА/ЭЗК/ЭАС/ЭК) в комментарии УЭР (AG)
 *   нет номера процедуры. Номер вида «ЭА152-26» — единственный ключ,
 *   которым строка книги связывается с книгой «Ежедневный мониторинг»
 *   (канон п.74, п.101а): без него сверка НМЦК и цены торгов для этой
 *   закупки невозможна. У закупок у единственного поставщика процедуры
 *   нет — правило их не трогает.
 * - `ep_reason_on_competitive` — правило (к), вопрос владельца 20.08:
 *   способ в L конкурентный (ЭА/ЭЗК/ЭАС/ЭК), а колонка M («Обоснование
 *   выбора способа — в случае ЕП») несёт текст про единственного
 *   поставщика или ссылку на ст.93. Либо способ в L устарел после смены,
 *   либо обоснование попало не в ту колонку. Живой пример: УО № п/п 2346
 *   («ЭА» + «Закупка с ЕП предусматривает заключение по наименьшей цене»);
 *   отдельный род внутри — «ч.12 ст.93» у 12 строк УД: малые закупки через
 *   электронную площадку формально идут по ЕП, и тогда неточен способ L.
 */
export type CommentInconsistencyKind =
  | 'stage_marker_when_signed'
  | 'past_promise_no_fact'
  | 'stage_vs_monitoring'
  | 'foreign_text_in_ag'
  | 'promise_after_fact'
  | 'denial_when_signed'
  | 'execution_claim_no_fact'
  | 'missing_procedure_ref'
  | 'ep_reason_on_competitive';

/** Адрес строки книги ГРБС: книга + номер строки ЛИСТА (канон нумерации п.28). */
export interface CommentRowRef {
  /** Книга ГРБС (например «УО», «УЭР», «УД»). */
  book: string;
  /** Номер строки листа (нумерация самого листа, не выборки). */
  sheetRow: number;
}

/**
 * Аннотация несогласованности — карточка диагноста (п.53) с полным
 * провенансом: откуда взят текст (ячейка), что именно совпало (excerpt),
 * почему это несогласованность (mechanism) и что делать (action).
 */
export interface CommentAnnotation {
  /** Ключ строки: `<книга>:r<номер строки листа>` (например «УД:r14»). */
  rowKey: string;
  /** Колонка комментария, в которой найден несогласованный текст. */
  column: CommentColumn;
  /** Адрес ячейки листа: буква колонки + номер строки (например «AF14»). */
  cell: string;
  /** Вид несогласованности. */
  kind: CommentInconsistencyKind;
  /** Фрагмент текста вокруг совпадения (провенанс: что именно совпало). */
  excerpt: string;
  /** (п.53 часть 1) Механизм простыми словами: что чему противоречит. */
  mechanism: string;
  /** (п.53 часть 3) Действие с адресатом — владельцу книги: обновить комментарий. */
  action: string;
}

/**
 * ЗАГЛУШКА под правило (в) — контекст стадии из книги «Ежедневный мониторинг».
 * Пока связка «строка книги ГРБС ↔ строка мониторинга» не построена, параметр
 * не используется и карточки `stage_vs_monitoring` не эмитятся.
 */
export interface MonitoringStageContext {
  /** Стадия процедуры по мониторингу (свободная форма листа мониторинга). */
  stage?: string;
}

