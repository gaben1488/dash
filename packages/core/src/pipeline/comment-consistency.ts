/**
 * comment-consistency.ts — сигнал несогласованности комментария со структурой.
 *
 * ДИРЕКТИВА п.72(а) интервью 14.08.2026: сигнал по НЕАКТУАЛЬНЫМ комментариям —
 * текст описывает этапность, противоречащую факту (например «в стадии подачи
 * заявок» при заключённом контракте).
 *
 * ГРАНИЦА КАНОНА п.27: из свободного текста НЕЛЬЗЯ выводить статус закупки.
 * Здесь статус НЕ выводится: статус берётся ТОЛЬКО из структурной колонки Q
 * (дата заключения), а текст лишь проверяется на СОГЛАСОВАННОСТЬ с ним.
 * Результат — карточка «комментарий устарел — обновите» с адресом ячейки
 * (стандарт диагноста п.53: механизм / адрес / действие), а не изменение
 * какого-либо сигнала или статуса. Существующие signals.ts / validate.ts
 * эта подсистема не трогает и не переопределяет.
 *
 * Колонки (семантика по дампу comments-full.jsonl, снят с прода 14.08.2026):
 *   M = обоснование ЕП, U = статус/причина отклонения, AE = примечание,
 *   AF = комм. ГРБС, AG = комм. УЭР, AH = комм. УФБП,
 *   Q = дата заключения (структурная), N = план-дата.
 */

import { dayNumberOf, isoOfDayNumber } from '@aemr/shared';

// ────────────────────────────────────────────────────────────
// Типы
// ────────────────────────────────────────────────────────────

/** Текстовые колонки комментариев книг ГРБС (директива п.72). */
export type CommentColumn = 'M' | 'U' | 'AE' | 'AF' | 'AG' | 'AH';

/**
 * Вид несогласованности комментария со структурными колонками.
 *
 * - `stage_marker_when_signed` — правило (а): текст описывает стадию
 *   размещения (подача заявок / будет размещена / протокол / на подписании /
 *   планируется размещение), а контракт уже заключён (Q — валидная дата).
 * - `past_promise_no_fact` — правило (б): текст обещает «будет
 *   заключен/подписан/размещён [до] ДД.ММ[.ГГГГ]», дата обещания прошла
 *   относительно даты снимка, а дата заключения (Q) — заглушка.
 * - `stage_vs_monitoring` — правило (в), ЗАГЛУШКА ИНТЕРФЕЙСА: устаревшая
 *   стадия против книги «Ежедневный мониторинг». Тип объявлен, карточки этого
 *   вида НЕ эмитятся — реализация после связки строк книг ГРБС со строками
 *   мониторинга (отдельная волна, п.72(в)).
 */
export type CommentInconsistencyKind =
  | 'stage_marker_when_signed'
  | 'past_promise_no_fact'
  | 'stage_vs_monitoring';

/** Адрес строки книги ГРБС: книга + номер строки ЛИСТА (канон нумерации п.28). */
export interface CommentRowRef {
  /** Книга ГРБС (например «УО», «УЭР», «УД»). */
  book: string;
  /** Номер строки листа (нумерация самого листа, не выборки). */
  sheetRow: number;
}

/**
 * Аннотация несогласованности — карточка диагноста (п.53) с полным
 * провенансом: откуда взят текст (ячейка), что именно совпало (excerpt),
 * почему это несогласованность (mechanism) и что делать (action).
 */
export interface CommentAnnotation {
  /** Ключ строки: `<книга>:r<номер строки листа>` (например «УД:r14»). */
  rowKey: string;
  /** Колонка комментария, в которой найден несогласованный текст. */
  column: CommentColumn;
  /** Адрес ячейки листа: буква колонки + номер строки (например «AF14»). */
  cell: string;
  /** Вид несогласованности. */
  kind: CommentInconsistencyKind;
  /** Фрагмент текста вокруг совпадения (провенанс: что именно совпало). */
  excerpt: string;
  /** (п.53 часть 1) Механизм простыми словами: что чему противоречит. */
  mechanism: string;
  /** (п.53 часть 3) Действие с адресатом — владельцу книги: обновить комментарий. */
  action: string;
}

/**
 * ЗАГЛУШКА под правило (в) — контекст стадии из книги «Ежедневный мониторинг».
 * Пока связка «строка книги ГРБС ↔ строка мониторинга» не построена, параметр
 * не используется и карточки `stage_vs_monitoring` не эмитятся.
 */
export interface MonitoringStageContext {
  /** Стадия процедуры по мониторингу (свободная форма листа мониторинга). */
  stage?: string;
}

// ────────────────────────────────────────────────────────────
// Правила (регексы)
// ────────────────────────────────────────────────────────────

/**
 * Маркеры стадий размещения — правило (а). Набор задан директивой волны
 * 14.08.2026. ВНИМАНИЕ: `\w` в JS не матчит кириллицу — окончания слов
 * покрываются классом [а-яё] с флагом iu.
 */
const STAGE_MARKERS: ReadonlyArray<{ re: RegExp; label: string }> = [
  { re: /подач[а-яё]*\s+заявок/iu, label: 'подача заявок' },
  { re: /будет\s+размещ/iu, label: 'будет размещена' },
  { re: /протокол/iu, label: 'протокол' },
  { re: /на\s+подписании/iu, label: 'на подписании' },
  { re: /планируется\s+размещение/iu, label: 'планируется размещение' },
];

/**
 * Обещание с датой — правило (б): «будет заключен/подписан/размещён [до]
 * ДД.ММ[.ГГГГ]». Живые формы из дампа 14.08.2026: «договор будет заключен
 * 01.06.2026» (УО, строка листа 331, AF), «контракт будет заключен 2.09.2026»
 * (УКСиМП, строка 88, AF); форма с «до» — эталон владельца std-dop-infa.txt
 * строка 10: «Контракт будет подписан до 31.07.2026».
 */
const PROMISE_RE =
  /будет\s+(?:заключ|подписан|размещ)[а-яё]*\s*(?:до\s+)?(\d{1,2})\.(\d{1,2})(?:\.(\d{4}))?/iu;

/** Колонки, сканируемые правилом (а) — по формулировке директивы: AF и AE. */
const STAGE_SCAN_COLUMNS: ReadonlyArray<CommentColumn> = ['AF', 'AE'];

/** Колонки, сканируемые правилом (б): все комментарные текстовые колонки. */
const PROMISE_SCAN_COLUMNS: ReadonlyArray<CommentColumn> = ['U', 'AE', 'AF', 'AG', 'AH'];

/** Радиус контекста вокруг совпадения в excerpt, символов. */
const EXCERPT_RADIUS = 60;

// ────────────────────────────────────────────────────────────
// Вспомогательные
// ────────────────────────────────────────────────────────────

/** Текст ячейки или null (не строка / пусто). */
function textOf(cells: Record<string, unknown>, col: string): string | null {
  const v = cells[col];
  if (typeof v !== 'string') return null;
  const t = v.trim();
  return t.length > 0 ? t : null;
}

/** Фрагмент текста вокруг [start, end) с многоточиями по краям. */
function excerptAround(text: string, start: number, end: number): string {
  const from = Math.max(0, start - EXCERPT_RADIUS);
  const to = Math.min(text.length, end + EXCERPT_RADIUS);
  const prefix = from > 0 ? '…' : '';
  const suffix = to < text.length ? '…' : '';
  return prefix + text.slice(from, to).replace(/\s+/gu, ' ').trim() + suffix;
}

/** Номер календарных суток снимка — из ЛОКАЛЬНЫХ компонент (как в signals.ts). */
function snapshotDayOf(snapshotDate: Date): number {
  return Date.UTC(snapshotDate.getFullYear(), snapshotDate.getMonth(), snapshotDate.getDate()) / 86400000;
}

/** «дд.мм.гггг» из номера суток — для текста карточек. */
function ruDateOfDay(day: number): string {
  const [y, m, d] = isoOfDayNumber(day).split('-');
  return `${d}.${m}.${y}`;
}

// ────────────────────────────────────────────────────────────
// Основная функция
// ────────────────────────────────────────────────────────────

/**
 * Проверяет ОДНУ строку книги ГРБС на несогласованность текста комментариев
 * со структурной колонкой Q (дата заключения).
 *
 * @param ref — адрес строки (книга + номер строки листа)
 * @param cells — сырые колонки строки: словарь «буква колонки → значение»
 * @param snapshotDate — дата снимка данных; «сейчас» правил (б). Никаких
 *   Date.now внутри: воспроизводимость на историческом снимке обязательна.
 * @param _monitoring — ЗАГЛУШКА правила (в), не используется до связки
 *   с «Ежедневным мониторингом»
 * @returns карточки несогласованности; пусто — противоречий не найдено
 */
export function detectCommentInconsistencies(
  ref: CommentRowRef,
  cells: Record<string, unknown>,
  snapshotDate: Date,
  _monitoring?: MonitoringStageContext,
): CommentAnnotation[] {
  const annotations: CommentAnnotation[] = [];
  const rowKey = `${ref.book}:r${ref.sheetRow}`;
  const factDay = dayNumberOf(cells['Q']); // null = заглушка (Х/X/пусто/мусор)
  const snapDay = snapshotDayOf(snapshotDate);

  // ── Правило (а): этапность при заключённом ──
  // Статус «заключено» — ТОЛЬКО структурная Q (канон п.27). Текст стадии
  // размещения при заполненной Q написан до заключения → комментарий устарел.
  if (factDay !== null) {
    for (const column of STAGE_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      for (const marker of STAGE_MARKERS) {
        const m = marker.re.exec(text);
        if (m === null || m.index === undefined) continue;
        annotations.push({
          rowKey,
          column,
          cell: `${column}${ref.sheetRow}`,
          kind: 'stage_marker_when_signed',
          excerpt: excerptAround(text, m.index, m.index + m[0].length),
          mechanism:
            `Комментарий описывает стадию размещения процедуры (маркер «${marker.label}»), ` +
            `но контракт по этой строке уже заключён: в Q${ref.sheetRow} стоит дата ${ruDateOfDay(factDay)}. ` +
            `Текст написан до заключения и больше не отражает состояние закупки.`,
          action:
            `Владельцу книги «${ref.book}»: обновите комментарий в ячейке ${column}${ref.sheetRow} — ` +
            `опишите текущее состояние после заключения контракта или удалите устаревшую этапность.`,
        });
        break; // одна карточка на ячейку: каскад маркеров одной причины = одна карточка (п.53)
      }
    }
  }

  // ── Правило (б): просроченное обещание при незаключённом ──
  // «Будет заключен/подписан/размещён [до] ДД.ММ[.ГГГГ]» с датой в прошлом
  // относительно снимка, а Q — заглушка. Год не указан → берётся год снимка
  // (в дампе 14.08.2026 бездатных-по-году обещаний 0, ветка — по букве директивы).
  if (factDay === null) {
    for (const column of PROMISE_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      const m = PROMISE_RE.exec(text);
      if (m === null || m.index === undefined) continue;
      const dd = parseInt(m[1], 10);
      const mm = parseInt(m[2], 10);
      const yyyy = m[3] !== undefined ? parseInt(m[3], 10) : snapshotDate.getFullYear();
      if (dd < 1 || dd > 31 || mm < 1 || mm > 12) continue;
      const promiseDay = Date.UTC(yyyy, mm - 1, dd) / 86400000;
      if (promiseDay >= snapDay) continue; // обещание ещё в силе — не карточка
      annotations.push({
        rowKey,
        column,
        cell: `${column}${ref.sheetRow}`,
        kind: 'past_promise_no_fact',
        excerpt: excerptAround(text, m.index, m.index + m[0].length),
        mechanism:
          `Комментарий обещает заключение/размещение до ${ruDateOfDay(promiseDay)}, эта дата уже прошла ` +
          `(снимок от ${ruDateOfDay(snapDay)}), а дата заключения Q${ref.sheetRow} не проставлена. ` +
          `Либо обещание не исполнено, либо комментарий не обновлён после заключения.`,
        action:
          `Владельцу книги «${ref.book}»: обновите комментарий в ячейке ${column}${ref.sheetRow} — ` +
          `укажите актуальный срок; если контракт уже заключён, проставьте дату заключения в Q${ref.sheetRow}.`,
      });
    }
  }

  // ── Правило (в): устаревшая стадия против «Ежедневного мониторинга» ──
  // ЗАГЛУШКА (п.72(в)): реализация после связки строк ГРБС со строками
  // мониторинга. Тип 'stage_vs_monitoring' объявлен, карточки не эмитятся.

  return annotations;
}
