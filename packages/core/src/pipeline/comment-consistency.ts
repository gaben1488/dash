/**
 * Проверяет ОДНУ строку книги ГРБС на несогласованность текста комментариев
 * со структурной колонкой Q (дата заключения).
 *
 * @param ref — адрес строки (книга + номер строки листа)
 * @param cells — сырые колонки строки: словарь «буква колонки → значение»
 * @param snapshotDate — дата снимка данных; «сейчас» правил (б). Никаких
 *   Date.now внутри: воспроизводимость на историческом снимке обязательна.
 * @param _monitoring — ЗАГЛУШКА правила (в), не используется до связки
 *   с «Ежедневным мониторингом»
 * @returns карточки несогласованности; пусто — противоречий не найдено
 */
export function detectCommentInconsistencies(
  ref: CommentRowRef,
  cells: Record<string, unknown>,
  snapshotDate: Date,
  _monitoring?: MonitoringStageContext,
): CommentAnnotation[] {
  const annotations: CommentAnnotation[] = [];
  const rowKey = `${ref.book}:r${ref.sheetRow}`;
  const factDay = dayNumberOf(cells['Q']); // null = заглушка (Х/X/пусто/мусор)
  const snapDay = snapshotDayOf(snapshotDate);

  // ── Правило (а): этапность при заключённом ──
  // Статус «заключено» — ТОЛЬКО структурная Q (канон п.27). Текст стадии
  // размещения при заполненной Q написан до заключения → комментарий устарел.
  if (factDay !== null) {
    for (const column of STAGE_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      for (const marker of STAGE_MARKERS) {
        const m = marker.re.exec(text);
        if (m === null || m.index === undefined) continue;
        annotations.push({
          rowKey,
          column,
          cell: `${column}${ref.sheetRow}`,
          kind: 'stage_marker_when_signed',
          excerpt: excerptAround(text, m.index, m.index + m[0].length),
          mechanism:
            `Комментарий описывает стадию размещения процедуры (маркер «${marker.label}»), ` +
            `но контракт по этой строке уже заключён: в Q${ref.sheetRow} стоит дата ${ruDateOfDay(factDay)}. ` +
            `Текст написан до заключения и больше не отражает состояние закупки.`,
          action:
            `Владельцу книги «${ref.book}»: обновите комментарий в ячейке ${column}${ref.sheetRow} — ` +
            `опишите текущее состояние после заключения контракта или удалите устаревшую этапность.`,
        });
        break; // одна карточка на ячейку: каскад маркеров одной причины = одна карточка (п.53)
      }
    }
  }

  // ── Правило (б): просроченное обещание при незаключённом ──
  // «Будет заключен/подписан/размещён [до] ДД.ММ[.ГГГГ]» с датой в прошлом
  // относительно снимка, а Q — заглушка. Год не указан → берётся год снимка
  // (в дампе 14.08.2026 бездатных-по-году обещаний 0, ветка — по букве директивы).
  if (factDay === null) {
    for (const column of PROMISE_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      const m = PROMISE_RE.exec(text);
      if (m === null || m.index === undefined) continue;
      const dd = parseInt(m[1], 10);
      const mm = parseInt(m[2], 10);
      const yyyy = m[3] !== undefined ? parseInt(m[3], 10) : snapshotDate.getFullYear();
      if (dd < 1 || dd > 31 || mm < 1 || mm > 12) continue;
      const promiseDay = Date.UTC(yyyy, mm - 1, dd) / 86400000;
      if (promiseDay >= snapDay) continue; // обещание ещё в силе — не карточка
      annotations.push({
        rowKey,
        column,
        cell: `${column}${ref.sheetRow}`,
        kind: 'past_promise_no_fact',
        excerpt: excerptAround(text, m.index, m.index + m[0].length),
        mechanism:
          `Комментарий обещает заключение/размещение до ${ruDateOfDay(promiseDay)}, эта дата уже прошла ` +
          `(снимок от ${ruDateOfDay(snapDay)}), а дата заключения Q${ref.sheetRow} не проставлена. ` +
          `Либо обещание не исполнено, либо комментарий не обновлён после заключения.`,
        action:
          `Владельцу книги «${ref.book}»: обновите комментарий в ячейке ${column}${ref.sheetRow} — ` +
          `укажите актуальный срок; если контракт уже заключён, проставьте дату заключения в Q${ref.sheetRow}.`,
      });
    }
  }

  // ── Правило (в): устаревшая стадия против «Ежедневного мониторинга» ──
  // ЗАГЛУШКА (п.72(в)): реализация после связки строк ГРБС со строками
  // мониторинга. Тип 'stage_vs_monitoring' объявлен, карточки не эмитятся.

  // ── Правило (г): посторонний текст в колонке номера процедуры (п.74(б)) ──
  // AG — структурный ключ «номер процедуры» (канон п.74(а)), основной мост к
  // «Ежедневному мониторингу». Не-номерное содержимое НЕ трётся молча и не
  // зависит от Q: detectForeignText вычитает валидные коды и разделители,
  // непустой остаток — карточка. Два живых случая дампа 14.08.2026 различаются
  // текстом механизма: «код + приписка» (extractProcedureRefs непуст) и
  // «ни одного кода» (в т.ч. искажённый номер: «ЭЗК 283», «ЭК03-26»).
  const agForeign = detectForeignText(cells['AG']);
  if (agForeign !== null) {
    const agRefs = extractProcedureRefs(cells['AG']);
    const excerpt =
      agForeign.length > EXCERPT_RADIUS * 2
        ? `${agForeign.slice(0, EXCERPT_RADIUS * 2)}…`
        : agForeign;
    const mechanism =
      agRefs.length > 0
        ? `В ячейке AG${ref.sheetRow} рядом с номером процедуры (${agRefs.map((r) => r.code).join(', ')}) ` +
          `стоит посторонний текст: «${excerpt}». Колонка AG — структурный ключ «номер процедуры» ` +
          `(канон п.74): приписки мешают связке строки с «Ежедневным мониторингом».`
        : `Ячейка AG${ref.sheetRow} не содержит распознаваемого номера процедуры ` +
          `(канонический формат «ЭА152-26», семейства ЭА/ЭЗК/ЭЕП/ЭАС): «${excerpt}». ` +
          `Колонка AG — структурный ключ «номер процедуры»: такой текст (или искажённый номер) ` +
          `связке с «Ежедневным мониторингом» не подлежит.`;
    const action =
      agRefs.length > 0
        ? `Владельцу книги «${ref.book}»: перенесите посторонний текст из AG${ref.sheetRow} в примечание ` +
          `(AE${ref.sheetRow}), в AG${ref.sheetRow} оставьте только номер процедуры — без пробелов и приписок (п.74(в)).`
        : `Владельцу книги «${ref.book}»: если это номер процедуры — исправьте AG${ref.sheetRow} до канонического ` +
          `формата (например «ЭА152-26»); если это комментарий — перенесите его в примечание (AE${ref.sheetRow}).`;
    annotations.push({
      rowKey,
      column: 'AG',
      cell: `AG${ref.sheetRow}`,
      kind: 'foreign_text_in_ag',
      excerpt,
      mechanism,
      action,
    });
  }

  // ── Правило (д): отложено на дату ПОЗЖЕ уже состоявшегося заключения ──
  // Случай владельца (канон п.110): «отложено до 01.09», а контракт заключён
  // 15.08. Дата в тексте НЕ становится датой закупки — она лишь сравнивается
  // со структурной Q. Даты чужих документов («распоряжение от 03.09»)
  // исключаются: именно их смешение с датой контракта портило учёт.
  if (factDay !== null) {
    for (const column of CLAIM_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      const m = POSTPONE_RE.exec(text);
      if (m === null || m.index === undefined) continue;
      const dateAt = text.indexOf(m[1], m.index);
      if (insideForeignDate(foreignDateSpans(text), dateAt < 0 ? m.index : dateAt)) continue;
      const dd = parseInt(m[1], 10);
      const mm = parseInt(m[2], 10);
      const yyyy = m[3] !== undefined ? parseInt(m[3], 10) : snapshotDate.getFullYear();
      if (dd < 1 || dd > 31 || mm < 1 || mm > 12) continue;
      const promiseDay = Date.UTC(yyyy, mm - 1, dd) / 86400000;
      if (promiseDay <= factDay) continue; // отложено на срок до заключения — не противоречие
      annotations.push({
        rowKey,
        column,
        cell: `${column}${ref.sheetRow}`,
        kind: 'promise_after_fact',
        excerpt: excerptAround(text, m.index, m.index + m[0].length),
        mechanism:
          `Комментарий откладывает закупку до ${ruDateOfDay(promiseDay)}, а контракт по строке заключён ` +
          `раньше — ${ruDateOfDay(factDay)} (Q${ref.sheetRow}). Текст пережил событие: читатель видит ` +
          `отложенную закупку там, где договор уже подписан.`,
        action:
          `Владельцу книги «${ref.book}»: обновите комментарий в ячейке ${column}${ref.sheetRow} — ` +
          `отложенный срок больше не действует, опишите состояние после заключения.`,
      });
    }
  }

  // ── Правило (е): текст отрицает заключение при заполненной дате ──
  // Ровно тот случай, из-за которого «не заключен» когда-то читался как
  // «подписан». Теперь текст не меняет статус: статус — дата Q, а
  // противоречие становится карточкой (п.27 + п.110).
  if (factDay !== null) {
    for (const column of CLAIM_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      for (const marker of DENIAL_MARKERS) {
        const m = marker.re.exec(text);
        if (m === null || m.index === undefined) continue;
        // «Аукцион не состоялся» — про процедуру, а не про договор: законное
        // основание закупки у единственного поставщика, не противоречие.
        // Отмена и расторжение противоречат дате заключения в любом случае.
        if (marker.procedureOk === true && denialAboutProcedure(text, m.index)) continue;
        annotations.push({
          rowKey,
          column,
          cell: `${column}${ref.sheetRow}`,
          kind: 'denial_when_signed',
          excerpt: excerptAround(text, m.index, m.index + m[0].length),
          mechanism:
            `Комментарий говорит «${marker.label}», а в Q${ref.sheetRow} стоит дата заключения ` +
            `${ruDateOfDay(factDay)}. Одно из двух неверно: либо дата проставлена ошибочно, ` +
            `либо текст устарел и вводит в заблуждение — свод и отчёт считают строку заключённой.`,
          action:
            `Владельцу книги «${ref.book}»: сверьте ячейки ${column}${ref.sheetRow} и Q${ref.sheetRow} — ` +
            `если контракт заключён, обновите комментарий; если нет — уберите дату заключения.`,
        });
        break; // одна карточка на ячейку (каскад п.53)
      }
    }
  }

  // ── Правило (ж): текст утверждает исполнение, а фактических денег нет ──
  if (!hasFactMoney(cells)) {
    for (const column of CLAIM_SCAN_COLUMNS) {
      const text = textOf(cells, column);
      if (text === null) continue;
      if (EXECUTION_FALSE_FRIENDS.test(text)) continue; // «качество исполнения» и родня
      for (const marker of EXECUTION_MARKERS) {
        const m = marker.re.exec(text);
        if (m === null || m.index === undefined) continue;
        annotations.push({
          rowKey,
          column,
          cell: `${column}${ref.sheetRow}`,
          kind: 'execution_claim_no_fact',
          excerpt: excerptAround(text, m.index, m.index + m[0].length),
          mechanism:
            `Комментарий утверждает «${marker.label}», но фактические суммы строки пусты ` +
            `(V${ref.sheetRow}–Y${ref.sheetRow}). Деньги либо не внесены в книгу — тогда свод и отчёт ` +
            `их не видят, либо комментарий опережает события.`,
          action:
            `Владельцу книги «${ref.book}»: если оплата прошла — внесите фактические суммы ` +
            `в V${ref.sheetRow}–Y${ref.sheetRow}; если ещё нет — поправьте комментарий ` +
            `в ячейке ${column}${ref.sheetRow}.`,
        });
        break;
      }
    }
  }

  // ── Правило (и): конкурентная строка без номера процедуры в AG ──
  // Поручение владельца 19.08: номер ЭА обязан быть проставлен — это ключ
  // связки с книгой мониторинга. Смотрим только конкурентные способы;
  // строка без способа или ЕП правилом не трогается.
  {
    const method = textOf(cells, 'L');
    // Границы слова: `\b` на кириллице не работает (см. PROCEDURE_SUBJECT_RE),
    // поэтому конец сокращения проверяется явным запретом кириллической буквы.
    const isCompetitive =
      method !== null && /^э(?:зк|ас|а|к)(?![а-яё])/iu.test(method.trim());
    if (isCompetitive) {
      const ag = textOf(cells, 'AG');
      const refs = ag === null ? [] : extractProcedureRefs(ag);
      if (refs.length === 0) {
        annotations.push({
          rowKey,
          column: 'AG',
          cell: `AG${ref.sheetRow}`,
          kind: 'missing_procedure_ref',
          excerpt: ag === null ? '' : excerptAround(ag, 0, Math.min(ag.length, 60)),
          mechanism:
            `Строка закупается конкурентным способом («${method}»), а в комментарии ` +
            `УЭР (AG${ref.sheetRow}) нет номера процедуры вида «ЭА152-26». Номер — ` +
            `единственный ключ, которым закупка связывается с книгой «Ежедневный ` +
            `мониторинг»: без него сверить начальную цену и цену торгов по этой ` +
            `строке невозможно.`,
          action:
            `Специалисту УЭР: проставить номер процедуры в ячейку AG${ref.sheetRow} ` +
            `в каноническом виде (например «ЭА152-26») — без пробелов и приписок.`,
        });
      }
    }
  }

  // ── Правило (к): ЕП-обоснование при конкурентном способе ──
  // Вопрос владельца 20.08.2026. Колонка M по шапке листа — «обоснование
  // выбора способа (в случае ЕП)»: у конкурентной строки ей положено быть
  // пустой. ЕП-текст в ней — противоречие способа и обоснования; свободные
  // комментарии без ЕП-маркеров правило не трогает (11 живых случаев —
  // заметки о смене способа, им место в U/AE, но это не логическая ошибка).
  {
    const method = textOf(cells, 'L');
    const isCompetitive =
      method !== null && /^э(?:зк|ас|а|к)(?![а-яё])/iu.test(method.trim());
    const m = textOf(cells, 'M');
    const mMeaningful = m !== null && !/^[XxХх\-—–.·\s]*$/u.test(m);
    if (isCompetitive && mMeaningful) {
      // Кириллические границы явные: `\b` на кириллице не работает.
      const epMark = /(?<![а-яё])еп(?![а-яё])|единствен|ст\.?\s*93/iu.exec(m);
      if (epMark !== null) {
        annotations.push({
          rowKey,
          column: 'M',
          cell: `M${ref.sheetRow}`,
          kind: 'ep_reason_on_competitive',
          excerpt: excerptAround(m, epMark.index, epMark.index + epMark[0].length),
          mechanism:
            `Способ строки — конкурентный («${method}»), а в колонке M ` +
            `(«обоснование выбора способа — в случае ЕП») стоит текст про ` +
            `единственного поставщика. Способ и обоснование спорят друг с ` +
            `другом: либо способ в L устарел после смены, либо обоснование ` +
            `попало не в ту колонку. Для малых закупок через электронную ` +
            `площадку (ч.12 ст.93) формально верен способ ЕП.`,
          action:
            `Владельцу книги: сверить способ в L${ref.sheetRow} с обоснованием ` +
            `в M${ref.sheetRow} — оставить то, что соответствует действительности; ` +
            `если закупка идёт по ч.12 ст.93, способ должен быть ЕП.`,
        });
      }
    }
  }

  return annotations;
}
