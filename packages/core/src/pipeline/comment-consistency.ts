/**
 * comment-consistency.ts — сигнал несогласованности комментария со структурой.
 *
 * ДИРЕКТИВА п.72(а) интервью 14.08.2026: сигнал по НЕАКТУАЛЬНЫМ комментариям —
 * текст описывает этапность, противоречащую факту (например «в стадии подачи
 * заявок» при заключённом контракте).
 *
 * ГРАНИЦА КАНОНА п.27: из свободного текста НЕЛЬЗЯ выводить статус закупки.
 * Здесь статус НЕ выводится: статус берётся ТОЛЬКО из структурной колонки Q
 * (дата заключения), а текст лишь проверяется на СОГЛАСОВАННОСТЬ с ним.
 * Результат — карточка «комментарий устарел — обновите» с адресом ячейки
 * (стандарт диагноста п.53: механизм / адрес / действие), а не изменение
 * какого-либо сигнала или статуса. Существующие signals.ts / validate.ts
 * эта подсистема не трогает и не переопределяет.
 *
 * Колонки (семантика по дампу comments-full.jsonl, снят с прода 14.08.2026):
 *   M = обоснование ЕП, U = статус/причина отклонения, AE = примечание,
 *   AF = комм. ГРБС, AG = комм. УЭР, AH = комм. УФБП,
 *   Q = дата заключения (структурная), N = план-дата.
 */

