/**
 * Разбор предмета закупки, устойчивый к опечаткам оператора.
 *
 * Зачем. Предмет и обоснование в книгах ГРБС набирают руками, и в них живут
 * настоящие опечатки: «кемонт» вместо «ремонт», «катриджей» вместо
 * «картриджей», «теплоснбжение», «медецинских», «опресовка», «едиственным».
 * Прежний разбор (`subject-classify.ts`) ищет точные образцы регулярными
 * выражениями: одна пропущенная буква — и закупка падает в «Другое». В отчёте
 * это выглядит как «мы не знаем, что покупали», хотя знаем прекрасно.
 *
 * Что делает этот модуль. Приводит слово к сравнимому виду (регистр, «ё», знаки
 * препинания), срезает русское окончание и сравнивает основу с образцом
 * категории, разрешая одну-две правки — вставку, удаление, замену или
 * перестановку соседних букв. Ровно те четыре ошибки, которые делает рука.
 *
 * Чего НЕ делает. Не правит книгу и не подменяет написанное: возвращается
 * разбор, а исходный текст остаётся как есть (канон п.27 — текст не источник
 * статусов; здесь он источник только для рубрикации, и рубрикация честно
 * сообщает, что сработала по опечатке).
 *
 * Почему свой код, а не библиотека. Разведка 18.08.2026: `natural` (13,5 МБ
 * распакованных, 14 зависимостей) тянет WordNet и классификаторы ради одного
 * PorterStemmerRu; `talisman` фонетики для русского не имеет вовсе (только
 * английская и французская ветки); `fuse.js` и `@leeoniya/ufuzzy` ищут по
 * списку, а не сопоставляют основу с образцом. Нужного здесь — сорок строк.
 *
 * Соседи: `subject-classify.ts` (точные образцы; сюда он проваливается, когда
 * не узнал предмет), `anomaly-detection.ts` (`normalizeSubject` — своё, более
 * грубое приведение для сравнения строк между собой).
 */

import type { SubjectCategory } from './subject-classify.js';

// ────────────────────────────────────────────────────────────
// 1. Приведение к сравнимому виду
// ────────────────────────────────────────────────────────────

/**
 * Регистр, «ё» → «е», всё нерусское и нецифровое — в пробел. «Ё» отдельной
 * буквой не считаем намеренно: в книгах её ставят через раз, и «ремонт
 * кровли» с «Ёмкость» из-за этого не спутать, а «еще/ещё» перестаёт
 * раздваивать одно и то же слово.
 */
export function normalizeRu(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^а-я0-9]+/g, ' ')
    .trim();
}

/** Слова длиной меньше этого в сравнении не участвуют — шум предлогов. */
const MIN_WORD_LENGTH = 4;

/** Разбивает предмет на слова, годные для сравнения. */
export function wordsOf(text: string): string[] {
  const normalized = normalizeRu(text);
  if (!normalized) return [];
  return normalized.split(' ').filter((w) => w.length >= MIN_WORD_LENGTH);
}

// ────────────────────────────────────────────────────────────
// 2. Основа слова
// ────────────────────────────────────────────────────────────

/**
 * Русские окончания в порядке убывания длины. Это не полный Портер, а срез
 * падежных и родовых хвостов — того, что мешает сравнить «картриджей» с
 * «картридж» и «медицинских» с «медицинск». Длинные хвосты идут первыми,
 * иначе «ами» съест «а» и оставит мусор.
 */
const ENDINGS: readonly string[] = [
  'иями', 'ями', 'ами', 'ими', 'ыми', 'ого', 'его', 'ому', 'ему', 'ыми',
  'ени', 'ией', 'ией', 'ов', 'ев', 'ей', 'ой', 'ый', 'ий', 'ая', 'яя',
  'ое', 'ее', 'ые', 'ие', 'ах', 'ях', 'ам', 'ям', 'ем', 'ом', 'их', 'ых',
  'ую', 'юю', 'ии', 'ии', 'ья', 'ье', 'ью', 'ть', 'ся',
  'а', 'я', 'е', 'и', 'й', 'о', 'у', 'ы', 'ь', 'ю',
];

/** Короче этого основу не режем — иначе от слова остаётся неразличимый огрызок. */
const MIN_STEM_LENGTH = 4;

/**
 * Срезает одно русское окончание. Одно, а не все подряд: повторный проход
 * стачивает «работы» до «раб» и роднит его с чем угодно.
 */
export function stemRu(word: string): string {
  for (const ending of ENDINGS) {
    if (word.length - ending.length >= MIN_STEM_LENGTH && word.endsWith(ending)) {
      return word.slice(0, word.length - ending.length);
    }
  }
  return word;
}

// ────────────────────────────────────────────────────────────
// 3. Расстояние правки
// ────────────────────────────────────────────────────────────

/**
 * Дамерау—Левенштейн (оптимальное выравнивание) с потолком: считает, за сколько
 * правок одно слово превращается в другое, где правка — вставка, удаление,
 * замена или перестановка двух соседних букв. Перестановка здесь не роскошь:
 * «карридж»/«кариджт» — обычный промах пальцев по соседним клавишам.
 *
 * Потолок обрывает счёт: за пределами разрешённого числа правок точное
 * расстояние не нужно, а перебор на сорока тысячах строк стоит времени.
 */
export function editDistance(a: string, b: string, maxDistance: number): number {
  if (a === b) return 0;
  if (Math.abs(a.length - b.length) > maxDistance) return maxDistance + 1;
  if (a.length === 0) return b.length;
  if (b.length === 0) return a.length;

  let previous: number[] = Array.from({ length: b.length + 1 }, (_, j) => j);
  let beforePrevious: number[] = [];

  for (let i = 1; i <= a.length; i++) {
    const current: number[] = new Array<number>(b.length + 1);
    current[0] = i;
    let rowBest = current[0];

    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      let value = Math.min(
        (current[j - 1] ?? 0) + 1,
        (previous[j] ?? 0) + 1,
        (previous[j - 1] ?? 0) + cost,
      );
      // Перестановка соседних букв — одна правка, а не две замены.
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) {
        value = Math.min(value, (beforePrevious[j - 2] ?? 0) + 1);
      }
      current[j] = value;
      if (value < rowBest) rowBest = value;
    }

    // Вся строка уже дороже потолка — дешевле не станет.
    if (rowBest > maxDistance) return maxDistance + 1;

    beforePrevious = previous;
    previous = current;
  }

  return previous[b.length] ?? maxDistance + 1;
}

/**
 * Сколько правок прощаем образцу такой длины. Короткому слову — ни одной сверх
 * одной: на основе из четырёх букв две правки роднят «связ» с «спец».
 */
export function allowedEdits(stemLength: number): number {
  if (stemLength <= 5) return 1;
  if (stemLength <= 8) return 1;
  return 2;
}

// ────────────────────────────────────────────────────────────
// 4. Образцы категорий
// ────────────────────────────────────────────────────────────

/**
 * Основы-образцы по категориям. Это НЕ дубль регулярных выражений из
 * `subject-classify.ts`: там куски слов для точного поиска по строке
 * («картридж»), здесь — основы целых слов для сравнения с расстоянием.
 * Порядок категорий задаёт старшинство при равном расстоянии.
 */
const CATEGORY_STEMS: readonly (readonly [SubjectCategory, readonly string[]])[] = [
  ['Коммуналка', ['коммунальн', 'электроэнерг', 'теплоснабжен', 'водоснабжен',
    'водоотведен', 'отоплен', 'опрессовк', 'теплов']],
  ['Оргтехника', ['компьютер', 'принтер', 'ноутбук', 'монитор', 'сканер', 'картридж',
    'тонер', 'многофункциональн']],
  ['Канцелярия', ['канцелярск', 'канцтовар', 'бумаг', 'скрепк', 'папк']],
  ['Медицина', ['медицинск', 'лекарствен', 'фармацевт', 'санитарн', 'дезинфекц']],
  ['Строительство', ['строительн', 'реконструкц', 'фасад', 'кровл', 'фундамент']],
  ['Проектирование', ['проектн', 'проектирован', 'смет', 'экспертиз', 'обследован']],
  ['Ремонт', ['ремонт', 'восстановлен', 'обслуживан']],
  ['Питание', ['питан', 'продукт', 'продовольствен', 'полуфабрикат']],
  ['Охрана', ['охран', 'видеонаблюден', 'пожарн', 'сигнализац', 'безопасност']],
  ['Клининг', ['уборк', 'клининг', 'моющ', 'дезинсекц']],
  ['Связь', ['телефон', 'интернет', 'хостинг', 'электросвяз']],
  ['Транспорт', ['автомобил', 'автобус', 'транспортн', 'грузов']],
  ['ГСМ', ['бензин', 'топлив', 'дизельн', 'моторн']],
  ['Мебель', ['мебел', 'стеллаж', 'кресл', 'шкаф']],
  ['Спецодежда', ['спецодежд', 'перчатк', 'обувь']],
  ['Образование', ['учебн', 'образовательн', 'методическ', 'литератур']],
];

// ────────────────────────────────────────────────────────────
// 5. Разбор
// ────────────────────────────────────────────────────────────

/** Как категория была узнана. */
export type FuzzyMatchKind =
  /** Основа совпала буква в букву. */
  | 'точно'
  /** Основа отличается на разрешённое число правок — похоже на опечатку. */
  | 'опечатка'
  /** Не узнали. */
  | 'нет';

export interface FuzzySubjectMatch {
  category: SubjectCategory;
  kind: FuzzyMatchKind;
  /** Слово книги, по которому узнали (как написано в источнике, приведённое). */
  word: string;
  /** Образец, на который оно похоже. */
  pattern: string;
  /** Сколько правок отделяет слово от образца. */
  distance: number;
  /**
   * Готовая фраза для карточки диагноста: механизм + что наблюдается.
   * Без упрёка: возможно, так и задумано.
   */
  note: string;
}

/** Не узнали — общий ответ, чтобы не плодить null-проверки у вызывающих. */
const NO_MATCH: FuzzySubjectMatch = {
  category: 'Другое',
  kind: 'нет',
  word: '',
  pattern: '',
  distance: Number.POSITIVE_INFINITY,
  note: 'Предмет не отнесён ни к одной группе: подходящего слова в тексте не нашлось.',
};

/**
 * Ищет категорию по основам слов, прощая опечатки. Возвращает лучшее
 * совпадение: сначала точное, при равенстве расстояний — категорию, стоящую
 * выше в списке образцов.
 */
export function matchSubjectFuzzy(subject: string): FuzzySubjectMatch {
  const words = wordsOf(subject);
  if (words.length === 0) return NO_MATCH;

  const stems = words.map(stemRu);
  let best: FuzzySubjectMatch | null = null;

  for (const [category, patterns] of CATEGORY_STEMS) {
    for (const pattern of patterns) {
      const budget = allowedEdits(pattern.length);
      for (let i = 0; i < stems.length; i++) {
        const stem = stems[i] ?? '';
        // Точное вхождение основы — самый дешёвый и самый надёжный случай.
        if (stem === pattern || stem.startsWith(pattern) || pattern.startsWith(stem)) {
          if (Math.abs(stem.length - pattern.length) <= budget) {
            return {
              category,
              kind: 'точно',
              word: words[i] ?? stem,
              pattern,
              distance: 0,
              note: `Отнесено к группе «${category}» по слову «${words[i] ?? stem}».`,
            };
          }
        }
        const distance = editDistance(stem, pattern, budget);
        if (distance <= budget && (best === null || distance < best.distance)) {
          const word = words[i] ?? stem;
          best = {
            category,
            kind: 'опечатка',
            word,
            pattern,
            distance,
            note:
              `Отнесено к группе «${category}»: слово «${word}» отличается от «${pattern}» ` +
              `на ${distance === 1 ? 'одну букву' : `${distance} буквы`} — похоже на опечатку. ` +
              'Текст в книге не менялся; проверьте строку, если группа определена неверно.',
          };
        }
      }
    }
  }

  return best ?? NO_MATCH;
}

/**
 * Похоже ли в тексте хоть одно слово на образец. Нужно там, где рубрикация ни
 * при чём, а важен сам факт слова: «едиственным поставщиком» в обосновании,
 * «расчитке» в описании работ.
 */
export function fuzzyIncludes(text: string, pattern: string): boolean {
  const budget = allowedEdits(pattern.length);
  for (const word of wordsOf(text)) {
    const stem = stemRu(word);
    if (stem === pattern || stem.startsWith(pattern)) return true;
    if (editDistance(stem, pattern, budget) <= budget) return true;
  }
  return false;
}
