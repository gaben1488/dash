/** Показатели, чья родословная установлена. */
export const PROVENANCE_KEYS: readonly string[] = Object.keys(METRIC_PROVENANCE);

/** Родословная показателя либо undefined, если она не установлена. */
export function metricProvenance(metricKey: string): MetricProvenance | undefined {
  return METRIC_PROVENANCE[metricKey];
}

/** Все показатели, пришедшие из указанного источника. */
export function metricsBySource(source: MetricSourceId): readonly string[] {
  return PROVENANCE_KEYS.filter((k) => METRIC_PROVENANCE[k].source === source);
}

/**
 * Показатели-сироты: наша инициатива без документального источника.
 * Их не запрещено показывать — их запрещено показывать МОЛЧА.
 */
export function orphanMetrics(): readonly string[] {
  return PROVENANCE_KEYS.filter((k) => METRIC_PROVENANCE[k].source === 'own');
}

/** Показатели, где наш счёт расходится со счётом источника. */
export function divergentMetrics(): readonly string[] {
  return PROVENANCE_KEYS.filter((k) => METRIC_PROVENANCE[k].match === 'divergent');
}
