/**
 * Канон МАРКЕРА ОТСУТСТВИЯ (решение владельца 14.08.2026, интервью п.62).
 *
 * В книгах ГРБС принято соглашение: «X», «x», «Х», «х» (латиница и кириллица,
 * любой регистр), а также тире — это ЯВНЫЙ маркер «здесь этого нет». Он
 * применяется НЕ только к колонке C (подвед — см. org-itself.ts), но и к
 * программе (D), подпрограмме (E), основанию выбора ЕП и другим текстовым
 * колонкам. Смысл — как у пустой ячейки, но проставленный осознанно.
 *
 * Следствия для всего кода:
 *  - фильтры и группировки не создают группу «X»;
 *  - сигналы не читают маркер как содержимое (например, «X» — не текст
 *    основания и не название программы);
 *  - интерфейс и выгрузки никогда не печатают «X» как значение — показывают
 *    «—» либо честное «не указано»;
 *  - счётчики «заполнено/не заполнено» относят маркер к «не заполнено».
 *
 * Единый предикат — здесь. Родственные узкие каноны (org-itself для C,
 * PROGRAM_EMPTY для D в activity-scope) мигрируют на него свипом приёмки —
 * до миграции их правила обязаны быть подмножеством этого.
 */

/** Одиночный маркер отсутствия: латинская/кириллическая X или тире. */
export const ABSENT_MARKER_RE = /^[XxХх\-—–]$/u;

/** true, если значение ячейки — маркер отсутствия или пустота. */
export function isAbsentCell(value: unknown): boolean {
  const s = String(value ?? '').trim();
  if (s === '') return true;
  return ABSENT_MARKER_RE.test(s);
}

/**
 * Значение ячейки для показа/выгрузки: маркер отсутствия и пустота — null,
 * иначе обрезанный текст. Печать «X» пользователю — дефект (интервью:
 * «Основание выбора ЕП: X» на проде).
 */
export function cellTextOrNull(value: unknown): string | null {
  return isAbsentCell(value) ? null : String(value).trim();
}
