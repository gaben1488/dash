const CANON_NORMALIZED: ReadonlyArray<{ id: DeviationReasonId; norm: string }> =
  DEVIATION_REASONS_V2.map((r) => ({ id: r.id, norm: normalizeCommentText(r.text) }));

/** Символьные биграммы строки (для похожести Дайса). */
function bigrams(s: string): Map<string, number> {
  const m = new Map<string, number>();
  for (let i = 0; i < s.length - 1; i++) {
    const b = s.slice(i, i + 2);
    m.set(b, (m.get(b) ?? 0) + 1);
  }
  return m;
}

/**
 * Похожесть Дайса по символьным биграммам (0..1). Аналог difflib-порога
 * таксономии 14.08: ловит опечатки и мелкие вариации канон-формулировки
 * («Отсутствие текущей потребности, срок будет скорректирован.» с точкой,
 * перестановка слов), но не смысловые пересказы — те закрывают стемы.
 */
function diceSimilarity(a: string, b: string): number {
  if (a.length < 2 || b.length < 2) return a === b ? 1 : 0;
  const ba = bigrams(a);
  const bb = bigrams(b);
  let inter = 0;
  let total = 0;
  for (const [g, c] of ba) {
    total += c;
    const cb = bb.get(g);
    if (cb !== undefined) inter += Math.min(c, cb);
  }
  for (const [, c] of bb) total += c;
  return (2 * inter) / total;
}

/**
 * Консервативный порог похожести для парафраза (аналог difflib 0.70 в
 * таксономии; Дайс на биграммах даёт чуть более высокие значения — порог
 * поднят до 0.75, чтобы не притягивать чужие тексты).
 */
const SIMILARITY_THRESHOLD = 0.75;

/**
 * Сопоставляет свободный текст ячейки со словарём причин 2.0.
 * exact — нормализованный текст дословно равен канон-формулировке;
 * paraphrase — сработало консервативное стем-правило (сочетание корней)
 * либо текст почти дословно повторяет канон (похожесть Дайса ≥ 0.75).
 * Плейсхолдеры листа («Х», «-», «.») и пустота → null.
 *
 * Это ГРУППИРОВКА причин для статистики и подсказок при вводе, не вывод
 * статуса строки из текста — канон п.27 (свободный текст исполнителей
 * машинно не интерпретируется как источник статусов) соблюдён.
 */
export function matchDeviationReason(text: unknown): DeviationReasonMatch | null {
  if (typeof text !== 'string') return null;
  const norm = normalizeCommentText(text);
  if (norm === '' || /^[xх\-—–.,\s]+$/.test(norm)) return null;
  for (const c of CANON_NORMALIZED) {
    if (norm === c.norm) return { id: c.id, match: 'exact' };
  }
  for (const rule of PARAPHRASE_RULES) {
    if (rule.test(norm)) return { id: rule.id, match: 'paraphrase' };
  }
  let bestId: DeviationReasonId | null = null;
  let bestScore = 0;
  for (const c of CANON_NORMALIZED) {
    const s = diceSimilarity(norm, c.norm);
    if (s > bestScore) {
      bestScore = s;
      bestId = c.id;
    }
  }
  if (bestId !== null && bestScore >= SIMILARITY_THRESHOLD) {
    return { id: bestId, match: 'paraphrase' };
  }
  return null;
}

