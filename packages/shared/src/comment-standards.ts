/**
 * Нормализация текста ячейки — та же, что в таксономии комментариев
 * (tax_classify, волна 14.08): lowercase, ё→е, кавычки и прочая пунктуация
 * кроме «.,№-» → пробел, схлоп пробелов, срез краевых точек.
 * ВАЖНО: JS-класс \w кириллицу НЕ покрывает — классы пишутся явно.
 */
export function normalizeCommentText(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/["'«»„“”]/g, ' ')
    .replace(/[^a-zа-я0-9_\s.,№-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^[\s.]+|[\s.]+$/g, '');
}

