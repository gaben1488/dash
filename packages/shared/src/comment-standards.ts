/**
 * Тип причины по провенансу (канон п.75а):
 *
 * - `'retro'` — объяснение УЖЕ СЛУЧИВШЕГОСЯ: причина описывает событие
 *   прошлого, из-за которого срок строки уже сдвинулся (история строки).
 *   Читателю нужна для летописи и статистики повторяемости; действий
 *   сегодня не требует — событие завершено.
 *
 * - `'live'` — живая организационная проблема ТЕКУЩЕГО этапа: причина
 *   описывает то, что мешает строке прямо сейчас, и требует внимания
 *   сегодня — у адресата есть конкретное действие, снимающее блок.
 */
export type DeviationReasonKind = 'retro' | 'live';

/**
 * Чьё действие снимает (или объясняет) причину:
 * - «управление» — сам ГРБС (планирование, потребность, документация);
 * - «бюджетный процесс» — финансовый контур (лимиты, ассигнования,
 *   кассовый план, регламентная проверка УФБП);
 * - «поставщик» — контрагент (согласование и присылка проекта контракта);
 * - «уполномоченный орган» — ведёт процедуры (размещение, изменения,
 *   повторы, взаимодействие с ФАС).
 */
