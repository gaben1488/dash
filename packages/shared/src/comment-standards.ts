/**
 * Номер электронного аукциона в нумерации уполномоченного органа: «ЭА152-26».
 * Формат наблюдён в эталонной разметке владельца (std-dop-infa.txt: ЭА152-26,
 * ЭА167-26, ЭА244-26, ЭА292-26, ЭА296-26, ЭА206-26, ЭА297-26, ЭА230-26,
 * ЭА295-26, ЭА43-26) и в живых ячейках AG книг ГРБС (пример: УД строка 14,
 * AG = «ЭА179-26», дамп comments-full.jsonl 14.08.2026).
 */
export const EA_PROCEDURE_RE = /ЭА\d+-\d+/gu;

/**
 * Номер извещения/закупки ЕИС — «№» и 8+ цифр. Пример из эталонной разметки
 * владельца (std-dop-infa.txt, строка УО / МАДОУ ДС № 1 «Ласточка»):
 * «№ 32615775240». Порог 8 цифр отсекает короткие номера распоряжений
 * («№ 112», «№ПП-3») — они номера документов, не процедур.
 */
export const EIS_NOTICE_RE = /№\s*\d{8,}/gu;

/**
 * Извлекает номера процедур из свободного текста: аукционные «ЭА152-26» и
 * ЕИС-«№ 32615775240». Возвращает найденные вхождения в порядке появления,
 * без дублей. Чистая справочная функция (провенанс-слой) — статусов из
 * текста не выводит (канон п.27).
 */
export function extractProcedureNumbers(text: unknown): string[] {
  if (typeof text !== 'string' || text.length === 0) return [];
  const found: string[] = [];
  for (const re of [EA_PROCEDURE_RE, EIS_NOTICE_RE]) {
    // Собственный lastIndex глобального регекса сбрасываем на каждый вызов.
    re.lastIndex = 0;
    for (const m of text.matchAll(re)) found.push(m[0].replace(/№\s*/u, '№ '));
  }
  return [...new Set(found)];
}
