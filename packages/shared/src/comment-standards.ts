  id: DeviationReasonId;
  /** Канон-формулировка — то, что просим писать в ячейку. */
  text: string;
  /** Провенанс совершённого ('retro') или живая проблема этапа ('live'). */
  kind: DeviationReasonKind;
  /** Суть одним предложением — что на самом деле произошло/происходит. */
