/**
 * grade-scale.ts — ОДНА шкала букв на продукт.
 *
 * Решение владельца п.137(9) от 21.08.2026, дословно: «как в композите
 * датасета везде» — то есть меньше значит лучше.
 *
 * Что чинится. На соседних экранах стояли две шкалы с одинаковыми буквами и
 * противоположной арифметикой: композит датасета считал ШТРАФ (0 — идеально,
 * 100 — беда, буква A у наименьшего числа), а грейд управления считал БАЛЛ
 * (100 — идеально, буква A у наибольшего). Читатель, увидевший «A» и «85» на
 * одной вкладке и «A» и «6» на другой, не мог понять, хорошо это или плохо, и
 * ни одна подпись ему не помогала.
 *
 * Что канонизируется. Направление числа: ВЕЗДЕ штраф, ноль — лучший исход.
 * Буква у обоих инструментов означает одно — A лучшая, дальше по алфавиту
 * хуже. Наборы букв остаются разными сознательно: композит датасета говорит
 * пятью буквами A–F (у него есть провал «F», в который управление по своим
 * порогам не попадает), оценка управления — четырьмя A–D. Разное число ступеней
 * не делает шкалы разными: одинаково направление и одинаков смысл буквы.
 *
 * Пороги обеих ступенчатых карт лежат здесь рядом намеренно: пока они жили в
 * двух файлах, ничто не мешало одному из них однажды перевернуться обратно.
 */

/** Направление числовой части шкалы. Одно на продукт: меньше — лучше. */
export const GRADE_SCALE_DIRECTION = 'penalty' as const;

/**
 * Как объяснить число читателю. Подпись обязана стоять рядом с цифрой везде,
 * где цифра показывается: «85» без этой подписи читается как балл.
 */
export const GRADE_SCORE_CAPTION = 'штрафных баллов из 100 (меньше — лучше)';

/** Композит датасета: пять ступеней. */
export type CompositeGrade = 'A' | 'B' | 'C' | 'D' | 'F';

/** Оценка управления: четыре ступени. */
export type ManagementGrade = 'A' | 'B' | 'C' | 'D';

/**
 * Пороги композита датасета — штраф 0-100, буква по возрастанию штрафа.
 * Значения историчны и не менялись: переносится карта, а не пороги. Край
 * порога исключающий (штраф ровно 10 — уже B), как считалось до переноса.
 */
export const COMPOSITE_GRADE_CUTS: readonly { below: number; grade: CompositeGrade }[] = [
  { below: 10, grade: 'A' },
  { below: 25, grade: 'B' },
  { below: 40, grade: 'C' },
  { below: 60, grade: 'D' },
];

/**
 * Пороги оценки управления — те же ступени, что были, но записанные штрафом.
 * Прежняя запись баллом читалась A ≥ 85, B ≥ 70, C ≥ 50; штраф — её зеркало
 * (100 − балл), поэтому ни одно управление буквы не меняет. Край порога здесь
 * включающий (штраф ровно 15 — ещё A): у балльной записи он был включающим, и
 * менять его переносом шкалы значило бы тихо понизить пограничные управления.
 *
 * Разный край у двух карт — наследство инструментов, а не вторая шкала: канон
 * этого файла про НАПРАВЛЕНИЕ числа и смысл буквы, а не про то, куда отнести
 * ровное совпадение с порогом.
 */
export const MANAGEMENT_GRADE_CUTS: readonly { upTo: number; grade: ManagementGrade }[] = [
  { upTo: 15, grade: 'A' },
  { upTo: 30, grade: 'B' },
  { upTo: 50, grade: 'C' },
];

/** Что означает буква — общий текст для обеих шкал. */
export const GRADE_MEANING: Readonly<Record<CompositeGrade, string>> = {
  A: 'Замечаний по существу нет.',
  B: 'Мелкие отклонения, разбираются в рабочем порядке.',
  C: 'Заметные отклонения, нужен разбор.',
  D: 'Отклонения серьёзные, нужен разбор с руководством.',
  F: 'Положение дел требует вмешательства.',
};

/** Буква композита по штрафу (0-100, меньше — лучше). */
export function compositeGradeOfPenalty(penalty: number): CompositeGrade {
  for (const cut of COMPOSITE_GRADE_CUTS) {
    if (penalty < cut.below) return cut.grade;
  }
  return 'F';
}

/** Буква оценки управления по штрафу (0-100, меньше — лучше). */
export function managementGradeOfPenalty(penalty: number): ManagementGrade {
  for (const cut of MANAGEMENT_GRADE_CUTS) {
    if (penalty <= cut.upTo) return cut.grade;
  }
  return 'D';
}
