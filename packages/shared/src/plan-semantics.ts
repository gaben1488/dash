/**
 * plan-semantics.ts — ЕДИНСТВЕННЫЙ дом ответа на вопрос «что означает „план“
 * в книге этого управления» (канон п.102 реестра интервью, 18.08.2026).
 *
 * ЗАЧЕМ. Столбцы H/I/J/K книг ГРБС называются одинаково — «план», — но несут
 * РАЗНЫЕ величины, и продукт складывал их молча. Слова владельца 18.08:
 * «то, что я называл лимитами — наши исполнители начали записывать туда НМЦК
 * с разбивкой из заявок»; далее — уточнения по каждому управлению. Пока
 * колонки не разведены («Закупки 2.0»: ЛБО отдельно, НМЦК отдельно), продукт
 * обязан хотя бы ПОДПИСЫВАТЬ величину, а не выдавать сумму разнородных чисел
 * за один показатель.
 *
 * ТРИ СЕМАНТИКИ K (п.102, замер 18.08 по дампам книг E:/aemr-dumps):
 *   1. `nmck` — начальная (максимальная) цена контракта, неизменная. Разность
 *      «план минус факт» здесь = снижение на торгах, то есть настоящая
 *      экономия.
 *   2. `nmck-minus-taken` — НМЦК, из которой задним числом вычтено изъятое
 *      перераспределением (практика культуры, УКСиМП: сэкономленное на торгах
 *      при переброске на другую потребность отминусовывают от НМЦК). Разность
 *      «план минус факт» здесь занижена на сумму изъятого.
 *   3. `redistributed-limit` — лимит, расписанный под закупку и снимаемый с
 *      неё при экономии. Дословно специалист УДТХ: «я не показываю НМЦК, а
 *      расписываю все наши лимиты под планируемые закупки, поэтому когда
 *      появляется экономия по какой-то закупке, я естественно снимаю лимиты
 *      с неё и перераспределяю их на следующую закупку». Разность «план минус
 *      факт» здесь близка к нулю по устройству учёта, а не по итогам торгов
 *      (отсюда витрина листа СВОД: «УДТХ — нулевая экономия при 93,11 %
 *      конкурентных процедур»).
 *   4. `unknown` — управление ответа ещё не дало (УИО, УФБП). Молчание — не
 *      повод назначить величину: подписываем честно «не подтверждено».
 *
 * ОБЩИЙ ЗНАМЕНАТЕЛЬ (2) и (3): экономия уходит ПРАВКОЙ ПЛАНА ЗАДНИМ ЧИСЛОМ —
 * исчезает из разности «план минус факт» и становится невидимой. Ловится по
 * журналу правок (ретро-снижения K у строк с фактом) — это отдельный фронт;
 * здесь только подпись величины.
 *
 * ОТКУДА ЗНАНИЕ. Карта заполнена РУКАМИ со слов владельца 18.08.2026 — это
 * показания людей, а не машинный вывод из ячеек. Свободный текст исполнителей
 * машинно не интерпретируется (канон п.27), и семантика столбца из него тоже
 * не выводится. Когда УИО и УФБП ответят — правится эта карта, а не вёрстка.
 *
 * ТОН (канон п.53). Подписи объясняют МЕХАНИЗМ и называют АДРЕС (какое
 * управление, какой столбец), без упрёка: заполняющие ведут книги так, как им
 * велит их бюджетный процесс, и претензия здесь не к ним, а к тому, что
 * продукт складывал разное.
 */

import { DEPARTMENT_REGISTRY, findDept, type LatinDeptId } from './department-registry.js';
import type { DepartmentId } from './types.js';

// ────────────────────────────────────────────────────────────
// 1. Тип семантики
// ────────────────────────────────────────────────────────────

/** Природа величины в плановых столбцах H/I/J/K книги управления. */
export type PlanSemanticsKind = 'nmck' | 'nmck-minus-taken' | 'redistributed-limit' | 'unknown';

/**
 * Насколько твёрдо знание о семантике:
 * `confirmed` — управление подтвердило прямо; `mostly` — подтверждено как
 * преобладающая практика («в основном»), отдельные строки могут быть иными;
 * `unknown` — ответа ещё нет.
 */
export type PlanSemanticsConfidence = 'confirmed' | 'mostly' | 'unknown';

/** Подпись плановой суммы одного управления. */
export interface PlanSemantics {
  kind: PlanSemanticsKind;
  /** Короткое имя величины — годится под числом и в чипе. */
  label: string;
  /** Механизм простыми словами: что именно записано в столбец и что даёт разность «план минус факт». */
  explain: string;
  confidence: PlanSemanticsConfidence;
  /** Происхождение знания — предъявляется читателю вместе с подписью. */
  source: string;
}

/** Происхождение всей карты: показания, а не вывод из данных. */
export const PLAN_SEMANTICS_SOURCE = 'слова владельца 18.08';

// ────────────────────────────────────────────────────────────
// 2. Базовые тексты по природе величины
// ────────────────────────────────────────────────────────────

interface KindText {
  label: string;
  explain: string;
}

/** Имя и механизм каждой из четырёх природ — один дом текста на весь продукт. */
export const PLAN_SEMANTICS_KIND_TEXT: Readonly<Record<PlanSemanticsKind, KindText>> = {
  nmck: {
    label: 'НМЦК по заявке',
    explain:
      'В плановые столбцы книги записана начальная (максимальная) цена контракта из заявки. '
      + 'Разность «план минус факт» по такой строке — снижение на торгах, то есть настоящая экономия.',
  },
  'nmck-minus-taken': {
    label: 'НМЦК за вычетом изъятого',
    explain:
      'В плановые столбцы книги записана начальная цена контракта, но при перераспределении '
      + 'сэкономленных денег на другую потребность её правят вниз задним числом на сумму изъятого. '
      + 'Часть экономии поэтому уже растворена в плане и в разности «план минус факт» не видна.',
  },
  'redistributed-limit': {
    label: 'распределяемый лимит',
    explain:
      'В плановые столбцы книги записана не начальная цена контракта, а лимит, расписанный под '
      + 'закупку: при появлении экономии лимит снимают с этой строки и переносят на следующую. '
      + 'Разность «план минус факт» здесь близка к нулю по устройству учёта, а не по итогам торгов.',
  },
  unknown: {
    label: 'величина не подтверждена',
    explain:
      'Чем заполнены плановые столбцы книги — начальной ценой контракта или лимитом — управление '
      + 'пока не сообщило. До ответа число показывается как есть и в сводные подписи входит с '
      + 'оговоркой.',
  },
} as const;

/** Приписка к механизму там, где практика подтверждена как преобладающая, а не сплошная. */
const MOSTLY_RIDER =
  ' Управление назвало эту практику преобладающей, поэтому отдельные строки могут держать прежнюю величину.';

function entry(kind: PlanSemanticsKind, confidence: PlanSemanticsConfidence): PlanSemantics {
  const text = PLAN_SEMANTICS_KIND_TEXT[kind];
  return {
    kind,
    label: text.label,
    explain: confidence === 'mostly' ? text.explain + MOSTLY_RIDER : text.explain,
    confidence,
    source: PLAN_SEMANTICS_SOURCE,
  };
}

// ────────────────────────────────────────────────────────────
// 3. Карта: управление → семантика плановой суммы
// ────────────────────────────────────────────────────────────

/**
 * Восемь управлений — восемь ответов (п.102, 18.08.2026):
 *   УАГЗО, УД — НМЦК, подтверждено стопроцентно;
 *   УКСиМП    — НМЦК подтверждена стопроцентно, но с нюансом культуры:
 *               при перераспределении её правят вниз на изъятое;
 *   УО, УЭР   — НМЦК «в основном»;
 *   УДТХ      — лимиты (дословные слова специалиста управления);
 *   УИО, УФБП — владелец ждёт ответа.
 * Страж-тест не даёт оставить управление без записи.
 */
export const PLAN_SEMANTICS_BY_DEPT: Readonly<Record<LatinDeptId, PlanSemantics>> = {
  uagzo: entry('nmck', 'confirmed'),
  ud: entry('nmck', 'confirmed'),
  uksimp: entry('nmck-minus-taken', 'confirmed'),
  uo: entry('nmck', 'mostly'),
  uer: entry('nmck', 'mostly'),
  udtx: entry('redistributed-limit', 'confirmed'),
  uio: entry('unknown', 'unknown'),
  ufbp: entry('unknown', 'unknown'),
} as const;

/** Запасной ответ для ключа, которого нет в реестре управлений. */
const UNKNOWN_SEMANTICS: PlanSemantics = entry('unknown', 'unknown');

/**
 * Семантика плана по любому виду ключа управления — кириллическому («УДТХ»)
 * или латинскому («udtx»). Незнакомый ключ не роняет экран: возвращается
 * честное «величина не подтверждена».
 */
export function planSemanticsFor(idOrLatin: string): PlanSemantics {
  const dept = findDept(idOrLatin);
  return dept ? PLAN_SEMANTICS_BY_DEPT[dept.latinId] : UNKNOWN_SEMANTICS;
}

// ────────────────────────────────────────────────────────────
// 4. Сводная подпись для периметра управлений
// ────────────────────────────────────────────────────────────

/** Порядок природ в подписях — от самой твёрдой величины к неизвестной. */
const KIND_ORDER: readonly PlanSemanticsKind[] = [
  'nmck',
  'nmck-minus-taken',
  'redistributed-limit',
  'unknown',
];

/** Управления периметра, сгруппированные по природе их плановой суммы. */
export interface PlanSemanticsGroup {
  kind: PlanSemanticsKind;
  label: string;
  /** Краткие имена управлений («УДТХ»), в порядке реестра. */
  depts: DepartmentId[];
}

/** Сводная подпись плановых чисел по набору управлений. */
export interface PlanSemanticsSummary {
  /** Природы, встреченные в периметре, в каноническом порядке. */
  kinds: PlanSemanticsKind[];
  groups: PlanSemanticsGroup[];
  /** В периметре больше одной ПОДТВЕРЖДЁННОЙ природы — числа разнородны. */
  mixed: boolean;
  /** В периметре есть управление, чья величина ещё не подтверждена. */
  hasUnknown: boolean;
  /** Короткая подпись под числом. */
  label: string;
  /** Развёрнутое объяснение для подсказки по наведению (абзацы через перенос строки). */
  explain: string;
  /** Предупреждение о смешении величин; null, если периметр однороден. */
  warning: string | null;
  /** Оговорка о неподтверждённых управлениях; null, если таких нет. */
  unknownNote: string | null;
  source: string;
}

/** Порядок реестра — чтобы перечисления управлений везде читались одинаково. */
const DEPT_ORDER = new Map<DepartmentId, number>(
  DEPARTMENT_REGISTRY.map((d, i) => [d.id, i]),
);

function listDepts(depts: readonly DepartmentId[]): string {
  return depts.join(', ');
}

/** Пустой периметр — отдельное состояние: подписывать нечего, врать нечем. */
const EMPTY_SUMMARY: PlanSemanticsSummary = {
  kinds: [],
  groups: [],
  mixed: false,
  hasUnknown: false,
  label: 'Управления не выбраны',
  explain:
    'Периметр пуст: подписывать нечего. Выберите управление — и подпись скажет, что означает его «план».',
  warning: null,
  unknownNote: null,
  source: PLAN_SEMANTICS_SOURCE,
};

/**
 * Сводная подпись для набора управлений (ключи в любой форме — кириллица или
 * латиница; повторы и незнакомые ключи безопасны).
 *
 * Главное, ради чего функция существует: если в периметре сошлись НМЦК одних
 * управлений и лимиты других, сводное плановое число складывает разные
 * величины — и обязано сказать об этом само, до того как читатель построит на
 * нём вывод (канон п.102, тон п.53).
 */
export function summarizePlanSemantics(depts: readonly string[]): PlanSemanticsSummary {
  const byKind = new Map<PlanSemanticsKind, Set<DepartmentId>>();
  for (const key of depts) {
    const dept = findDept(key);
    if (!dept) continue;
    const { kind } = PLAN_SEMANTICS_BY_DEPT[dept.latinId];
    let bucket = byKind.get(kind);
    if (!bucket) {
      bucket = new Set<DepartmentId>();
      byKind.set(kind, bucket);
    }
    bucket.add(dept.id);
  }
  if (byKind.size === 0) return EMPTY_SUMMARY;

  const groups: PlanSemanticsGroup[] = KIND_ORDER.filter((k) => byKind.has(k)).map((kind) => ({
    kind,
    label: PLAN_SEMANTICS_KIND_TEXT[kind].label,
    depts: [...byKind.get(kind)!].sort(
      (a, b) => (DEPT_ORDER.get(a) ?? 0) - (DEPT_ORDER.get(b) ?? 0),
    ),
  }));
  const kinds = groups.map((g) => g.kind);
  const known = kinds.filter((k) => k !== 'unknown');
  const mixed = known.length > 1;
  const hasUnknown = kinds.includes('unknown');

  const unknownNote = hasUnknown
    ? `Величина плановых столбцов ещё не подтверждена: ${listDepts(
        groups.find((g) => g.kind === 'unknown')!.depts,
      )}. Числа этих управлений в сумме участвуют, но чем они являются — начальной ценой или лимитом — пока неизвестно.`
    : null;

  const warning = mixed ? buildMixWarning(groups) : null;

  const label = mixed
    ? 'План собран из разных величин'
    : `План — ${PLAN_SEMANTICS_KIND_TEXT[kinds[0]].label}`;

  const lines: string[] = [];
  for (const g of groups) {
    lines.push(`${g.label} — ${listDepts(g.depts)}. ${PLAN_SEMANTICS_KIND_TEXT[g.kind].explain}`);
  }
  if (warning) lines.push(warning);
  if (unknownNote) lines.push(unknownNote);
  lines.push(`Происхождение подписи: ${PLAN_SEMANTICS_SOURCE}.`);

  return {
    kinds,
    groups,
    mixed,
    hasUnknown,
    label,
    explain: lines.join('\n'),
    warning,
    unknownNote,
    source: PLAN_SEMANTICS_SOURCE,
  };
}

/**
 * Текст предупреждения о смешении. Разводим два случая, потому что вред от них
 * разный: НМЦК рядом с лимитами — величины разной природы, а НМЦК рядом с
 * «НМЦК минус изъятое» — одна природа, но часть экономии уже вычтена из плана.
 */
function buildMixWarning(groups: readonly PlanSemanticsGroup[]): string {
  const limits = groups.find((g) => g.kind === 'redistributed-limit');
  const nmck = groups.find((g) => g.kind === 'nmck');
  const minusTaken = groups.find((g) => g.kind === 'nmck-minus-taken');

  if (limits) {
    const nmckDepts = [...(nmck?.depts ?? []), ...(minusTaken?.depts ?? [])].sort(
      (a, b) => (DEPT_ORDER.get(a) ?? 0) - (DEPT_ORDER.get(b) ?? 0),
    );
    return (
      'Сводный план складывает НМЦК одних управлений с лимитами других: '
      + `начальные цены контрактов (${listDepts(nmckDepts)}) и распределяемые лимиты `
      + `(${listDepts(limits.depts)}) лежат в одном числе. Разность «план минус факт» по такому `
      + 'периметру означает разное у разных строк, поэтому единой экономией её читать нельзя — '
      + 'смотрите управления по отдельности.'
    );
  }
  return (
    `Часть плана правится вниз задним числом: у ${listDepts(minusTaken?.depts ?? [])} изъятое `
    + 'перераспределением вычитается из начальной цены, у остальных управлений начальная цена '
    + 'остаётся неизменной. Сводная разность «план минус факт» на сумму изъятого занижена.'
  );
}
