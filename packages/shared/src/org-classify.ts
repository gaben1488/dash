import { isOrgItself } from './org-itself.js';

/**
 * org-classify.ts — КАНОНИЧЕСКИЙ классификатор типа организации в колонке C
 * по организационно-правовой форме (ОПФ), а НЕ по регексам-догадкам
 * (ср. `OrgStrip` `SELF_REF_PATTERNS`, эвристики-имена).
 *
 * Колонка C данных смешивает ТРИ семантики (спека §18, орг-канон):
 *   1. организации-заказчики (учреждения) — МКУ / МБОУ / МАДОУ / …;
 *   2. псевдо-записи — «Совместные закупки»;
 *   3. функции/сокращения аппарата ГРБС — «Х» / пусто / «Опека» / «Администрирование».
 *
 * Юр-факт (ст.6 БК РФ): ПБС (получатель бюджетных средств) = казённые учреждения
 * (МКУ) + органы. Бюджетные (МБОУ/МБДОУ/МБУ) и автономные (МАОУ/МАДОУ/МАУ) — НЕ ПБС
 * (получатели субсидий); по 44-ФЗ все они — заказчики.
 *
 * Реальные значения колонки C всех 8 ГРБС — docs/superpowers/qa/org_canon.md
 * (прогон снапшота 13.07.2026): 4 казённых МКУ, 60 бюджетных, 1 автономное,
 * 2 «Совместные закупки», 3 нераспознанных префиксом (ЦДТ/Опека/Администрирование).
 *
 * Переиспользует `isOrgItself` (единый предикат «само управление» оси C) — логику
 * пустой/самоссылочной колонки НЕ дублирует.
 */
export type OrgType =
  | 'apparatus'          // аппарат самого управления (Х/пусто/функции)
  | 'kazennoe'           // казённое учреждение (МКУ) — ПБС
  | 'byudzhetnoe'        // бюджетное (МБОУ/МБДОУ/МБУ/МБУК/МБУДО) — не ПБС, субсидия
  | 'avtonomnoe'         // автономное (МАОУ/МАДОУ/МАУ) — не ПБС
  | 'unitarnoe'          // МУП
  | 'joint_procurement'  // «Совместные закупки» — псевдо-организация
  | 'unknown';           // не в реестре ОПФ → сигнал качества

export interface OrgClassification {
  type: OrgType;
  /** ПБС по ст.6 БК: казённые + органы. Бюджетные/автономные — НЕ ПБС. */
  isPBS: boolean;
  /** человекочитаемый ярлык типа (для UI/БЗ) */
  label: string;
}

/**
 * Точные исключения — функции/сокращения аппарата в колонке C.
 * Источник: org_canon.md, раздел УО «НЕ КЛАССИФИЦИРОВАНО». Только «Опека» и
 * «Администрирование» — это функции аппарата (закупает само УО). «ЦДТ» из того
 * же раздела в этот список НЕ входит: это сокращение УЧРЕЖДЕНИЯ (Центр детского
 * творчества), а не функция → остаётся `unknown` (сигнал качества до уточнения ОПФ).
 */
const APPARATUS_FUNCTIONS = new Set(['опека', 'администрирование']);

/**
 * Классифицировать значение колонки C по ОПФ.
 * @param raw — сырое значение колонки C (строка/любое; нормализуется через String+trim).
 */
export function classifyOrg(raw: unknown): OrgClassification {
  const name = String(raw ?? '').trim();

  // Аппарат: пусто/самоссылка (isOrgItself) ИЛИ точная функция аппарата.
  if (isOrgItself(name) || APPARATUS_FUNCTIONS.has(name.toLowerCase())) {
    return { type: 'apparatus', isPBS: true, label: 'Аппарат' };
  }

  // Псевдо-организация «Совместные закупки» / «Совместная закупка».
  if (/^совместн/i.test(name)) {
    return { type: 'joint_procurement', isPBS: false, label: 'Совместные закупки' };
  }

  const upper = name.toUpperCase();

  // Порядок ОПФ-веток важен: сперва казённое (МК*), затем автономное (МА*),
  // затем бюджетное (МБ*). ВСЕ казённые формы — ПБС по ст.6 БК: МКУ (учреждение),
  // МКОУ (общеобразовательное), МКДОУ (дошкольное). НЕ путать с бюджетными МБ*.
  if (/^(МКУ|МКОУ|МКДОУ|МУНИЦИПАЛЬНОЕ КАЗ[ЁЕ]ННОЕ)/.test(upper)) {
    return { type: 'kazennoe', isPBS: true, label: 'Казённое учреждение (ПБС)' };
  }
  if (/^(МАОУ|МАДОУ|МАУ|МУНИЦИПАЛЬНОЕ АВТОНОМНОЕ)/.test(upper)) {
    return { type: 'avtonomnoe', isPBS: false, label: 'Автономное учреждение' };
  }
  if (/^(МБОУ|МБДОУ|МБУДО|МБУК|МБУ|МУНИЦИПАЛЬНОЕ БЮДЖЕТНОЕ)/.test(upper)) {
    return { type: 'byudzhetnoe', isPBS: false, label: 'Бюджетное учреждение' };
  }
  if (/^МУП/.test(upper)) {
    return { type: 'unitarnoe', isPBS: false, label: 'Унитарное предприятие' };
  }

  return { type: 'unknown', isPBS: false, label: name || '(не указано)' };
}
