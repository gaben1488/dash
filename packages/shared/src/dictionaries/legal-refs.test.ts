/**
 * Страж справочника правовых ссылок.
 *
 * DEADCODE_DISPOSITION_2026-06-05 §W-4: у значений `legal-refs.ts` нет
 * потребителей в коде — живёт только тип `LegalRefId`. Инвентарь долга
 * 18.08.2026 отнёс судьбу словаря к решению владельца (вонзить или снять),
 * поэтому файл оставлен. Пока он ждёт решения, за ним нужен присмотр: без
 * единого потребителя справочник расходится с кластерами обоснования ЕП
 * молча — ссылка в кластере остаётся, а записи под неё уже нет, и заметить
 * это будет некому.
 *
 * Тест закрывает две дыры: связность (каждая ссылка кластера имеет запись)
 * и характеризацию разбора (нынешнее поведение `parseLegalRef` записано до
 * того, как его начнут вонзать, — чтобы «вонзание» не переписало разбор
 * втихую).
 */
import { describe, expect, it } from 'vitest';
import { EP_REASON_DICT } from './ep-reason-clusters.js';
import { LEGAL_REFS, getLegalRef, isFederalRef, parseLegalRef } from './legal-refs.js';

describe('legal-refs — связность со словарём обоснований ЕП', () => {
  it('каждая правовая ссылка кластера ЕП имеет запись в справочнике', () => {
    const missing: string[] = [];

    for (const entry of Object.values(EP_REASON_DICT)) {
      for (const ref of entry.legal_refs) {
        if (!Object.hasOwn(LEGAL_REFS, ref)) missing.push(`${entry.cluster} → ${ref}`);
      }
    }

    expect(missing).toEqual([]);
  });

  it('запись справочника отвечает своим же идентификатором', () => {
    for (const [id, ref] of Object.entries(LEGAL_REFS)) {
      expect(ref.id).toBe(id);
      expect(getLegalRef(ref.id)).toBe(ref);
    }
  });

  it('федеральными считаются только записи федеральных типов', () => {
    for (const ref of Object.values(LEGAL_REFS)) {
      const expected = ref.law_type === 'federal' || ref.law_type === 'federal_special';
      expect(isFederalRef(ref.id)).toBe(expected);
    }
  });
});

describe('parseLegalRef — характеризация нынешнего разбора', () => {
  it('разбирает пункт 44-ФЗ вместе с упоминанием монополии', () => {
    expect(parseLegalRef('Монополист согласно п. 8 ч. 1 ст. 93 44-ФЗ + ФЗ-147'))
      .toEqual(['44_FZ_93_1_8', '147_FZ']);
  });

  it('краткая форма «пп. 5, п. 1» читается как распоряжение АЕМР № 112', () => {
    expect(parseLegalRef('пп. 5, п. 1')).toEqual(['AEMR_112', 'AEMR_112_5']);
  });

  it('поручение губернатора читается как ссылка', () => {
    expect(parseLegalRef('Закупка по поручению Губернатора'))
      .toEqual(['GUBERNATOR_CAMCHATKA']);
  });

  /**
   * Запись изъяна, а не одобрение: вторая ветка того же условия написана как
   * `местн[ыо](?:ого|ый)`, то есть требует «местноого» либо «местноый», и на
   * живом написании «местного производителя» промахивается. Пока справочник
   * ждёт решения владельца, изъян зафиксирован тестом — вонзать разбор,
   * не починив ветку, значит внести молчаливый промах в живой путь.
   */
  it('«местного производителя» мимо разбора — ветка написана с ошибкой', () => {
    expect(parseLegalRef('поддержка местного производителя')).toEqual([]);
  });

  it('несуществующий пункт 44-ФЗ не превращается в ссылку', () => {
    expect(parseLegalRef('п. 77 ч. 1 ст. 93')).toEqual([]);
  });

  it('текст без правовых признаков даёт пустой список', () => {
    expect(parseLegalRef('нецелесообразность проведения аукциона')).toEqual([]);
  });
});
