// extractForecastDate УДАЛЕНА 14.08.2026 — канон п.27 интервью
// (docs/superpowers/audits/2026-08-14-interview-register.md, пп.27/31/40/41):
// свободный текст исполнителей машинно НЕ интерпретируется НИГДЕ. Живой урон:
// «ожидается 30.08.2027» бралось из «лицензия до 30.08.2027» (УАГЗО, КАМИН),
// «ожидается 17.07.2026» — из «17.07 будет РАСТОРГНУТ МК» (расторжение
// прочитано как ожидание заключения). Комментарий показывается как есть —
// дату читатель видит в тексте пояснения своими глазами.
// canonicalizeDeviation ниже остаётся: это ГРУППИРОВКА причин для сводной
// статистики отчёта (счёт по кластерам), а не вывод статуса/даты по строке —
// её результат никогда не подменяет содержимое комментария.

/** Результат нормализации причины отклонения. */
export type DeviationResult =
  | { cluster: DeviationCluster; matched: string }
  | { cluster: 'EMPTY' }
  | { cluster: 'UNMAPPED' };

/**
 * Живая формулировка → кластер причины. Пустые маркеры листа («Х», прочерк)
 * означают «причина не указана», а не «причины нет»: это разные вещи, и
 * продукт обязан их различать.
 */
export function canonicalizeDeviation(raw: unknown): DeviationResult {
  if (raw === null || raw === undefined || raw === '') return { cluster: 'EMPTY' };
  if (typeof raw !== 'string') return { cluster: 'UNMAPPED' };
  const cleaned = raw.trim();
  if (/^[xхXХ—\-–]$/.test(cleaned)) return { cluster: 'EMPTY' };
  const normalized = cleaned.toLowerCase().replace(/\s+/g, ' ');

  for (const cluster of DEVIATION_CLUSTERS) {
    for (const re of DEVIATION_DICT[cluster].regex) {
      if (re.test(normalized)) return { cluster, matched: re.source };
    }
  }
  return { cluster: 'UNMAPPED' };
}
