/**
 * Является ли тип деятельности «программным».
 *
 * Потребителей сегодня нет (проверено 18.08.2026 по всем пакетам): срезы
 * считают через ACTIVITY_SCOPES. Предикат оставлен намеренно — это запись
 * канона п.30 одной строкой, и удалять его значит терять место, где правило
 * «программное — только ПМ» выражено кодом, а не комментарием.
 *
 * Канон п.30: ТОЛЬКО ПМ. Легаси-значение current_program — это ТД
 * (строка текущей деятельности с заполненной графой программы), считать
 * её программной значит воскресить упразднённый срез «ТД-ПМ».
 */
export function isProgramActivity(type: ActivityType): boolean {
  return type === 'program';
}
