/**
 * Единица порога. Существует затем, чтобы «25» экономии и «25» тысяч рублей
 * нельзя было сравнить по недосмотру: денежные пороги района ведутся в тысячах
 * (канон `report-map.ts`), а закон говорит о рублях — на этой подмене продукт
 * уже однажды потерял все проверки лимитов (БАГ #1 охоты 2026-08-08).
 */
export type ThresholdUnit =
  /** Процент, 0..100 — как его видит читатель на экране. */
  | 'percent'
  /** Доля 0..1 — как её пишет закон и как считает ядро. */
  | 'ratio'
  /** Штуки: замечания, процедуры, строки. */
  | 'count'
  /** Тысячи рублей — единица денежных колонок книг ГРБС. */
  | 'thousandRub'
  /** Записей журнала правок на одну строку книги. */
  | 'editsPerRow';

/** Человеческие имена единиц — для подписи под числом. */
export const THRESHOLD_UNIT_LABELS: Readonly<Record<ThresholdUnit, string>> = {
  percent: '%',
  ratio: 'доля',
  count: 'шт.',
  thousandRub: 'тыс. руб.',
  editsPerRow: 'правок на строку',
};

/** Область, за которую порог отвечает. Группировка для экрана и разговора. */
export type ThresholdDomain =
  | 'execution'
  | 'trust'
  | 'recon'
  | 'economy'
  | 'issues'
  | 'competition'
  | 'discipline'
  | 'observability'
  | 'law';

export interface ThresholdEntry {
  /** Человеческое имя порога — то, как он называется в разговоре. */
  readonly label: string;
  /** Значение. Берётся из существующей константы там, где она есть. */
  readonly value: number;
  readonly unit: ThresholdUnit;
  readonly domain: ThresholdDomain;
  /** Смысл одной фразой: что происходит при переходе через порог. */
  readonly means: string;
  /** Откуда порог родом: норма закона, канон документов либо наше решение. */
  readonly source: MetricSourceId;
  /** Точный адрес источника — статья закона, ячейка листа, пункт канона. */
  readonly sourceRef?: string;
  /**
   * Обоснование либо оговорка. Для порогов с источником `own` обязательно:
   * наше решение имеет право на жизнь, но не имеет права молчать.
   */
  readonly note?: string;
}

