/** Все известные имена порогов. */
export const THRESHOLD_IDS: readonly string[] = Object.keys(THRESHOLD_REGISTRY);

/** Запись порога либо undefined, если такого имени нет. */
export function threshold(id: string): ThresholdEntry | undefined {
  return THRESHOLD_REGISTRY[id];
}

/**
 * Значение порога по имени. Единственный способ добраться до числа из
 * разметки: литерал в тернарнике — это ровно та болезнь, ради которой файл
 * заведён.
 */
export function thresholdValue(id: string): number {
  const entry = THRESHOLD_REGISTRY[id];
  if (!entry) throw new Error(`Неизвестный порог: ${id}`);
  return entry.value;
}

/** Пороги одной области — для страницы объяснений и для разговора. */
export function thresholdsByDomain(domain: ThresholdDomain): readonly string[] {
  return THRESHOLD_IDS.filter((id) => THRESHOLD_REGISTRY[id]!.domain === domain);
}

/** Пороги одного происхождения. */
export function thresholdsBySource(source: MetricSourceId): readonly string[] {
  return THRESHOLD_IDS.filter((id) => THRESHOLD_REGISTRY[id]!.source === source);
}

/**
 * Пороги без документальной родословной — наше решение. Их не запрещено
 * применять; их запрещено применять молча, поэтому каждый обязан нести `note`.
 */
export function ownThresholds(): readonly string[] {
  return thresholdsBySource('own');
}

/**
 * Число с единицей, как его читает человек: «25 %», «600 тыс. руб.»,
 * «2 правок на строку». Доля печатается процентом — читателю привычнее.
 */
export function formatThreshold(id: string): string {
  const entry = THRESHOLD_REGISTRY[id];
  if (!entry) return '—';
  if (entry.unit === 'ratio') return `${(entry.value * 100).toFixed(0)} %`;
  return `${entry.value} ${THRESHOLD_UNIT_LABELS[entry.unit]}`;
}
