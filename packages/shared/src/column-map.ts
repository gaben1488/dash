/** Number of header rows in department sheets (шапка: 3 строки) */
export const DEPT_HEADER_ROWS = 3;

/**
 * Значения листов → строки-атомы книг ГРБС без шапки. Ключи входа — имена
 * листов; остаются только книги ГРБС (findDept знает имя), не-ГРБС листы
 * (СВОД, служебные) отсеиваются, шапка в DEPT_HEADER_ROWS строк срезается.
 * Ключи результата — те же кириллические короткие имена, что во входе.
 *
 * Единственный дом этой сборки: роут /api/report кормит сюда живой кэш,
 * пайплайн — прочитанные листы для снимка. Копии запрещены — при расхождении
 * отчёт «сегодня» и отчёт «из снимка» считались бы по разным строкам.
 */
export function collectRowsByDept(
  sheetValues: Record<string, unknown[][]>,
): Record<string, unknown[][]> {
  const rowsByDept: Record<string, unknown[][]> = {};
  for (const [name, values] of Object.entries(sheetValues)) {
    if (!findDept(name)) continue;
    if (values.length <= DEPT_HEADER_ROWS) continue;
    rowsByDept[name] = values.slice(DEPT_HEADER_ROWS);
  }
  return rowsByDept;
}

/**
 * Column letter → 0-based index mapping (A=0..AH=33).
 * Правая граница = последняя заполненная колонка живой шапки (AH). Это же
 * множество — белый список записи в routes/rows.ts, поэтому без AG/AH
 * комментарии УЭР/УФБП были недоступны продукту и на чтение, и на запись.
 */
export const COL_LETTER_INDEX: Readonly<Record<string, number>> = {
  A:0, B:1, C:2, D:3, E:4, F:5, G:6, H:7, I:8, J:9, K:10,
  L:11, M:12, N:13, O:14, P:15, Q:16, R:17, S:18, T:19, U:20,
  V:21, W:22, X:23, Y:24, Z:25, AA:26, AB:27, AC:28, AD:29, AE:30, AF:31,
  AG:32, AH:33,
};

/** Cached entries array for buildCellDict hot path */
const COL_ENTRIES = Object.entries(COL_LETTER_INDEX);

/** Convert a raw row array to a column-letter keyed cell dictionary. */
export function buildCellDict(row: unknown[]): Record<string, unknown> {
  const cells: Record<string, unknown> = {};
  for (const [col, i] of COL_ENTRIES) {
    cells[col] = row[i] ?? null;
  }
  return cells;
}

/**
 * Служебная строка листа — итог, раздел или заголовок: «Итого по разделу»,
 * «ВСЕГО», «Раздел 2», «Наименование мероприятия…» (текст шапки).
 *
 * ПОЧЕМУ якорь начала строки и целое слово, а не подстрока. Прежний вариант
 * (`includes` по ['итого','всего','раздел','блок','наименование']) выбрасывал
 * настоящие закупки, у которых служебное слово сидит ВНУТРИ названия: на
 * восьми живых книгах ГРБС (3 854 строки, снято 2026-07-29) так терялось
 * 42 закупки на 70 619,81 тыс. руб. — «Капитальный ремонт пищеблока» 46 672,72,
 * «Капитальный ремонт помещений спортзала, мастерской, мед.блока» 11 807,69,
 * «реконструкция системы вентиляции пищеблока» 2 827,82, «Системные блоки» 244,00,
 * «Создание (реконструкция, ремонт) мест (площадок) накопления (раздельного…)»
 * 3 853,00, «доски разделочные» и прочие. Ни одной служебной строки при этом
 * подстрочный режим не поймал: в живых книгах служебных строк в предмете (G)
 * и подведе (C) нет вовсе, а шапку срезает DEPT_HEADER_ROWS.
 *
 * «блок» из списка убрано насовсем: служебных строк с этого слова не
 * начинается, зато «Блок питания» / «Системный блок» — обычные закупки.
 * Отрицательный просмотр вперёд (?![а-яё]) отделяет слово от однокоренных:
 * «Разделочные доски» и «Итоговый отчёт» остаются закупками.
 */
const META_ROW_PREFIX = /^(итого|всего|раздел|наименование)(?![а-яё])/;
export function isMetaRow(text: string): boolean {
  if (!text) return false;
  return META_ROW_PREFIX.test(text.trim().toLowerCase());
}
