import { SIGNAL_CLASS_NAMES } from './product-dictionary.js';

// ────────────────────────────────────────────────────────────
// 1. Решение органа: графа «Статус» (AD)
// ────────────────────────────────────────────────────────────

/**
 * Что записано в графе «Статус» (AD):
 *  - `approved`     — «да»: экономия признана;
 *  - `declined`     — «нет»: орган решил, что экономией это не является;
 *  - `undetermined` — решения нет (пусто, «X», «·», прочерк, любой иной текст).
 *
 * «Нет» — это РЕШЕНИЕ, а не пробел: строка с ним из явления выпадает.
 */
export type EconomyFlagState = 'approved' | 'declined' | 'undetermined';

/** Канон значений графы «Статус»: латинские написания живут в книгах наравне. */
const APPROVED_WORDS = new Set(['да', 'yes']);
const DECLINED_WORDS = new Set(['нет', 'no']);

/** Значение графы «Статус» (AD) → решение органа. */
export function economyFlagState(adCell: unknown): EconomyFlagState {
  if (adCell === null || adCell === undefined) return 'undetermined';
  const text = String(adCell).trim().toLowerCase();
  if (APPROVED_WORDS.has(text)) return 'approved';
  if (DECLINED_WORDS.has(text)) return 'declined';
  return 'undetermined';
}

// ────────────────────────────────────────────────────────────
// 2. Явление «Экономия без отметки»
// ────────────────────────────────────────────────────────────

/**
 * Род строки. Явление считается по обоим родам (решение владельца 20.08:
 * «ЕП включённо»), но род называется вслух: у единственного поставщика
 * экономии быть не должно вовсе (канон п.98м/п.102 — план по ЕП это сумма
 * договора, обязанная равняться потраченной), поэтому там расхождение план/факт
 * само по себе повод для другой проверки, «По ЕП факт не равен плану».
 */
export type EconomyKind = 'ep' | 'competitive';

/**
 * Порог машинного шума в тысячах рублей: 0,01 тыс = 10 рублей.
 *
 * План хранится в двух знаках, факт — в пяти; разность в копейку это остаток
 * двоичной арифметики, а не экономия (тот же урок, что у допуска 0,5 % в
 * проверке «Факт превышает план»). Порог намеренно шумовой, а не значимостный:
 * прежнее правило листа требовало целой тысячи рублей и тем прятало настоящие
 * сотни, из-за чего его счёт не сходился ни с одним другим.
 */
export const ECONOMY_NOISE_THOUSAND = 0.01;

/** Числа строки, по которым считается явление. */
export interface EconomyFlagInput {
  /** План итого (K) в единицах книги — тысячах рублей. */
  planTotal: number | null;
  /** Факт итого (Y либо сумма V+W+X) в тех же единицах. */
  factTotal: number | null;
  /** Сырое значение графы «Статус» (AD). */
  adCell: unknown;
  /** Способ закупки — единственный поставщик? */
  isEp: boolean;
}

/** Разбор строки по канону: что с числами, что с решением, к какому роду. */
export interface EconomyFlagVerdict {
  /** Строка подпадает под явление «Экономия без отметки». */
  matches: boolean;
  /** Решение органа по графе «Статус». */
  state: EconomyFlagState;
  /** Род строки — называется вслух и в карточке, и в срезе. */
  kind: EconomyKind;
  /** Экономия план − факт в тысячах рублей; 0, когда её нет. */
  economy: number;
  /** Доля экономии от плана в процентах; 0, когда плана нет. */
  sharePct: number;
}

/** Число или пусто: NaN и бесконечности к числам не относятся. */
function finite(value: number | null): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

/**
 * ОПРЕДЕЛЕНИЕ ЯВЛЕНИЯ (единственное в продукте).
 *
 * Строка подпадает под «Экономию без отметки», когда одновременно:
 *   • план итого заполнен и больше нуля;
 *   • факт итого заполнен и больше нуля (закупка состоялась);
 *   • факт меньше плана сверх машинного шума — экономия видна по числам;
 *   • графа «Статус» (AD) не несёт ни «да», ни «нет» — решения нет.
 * Род строки (единственный поставщик или конкурентный способ) на попадание не
 * влияет, но возвращается: он меняет слова карточки, а не состав класса.
 */
export function economyFlagVerdict(input: EconomyFlagInput): EconomyFlagVerdict {
  const state = economyFlagState(input.adCell);
  const kind: EconomyKind = input.isEp ? 'ep' : 'competitive';
  const plan = finite(input.planTotal);
  const fact = finite(input.factTotal);

  if (plan === null || plan <= 0 || fact === null || fact <= 0) {
    return { matches: false, state, kind, economy: 0, sharePct: 0 };
  }

  const economy = plan - fact;
  if (economy < ECONOMY_NOISE_THOUSAND) {
    return { matches: false, state, kind, economy: 0, sharePct: 0 };
  }

  return {
    matches: state === 'undetermined',
    state,
    kind,
    economy,
    sharePct: (economy / plan) * 100,
  };
}

/** Короткий вопрос к строке: подпадает ли она под явление. */
export function isEconomyFlagUndetermined(input: EconomyFlagInput): boolean {
  return economyFlagVerdict(input).matches;
}

