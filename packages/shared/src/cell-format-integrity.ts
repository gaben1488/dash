/**
 * Сбитый формат ячейки: значение верное, а человек видит не то.
 *
 * Разбор жалобы 19.08.2026 («сотрудница вносила дату, изменения не
 * сохранились») вывел на соседний случай в той же книге: в плановой дате
 * строки лежало число 46172. Это внутренний код даты — так таблица хранит
 * пятнадцатое июня 2026 года, и наш разбор дат его понимает (parse-sheet-date
 * переводит код в сутки). То есть расчёты верны, свод не страдает.
 *
 * Страдает человек. Оператор открывает книгу и видит в графе даты голое
 * число — ни срока, ни смысла. Сортировка по дате работает, а глаз не читает;
 * при переносе в отчёт число уходит как число. Причина всегда одна: ячейке
 * задан числовой формат вместо формата даты — обычно после копирования из
 * другого места или вставки «только значений».
 *
 * Поэтому проверка смотрит не на смысл значения, а на ЕГО ВИД: что показано
 * в ячейке. Если в графе даты показано число, а не дата, — формат сбит.
 *
 * Границы диапазона выбраны от смысла, а не на глаз: код 44 927 — первое
 * января 2023 года, код 48 578 — тридцатое декабря 2032 года. Всё, что
 * выходит за эти годы, для книги закупок бессмысленно и скорее является
 * суммой, попавшей не в ту графу (этот случай ловит другая проверка).
 */

/** Код первого января 2023 года — раньше книги закупок не начинаются. */
export const DATE_SERIAL_MIN = 44927;
/** Код тридцать первого декабря 2032 года — дальше горизонта планирования нет. */
export const DATE_SERIAL_MAX = 48578;

/** Смещение внутреннего кода таблицы к обычному счёту суток. */
const SERIAL_EPOCH_OFFSET = 25569;
const MS_PER_DAY = 86400000;

export interface DateFormatFinding {
  /** Что показано в ячейке. */
  shown: string;
  /** Какая это дата на самом деле, «дд.мм.гггг». */
  meansDate: string;
  /** Объяснение механизма для карточки (канон п.53). */
  mechanism: string;
  /** Что делать оператору. */
  action: string;
}

/** Дата из внутреннего кода таблицы, «дд.мм.гггг». */
function dateOfSerial(serial: number): string {
  const ms = (serial - SERIAL_EPOCH_OFFSET) * MS_PER_DAY;
  const d = new Date(ms);
  const dd = String(d.getUTCDate()).padStart(2, '0');
  const mm = String(d.getUTCMonth() + 1).padStart(2, '0');
  return `${dd}.${mm}.${d.getUTCFullYear()}`;
}

/**
 * Показано ли в ячейке даты голое число вместо даты.
 *
 * @param shown — значение, как оно ВЫГЛЯДИТ в книге (formattedValue), а не
 *   как хранится: именно вид отличает сбитый формат от нормальной ячейки.
 * @param columnLetter — буква графы, нужна только для текста карточки.
 */
export function detectDateShownAsNumber(
  shown: unknown,
  columnLetter: string,
  sheetRow: number,
): DateFormatFinding | null {
  const s = String(shown ?? '').trim();
  if (s === '') return null;
  // Дата, показанная как дата, — с точками или дефисами: не наш случай.
  if (/[.\-/]/u.test(s)) return null;
  // Пробелы внутри числа — признак разрядов суммы, а не кода даты.
  if (/\s/u.test(s)) return null;
  if (!/^\d{5}(?:[,.]\d+)?$/u.test(s)) return null;

  const serial = Number(s.replace(',', '.'));
  if (!Number.isFinite(serial)) return null;
  if (serial < DATE_SERIAL_MIN || serial > DATE_SERIAL_MAX) return null;

  const cell = `${columnLetter}${sheetRow}`;
  const meansDate = dateOfSerial(Math.trunc(serial));
  return {
    shown: s,
    meansDate,
    mechanism:
      `В ячейке ${cell} показано число ${s}, хотя это графа даты. Так таблица ` +
      `хранит ${meansDate}: значение верное, расчёты его понимают, но человек ` +
      `видит внутренний код вместо срока. Причина — ячейке задан числовой ` +
      `формат вместо формата даты, обычно после вставки значений из другого места.`,
    action:
      `Владельцу книги: выделить ячейку ${cell} и задать ей формат даты ` +
      `(Формат → Числа → Дата). Значение менять не нужно — оно правильное, ` +
      `после смены формата покажется как ${meansDate}.`,
  };
}

/** Проверка строки: обе рукописные графы дат — плановая и фактическая. */
export function detectDateFormatIssues(
  cells: Readonly<Record<string, unknown>>,
  sheetRow: number,
): DateFormatFinding[] {
  const out: DateFormatFinding[] = [];
  // Канон п.93/45: рукописны только N (план) и Q (факт); производные графы
  // считаются формулами и числовой вид для них — норма, а не дефект.
  for (const col of ['N', 'Q'] as const) {
    const found = detectDateShownAsNumber(cells[col], col, sheetRow);
    if (found) out.push(found);
  }
  return out;
}
