export function humanizeActionFormula(formula) {
  if (typeof formula !== 'string' || !formula.startsWith('=')) throw new Error('ACTION_FORMULA');
  for (const [before, after] of Object.entries(ACTION_COPY)) {
    formula = formula.replaceAll('"' + before + '"', '"' + after + '"');
  }
  return formula;
}

