# ── расчёт ────────────────────────────────────────────────────────────────────

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    ok_pairs = 0
    fixed_pairs = 0
    rows = []
    for el, st, ang, sky, hor, ink, note in CELLS:
        need = 3.0 if 'норма 3' in note else 4.5
        sky2, cs, fs = fit(sky, ink, 4.5)
        hor2, ch, fh = fit(hor, ink, 4.5)
        fixed = fs or fh
        if fixed:
            fixed_pairs += 1
        else:
            ok_pairs += 1
        marks = []
        if fs:
            marks.append('небо ' + sky + '→' + sky2)
        if fh:
            marks.append('горизонт ' + hor + '→' + hor2)
        dob = '; '.join(marks) if marks else '—'
        rows.append('| %s | %s | %s | `%s` | `%s` | `%s` | %s | %s | %s | %s |' % (
            el, st, ang, sky2, hor2, ink, fmt(cs), fmt(ch),
            'да' if not fixed else 'добор', (note + ('; добор: ' + dob if fixed else '')) or '—'))

    with io.open(os.path.join(OUT_DIR, 'matrix.md'), 'w', encoding='utf-8') as f:
        f.write('| Элемент | Состояние | Угол | Небо | Горизонт | Подпись | К·небо | К·горизонт | Норма | Заметка |\n')
        f.write('|---|---|---|---|---|---|---|---|---|---|\n')
        f.write('\n'.join(rows) + '\n')

    tab_rows = []
    tabs_ok = 0
    tabs_fixed = 0
    for tid, label, sky, character in TABS:
        sky2, cs, fs = fit(sky, TAB_INK, 4.5)
        hor2, ch, fh = fit(TAB_HORIZON, TAB_INK, 4.5)
        if fs or fh:
            tabs_fixed += 1
        else:
            tabs_ok += 1
        tab_rows.append('| %s | `%s`%s | `%s` | `%s` | %s | %s | %s |' % (
            label, sky2, (' (затемнено с `%s`)' % sky) if fs else '', hor2, TAB_INK,
            fmt(cs), fmt(ch), character))

    with io.open(os.path.join(OUT_DIR, 'tabs.md'), 'w', encoding='utf-8') as f:
        f.write('| Вкладка | Небо | Горизонт | Подпись | К·небо | К·горизонт | Характер содержимого в этом небе |\n')
        f.write('|---|---|---|---|---|---|---|\n')
        f.write('\n'.join(tab_rows) + '\n')

    # контроль канона §20.1 — числа обязаны сойтись с посчитанными 29.08
    canon = [
        ('#1b170f', '#5b99f8', 6.26), ('#1b170f', '#9d8150', 4.84),
        ('#ffffff', '#426eb3', 5.11), ('#ffffff', '#675435', 7.25),
        ('#ffffff', '#5b99f8', 2.85), ('#ffffff', '#bfa161', 2.47),
    ]
    with io.open(os.path.join(OUT_DIR, 'canon-check.md'), 'w', encoding='utf-8') as f:
        for ink, bg, expect in canon:
            got = contrast(ink, bg)
            f.write('%s на %s: посчитано %s, канон %s — %s\n' % (
                ink, bg, fmt(got), fmt(expect), 'сходится' if abs(got - expect) < 0.03 else 'РАСХОЖДЕНИЕ'))

    print('cells=%d ok=%d fixed=%d' % (len(CELLS), ok_pairs, fixed_pairs))
    print('tabs=%d ok=%d fixed=%d' % (len(TABS), tabs_ok, tabs_fixed))
    print('out: %s' % OUT_DIR)


if __name__ == '__main__':
    main()
