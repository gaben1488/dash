def lum(hexs: str) -> float:
    hexs = hexs.lstrip('#')
    def chan(i):
        c = int(hexs[i:i + 2], 16) / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = chan(0), chan(2), chan(4)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def mix(c1: str, c2: str, t: float) -> str:
    c1, c2 = c1.lstrip('#'), c2.lstrip('#')
    out = ''
    for i in (0, 2, 4):
        v = round(int(c1[i:i + 2], 16) * (1 - t) + int(c2[i:i + 2], 16) * t)
        out += format(v, '02x')
    return '#' + out


def fit(end: str, ink: str, need: float):
    """Возвращает (итоговый цвет конца, контраст, добирали ли норму).
    Затемняем конец под светлую подпись, подсветляем под тёмную — шаг 2%."""
    c = contrast(end, ink)
    if c >= need:
        return end, c, False
    target = '#000000' if lum(ink) > lum(end) else '#ffffff'
    t, e = 0.0, end
    while c < need and t < 1.0:
        t += 0.02
        e = mix(end, target, t)
        c = contrast(e, ink)
    return e, c, True


def fmt(x: float) -> str:
    return ('%.2f' % x).replace('.', ',')


