export function selectRows(rows, filters = {}) {
  const q = (filters.search || '').trim().toLocaleLowerCase('ru');
  return rows.filter(
    (r) =>
      (filters.periods
        ? filters.periods.includes(`${r.year}-${r.month}`)
        : !filters.year || r.year === Number(filters.year)) &&
      (filters.depts ? filters.depts.includes(r.dept) : !filters.dept || r.dept === filters.dept) &&
      (!filters.org || r.org === filters.org) &&
      (!filters.month || r.month === Number(filters.month)) &&
      (!filters.method || r.method === filters.method) &&
      (!filters.budget || r.budget === filters.budget) &&
      (!q || [r.number, r.subject, r.org, r.procedure].join(' ').toLocaleLowerCase('ru').includes(q)) &&
      (!filters.attention || r.issue) &&
      (!filters.linked || r.procedure),
  );
}
export function summarize(rows) {
  return rows.reduce(
    (a, r) => ({
      count: a.count + 1,
      plan: a.plan + r.plan,
      fact: a.fact + (r.fact ?? 0),
      saving: a.saving + (r.ad ? r.saving : 0),
    }),
    { count: 0, plan: 0, fact: 0, saving: 0 },
  );
}
export function numberCollisions(rows) {
  const groups = new Map();
  for (const r of rows) {
    const key = r.dept + '|' + String(r.number).trim();
    if (!String(r.number).trim()) continue;
    groups.set(key, [...(groups.get(key) || []), r]);
  }
  return [...groups.values()].filter((g) => g.length > 1);
}
