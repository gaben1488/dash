import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import postcss from 'postcss';
const root = new URL('../', import.meta.url);
const gallery = fs.readFileSync(new URL('../zarya-vystavka.html', root), 'utf8');
const literal = gallery.match(/var СЕМЕЙСТВА = (\[[\s\S]*?\n  \]);/)[1];
const families = vm.runInNewContext(`(${literal})`, {}, {timeout:1000}).map(f=>({name:f.имя, description:f.идея, tabs:f.вкладки.map(v=>({name:v[0], image:v[1], top:v[2], bottom:v[3], ink:v[4]}))}));
fs.writeFileSync(new URL('src/source-shell/palettes.json', root), JSON.stringify(families,null,2)+'\n');
const css = fs.readFileSync(new URL('../../../../packages/web/src/index.css', root), 'utf8');
const tree = postcss.parse(css);
tree.walkComments(n=>n.remove());
tree.walkRules(r=>{ if (!/\.ob-/.test(r.selector)) r.remove(); });
tree.walkAtRules(a=>{if(!a.nodes || !a.nodes.length)a.remove();});
fs.writeFileSync(new URL('src/source-shell/organizations.css', root), '/* Extracted .ob-* rules from production index.css; adapt in consolidation.css. */\n'+tree.toString());
const store = fs.readFileSync(new URL('../../../../packages/web/src/store.ts',root),'utf8');
const filters = store.match(/export const PAGE_FILTERS[^=]*= (\{[\s\S]*?\n\});/)[1];
fs.writeFileSync(new URL('src/source-shell/page-filters.json',root),JSON.stringify(vm.runInNewContext(`(${filters})`,{}, {timeout:1000}),null,2)+'\n');
const evidence = {gallery:{path:'docs/superpowers/mockups/zarya-vystavka.html',sha256:crypto.createHash('sha256').update(gallery).digest('hex')}, organizations:{path:'packages/web/src/index.css',sha256:crypto.createHash('sha256').update(css).digest('hex')}, filters:{path:'packages/web/src/store.ts',sha256:crypto.createHash('sha256').update(store).digest('hex')}};
fs.writeFileSync(new URL('src/source-shell/consolidation-sources.json',root),JSON.stringify(evidence,null,2)+'\n');
console.log('Extracted 3 × 13 source pairs, production organization styles and page capabilities.');
